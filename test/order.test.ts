import assert from "node:assert/strict"
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { test } from "node:test"
import { orderPackage, JLCPCB_QUOTE } from "../src/dashboard/order.ts"
import { serveHub } from "../src/dashboard/server.ts"
import { zipEntries, zipStore } from "../src/tools/fab.ts"

// "Ready to order": one zip with what JLCPCB's PCBA upload asks for, plus the case for JLC3DP, from the latest settled
// revision only. Never an order: no upload, no account; the page opens JLCPCB's quote page.
const ID = "20261031-130000-ordrun"
const line = (seq: number, type: string, payload: object) => JSON.stringify({ seq, at: `2026-10-31T13:00:${String(seq).padStart(2, "0")}.000Z`, type, producerId: "x", payload }) + "\n"
const GERBERS = zipStore([{ name: "board-F_Cu.gtl", data: Buffer.from("G04 copper*") }])

function run(o: { noHardware?: boolean; settled?: boolean | null; fabRev?: number; fab?: boolean; enclosure?: boolean; after?: string; drcErrors?: number | null; review?: "pass" | "fail" | null } = {}): string {
	const root = mkdtempSync(join(tmpdir(), "bringup-order-"))
	const dir = join(root, ID)
	mkdirSync(join(dir, "fab"), { recursive: true })
	let trace = line(0, "run.started", { review: true, noHardware: o.noHardware ?? false, bench: false, stay: true })
	trace += line(1, "contract.changed", { field: "outline", version: 2, revision: 8, by: "architect" })
	// All green by default: the board built with a clean DRC, the brief review passed.
	if (o.drcErrors !== null) trace += line(10, "artifact.ready", { kind: "board", revision: 8, ...(o.drcErrors === undefined ? { drc: { errors: 0, warnings: 92, unconnected: 0 } } : { drc: { errors: o.drcErrors, warnings: 0, unconnected: 0 } }) })
	if (o.review !== null) trace += line(11, "review.completed", { revision: 8, verdict: o.review ?? "pass", findings: [] })
	if (o.settled !== null) trace += line(2, "design.settled", { settled: o.settled ?? true, revision: 8 })
	// A change after the settle: board inputs (outline) or not (behavior, which leaves the gerbers current).
	if (o.after) trace += line(3, "contract.changed", { field: o.after, version: 3, revision: 9, by: "architect" })
	writeFileSync(join(dir, "trace.jsonl"), trace)
	if (o.fab !== false) {
		writeFileSync(join(dir, "fab/gerbers.zip"), GERBERS)
		writeFileSync(join(dir, "fab/bom.csv"), "Comment,Designator,Footprint,LCSC Part #\n")
		writeFileSync(join(dir, "fab/cpl.csv"), "Designator,Mid X,Mid Y,Layer,Rotation\n")
		writeFileSync(join(dir, "fab/README.txt"), `Bringup fab package: board revision ${o.fabRev ?? 8}\n\nCHECKLIST: known unverified items.\n  [ ] CPL rotations are KiCad's.\n\nContract revision ${o.fabRev ?? 8}. Generated by Bringup.\n`)
	}
	if (o.enclosure !== false) {
		for (const r of [4, 8]) {
			mkdirSync(join(dir, `enclosure/rev-${r}`), { recursive: true })
			writeFileSync(join(dir, `enclosure/rev-${r}/case.stl`), `solid case-${r}`)
			writeFileSync(join(dir, `enclosure/rev-${r}/lid.stl`), `solid lid-${r}`)
		}
	}
	return dir
}

test("a settled run with real hardware: gerbers, BOM, CPL, the case and lid STLs and a README, in one zip", () => {
	const p = orderPackage(run())
	assert.equal(p.ok, true)
	if (!p.ok) return
	assert.equal(p.revision, 8)
	assert.equal(p.name, `bringup-${ID}-rev8-ready-to-order.zip`)
	const files = new Map(zipEntries(p.zip).map((e) => [e.name, e.data]))
	assert.deepEqual([...files.keys()], ["README.txt", "gerbers.zip", "bom.csv", "cpl.csv", "case.stl", "lid.stl"])
	assert.deepEqual(files.get("gerbers.zip"), GERBERS, "the gerbers go in unchanged")
	assert.equal(files.get("case.stl")!.toString(), "solid case-8", "the case from the settled revision, not an older one")
	const readme = files.get("README.txt")!.toString()
	assert.match(readme, /Ready to order/)
	assert.match(readme, new RegExp(JLCPCB_QUOTE.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")))
	assert.match(readme, /jlc3dp/i)
	assert.match(readme, /rev 8/)
	assert.match(readme, /CPL rotations are KiCad's/, "the fab checklist comes along")
	assert.match(readme, /nothing was uploaded/i)
	assert.doesNotMatch(readme, /\bordered\b/i)
})

test("refusals say why, so the button stays hidden until everything is green: settled, DRC clean, review passed, fab current", () => {
	const cases: [Parameters<typeof run>[0], RegExp][] = [
		[{ settled: null }, /not settled yet/],
		[{ settled: false }, /not consistent/],
		[{ noHardware: true }, /hardware was stubbed/],
		[{ fab: false }, /no fab package/],
		[{ fabRev: 7 }, /rev 7.*rev 8/],
		[{ after: "outline" }, /a change is in flight/],
		[{ drcErrors: 3 }, /DRC.*3 errors/],
		[{ drcErrors: null }, /board has not been built/],
		[{ review: "fail" }, /review/],
		[{ review: null }, /review/],
	]
	for (const [o, why] of cases) {
		const p = orderPackage(run(o))
		assert.equal(p.ok, false)
		if (!p.ok) assert.match(p.reason, why)
	}
	// A firmware-only change that settled keeps the board's fab package current (gerbers from rev 8, design at rev 9).
	const fw = run({ after: "behavior" })
	writeFileSync(join(fw, "trace.jsonl"), readFileSync(join(fw, "trace.jsonl"), "utf8") + line(4, "design.settled", { settled: true, revision: 9 }))
	assert.equal(orderPackage(fw).ok, true)
	// No enclosure is not a refusal: the board can be ordered; the README says the case is missing.
	const p = orderPackage(run({ enclosure: false }))
	assert.equal(p.ok, true)
	if (p.ok) assert.match(zipEntries(p.zip).find((e) => e.name === "README.txt")!.data.toString(), /no case STL/)
})

test("the hub: /ready-to-order/check says whether, /ready-to-order serves the zip or refuses with 409 and the reason", async () => {
	for (const [o, ok] of [[{}, true], [{ noHardware: true }, false]] as const) {
		const dir = run(o)
		const hub = await serveHub({ outRoot: join(dir, ".."), port: 0 })
		try {
			const check = (await (await fetch(`${hub.url}/api/runs/${ID}/ready-to-order/check`)).json()) as { ok: boolean; reason?: string; revision?: number }
			assert.equal(check.ok, ok)
			const res = await fetch(`${hub.url}/api/runs/${ID}/ready-to-order`)
			if (ok) {
				assert.equal(res.status, 200)
				assert.equal(res.headers.get("content-type"), "application/zip")
				assert.match(res.headers.get("content-disposition") ?? "", /attachment; filename="bringup-.*-rev8-ready-to-order\.zip"/)
				assert.equal(zipEntries(Buffer.from(await res.arrayBuffer())).length, 6)
			} else {
				assert.equal(res.status, 409)
				assert.match(((await res.json()) as { error: string }).error, /hardware was stubbed/)
				assert.match(check.reason ?? "", /hardware was stubbed/)
			}
			assert.equal((await fetch(`${hub.url}/api/runs/nope/ready-to-order/check`)).status, 404)
		} finally {
			await hub.close()
		}
	}
})
