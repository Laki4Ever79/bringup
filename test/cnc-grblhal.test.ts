// The CNC's grblHAL configuration (gap 11, src/cnc/grblhal.ts): the board map from the pin map, the settings from the
// machine, the no-restart requirement held by the settings, and a pin missing from the map reported to the architect.
import { test } from "node:test"
import assert from "node:assert/strict"
import { mkdtempSync, readFileSync, rmSync } from "node:fs"
import { join, resolve } from "node:path"
import { tmpdir } from "node:os"
import { CNC_DESIGN, CNC_MACHINE, CNC_TARGETS } from "../src/inference/scripts.ts"
import { grblhalMap, grblhalPins, grblhalSettings } from "../src/cnc/grblhal.ts"
import { cncChecks } from "../src/cnc/checks.ts"
import { defaultCheckCatalog } from "../src/mechanics/checks.ts"
import { prepareFirmware } from "../src/tools/firmware.ts"
import { fixtureContract } from "./fixture.ts"

const cnc = () => {
	const b = fixtureContract()
	return { ...b, values: { ...b.values, ...CNC_DESIGN, cncTargets: CNC_TARGETS, cnc: CNC_MACHINE } } as typeof b
}

test("the board map names every pin from the contract: STEP/DIR per motor (Y2 as M3), the shared enable, limits, spindle PWM, the e-stop as RESET", () => {
	const s = cnc()
	assert.deepEqual(grblhalPins(s).missing, [])
	const map = grblhalMap(s)
	for (const line of ["#define X_STEP_PORT GPIOA", "#define X_STEP_PIN 0", "#define Z_DIRECTION_PORT GPIOB", "#define Z_DIRECTION_PIN 10", "#define M3_STEP_PIN 6", "#define STEPPERS_ENABLE_PIN 2", "#define X_LIMIT_PIN 13", "#define SPINDLE_PWM_PIN 8", "#define RESET_PORT GPIOB", "#define RESET_PIN 12", "#define TRINAMIC_UART_ENABLE 1", "#define STEP_OUTMODE GPIO_BITBAND"])
		assert.ok(map.includes(line), line)
	for (const line of ["#define SERIAL_PORT 1", "#define TRINAMIC_STREAM 0"]) assert.ok(map.includes(line), line)
})

test("the settings come from the machine, and hold the no-restart requirement (homing on, the boot alarm forced)", () => {
	const set = new Map(grblhalSettings(cnc(), defaultCheckCatalog()!.mech)!.map((x) => [x.id, x.value]))
	assert.equal(set.get(100), 400, "200 steps/rev × 16 microsteps / 8 mm lead")
	assert.deepEqual([set.get(130), set.get(131), set.get(132)], [300, 200, 50])
	assert.equal(set.get(110), CNC_TARGETS.rapidMmMin)
	assert.equal(set.get(30), 20000)
	// Releasing the e-stop must not restart anything (lead-2, gap 7): grblHAL boots into alarm until reset and homing.
	assert.equal(set.get(22), 1)
	assert.equal(set.get(64), 1)
	assert.equal(set.get(21), 1, "hard limits on")
})

test("a signal the map needs, missing from the pins, wakes the architect; the firmware folder carries the map and settings", async () => {
	const s = cnc()
	const without = { ...s.values, pins: s.values.pins!.filter((p) => p.signal !== "SPINDLE_PWM") }
	assert.match(cncChecks(without, null).map((v) => v.message).join("\n"), /grblHAL's board map needs a GPIO for SPINDLE_PWM/)
	assert.ok(!cncChecks(s.values, null).some((v) => /grblHAL's board map/.test(v.message)))
	const dir = mkdtempSync(join(tmpdir(), "grblhal-"))
	try {
		await prepareFirmware(resolve(import.meta.dirname, ".."), dir, s)
		assert.match(readFileSync(join(dir, "grblhal/my_machine_map.h"), "utf8"), /^\/\/ Generated by Bringup/)
		assert.match(readFileSync(join(dir, "grblhal/settings.txt"), "utf8"), /^\$64=1 ;/m)
		assert.match(readFileSync(join(dir, "grblhal/README.txt"), "utf8"), /BOARD_MY_MACHINE/)
	} finally {
		rmSync(dir, { recursive: true, force: true })
	}
})
