import { test } from "node:test"
import assert from "node:assert/strict"
import { appendFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { serveDashboard } from "../src/dashboard/server.ts"
import { driftStatusLines, type DriftFile } from "../src/runner/drift.ts"
import { main } from "../src/main.ts"
import { ROOT, runDesign } from "../src/run.ts"
import { detectEnvironment } from "../src/tools/env.ts"
import { tempDir, waitFor } from "./helpers.ts"

const trace = (out: string) => readFileSync(join(out, "trace.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l))
const drift = (out: string): DriftFile => JSON.parse(readFileSync(join(out, "drift.json"), "utf8"))
const pinsFiles = (out: string) =>
	readdirSync(join(out, "firmware"))
		.map((d) => Number(d.slice(4)))
		.filter((r) => existsSync(join(out, "firmware", `rev-${r}`, "include/pins.h")))
		.sort((a, b) => a - b)
const pinsAt = (out: string, rev: number) => join(out, "firmware", `rev-${rev}`, "include/pins.h")
const act = (out: string, driftId: string, action: "revert" | "adopt") => appendFileSync(join(out, "drift-actions.jsonl"), JSON.stringify({ at: new Date().toISOString(), driftId, action }) + "\n")

async function stayRun() {
	const out = tempDir()
	const env = await detectEnvironment(ROOT)
	let end: () => void = () => {}
	const until = new Promise<void>((r) => (end = r))
	const run = runDesign({ brief: readFileSync(join(ROOT, "briefs/logger.md"), "utf8"), mock: true, noHardware: true, outDir: out, env, stay: { until } })
	await waitFor(() => existsSync(join(out, "trace.jsonl")) && trace(out).some((e) => e.type === "design.settled"), 30_000)
	return { out, run, end }
}

test("drift you can follow: an open drift reverts to the generated bytes, a stale pin move adopts into a request, mapped saves list as adopted", { timeout: 90_000 }, async () => {
	const { out, run, end } = await stayRun()
	try {
		const revs = pinsFiles(out)
		const newest = pinsAt(out, revs.at(-1)!)
		const generated = readFileSync(newest, "utf8")

		// 1. Not in the contract: open, not adoptable; revert puts the generated bytes back.
		writeFileSync(newest, generated + "#define DEBUG_LOG 1\n")
		await waitFor(() => existsSync(join(out, "drift.json")) && drift(out).entries.length === 1, 10_000)
		const open = drift(out).entries[0]
		assert.equal(drift(out).live, true)
		assert.deepEqual({ ...open, savedAt: "" }, {
			id: "drift-1",
			path: `firmware/rev-${revs.at(-1)}/include/pins.h`,
			savedAt: "",
			savedRevision: revs.at(-1),
			designRevision: revs.at(-1),
			kind: "not-in-contract",
			items: ["+ #define DEBUG_LOG 1"],
			status: "open",
			adoptable: false,
			note: "this edit isn't in the design contract; the next rebuild will overwrite it",
		})
		act(out, "drift-1", "revert")
		await waitFor(() => drift(out).entries[0].status === "reverted", 10_000)
		assert.equal(readFileSync(newest, "utf8"), generated, "the generated bytes are back")
		assert.ok(trace(out).some((e) => e.type === "drift.resolved" && e.payload.id === "drift-1" && e.payload.status === "reverted"))
		await new Promise((r) => setTimeout(r, 800))
		assert.equal(drift(out).entries.length, 1, "the revert's own write is not a new drift")

		// 2. Stale but mapped: an older pins.h with a pin move is open and adoptable; adopt sends it as the engineer's request.
		const old = pinsAt(out, revs[0])
		writeFileSync(old, readFileSync(old, "utf8").replace(/^#define PIN_I2C_SCL \d+$/m, "#define PIN_I2C_SCL 3"))
		await waitFor(() => drift(out).entries.length === 2, 10_000)
		const stale = drift(out).entries[1]
		assert.deepEqual([stale.kind, stale.status, stale.adoptable, stale.items], ["stale", "open", true, ["I2C_SCL GPIO9 → GPIO3"]])
		act(out, stale.id, "adopt")
		await waitFor(() => drift(out).entries[1].status === "adopted", 10_000)
		assert.equal(drift(out).entries[1].requestId, "req-1")
		// drift.json says adopted as soon as the request is queued; the trace gets change.requested a moment later.
		await waitFor(() => trace(out).some((e) => e.type === "change.requested"), 10_000)
		const req = trace(out).find((e) => e.type === "change.requested")!
		assert.equal(req.payload.text, "edited pins.h: I2C_SCL GPIO9 → GPIO3")
		assert.equal(req.payload.source.path, `firmware/rev-${revs[0]}/include/pins.h`)

		// 3. A save that maps on the newest file becomes a request at once and is listed as adopted → req-N.
		await waitFor(() => trace(out).filter((e) => e.type === "design.settled").length >= 2, 20_000)
		const latest = pinsFiles(out).at(-1)!
		writeFileSync(pinsAt(out, latest), readFileSync(pinsAt(out, latest), "utf8").replace(/^#define PIN_I2C_SDA \d+$/m, "#define PIN_I2C_SDA 4"))
		await waitFor(() => drift(out).entries.length === 3, 10_000)
		const auto = drift(out).entries[2]
		assert.deepEqual([auto.kind, auto.status, auto.requestId, auto.items], ["adopted", "adopted", "req-2", ["I2C_SDA GPIO8 → GPIO4"]])
	} finally {
		end()
		await run
	}
	assert.equal(drift(out).live, false, "not live after run.ended")
})

function fakeRun(live: boolean): string {
	const dir = join(tempDir(), "run-1")
	mkdirSync(dir, { recursive: true })
	writeFileSync(join(dir, "trace.jsonl"), "")
	const entry = (id: string, kind: string, adoptable: boolean, status = "open") => ({ id, path: "firmware/rev-7/include/pins.h", savedAt: "2026-10-31T12:00:00.000Z", savedRevision: 7, designRevision: 7, kind, items: ["x"], status, adoptable })
	writeFileSync(join(dir, "drift.json"), JSON.stringify({ live, entries: [entry("drift-1", "not-in-contract", false), entry("drift-2", "stale", true), entry("drift-3", "adopted", true, "adopted")] }))
	return dir
}

test("the hub queues revert and adopt for a live run, and refuses what can't be done", async () => {
	const dir = fakeRun(true)
	const dash = await serveDashboard(dir, 0)
	try {
		const post = (path: string) => fetch(`${dash.url}/api/runs/run-1/drift/${path}`, { method: "POST", headers: { "content-type": "application/json" }, body: "{}" })
		const adoptUnmappable = await post("drift-1/adopt")
		assert.equal(adoptUnmappable.status, 409)
		assert.match(((await adoptUnmappable.json()) as { error: string }).error, /isn't in the design contract: nothing to adopt/)
		assert.equal((await post("drift-3/revert")).status, 409, "already adopted")
		assert.equal((await post("drift-9/revert")).status, 404)
		const revert = await post("drift-1/revert")
		assert.equal(revert.status, 202)
		assert.deepEqual((await revert.json()) as object, { queued: true, id: "drift-1", action: "revert" })
		assert.equal((await post("drift-2/adopt")).status, 202)
		const queued = readFileSync(join(dir, "drift-actions.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l))
		assert.deepEqual(queued.map((q) => [q.driftId, q.action]), [["drift-1", "revert"], ["drift-2", "adopt"]])
		assert.deepEqual(((await (await fetch(`${dash.url}/api/runs/run-1/drift`)).json()) as { entries: unknown[] }).entries.length, 3)
	} finally {
		await dash.close()
	}
	const ended = fakeRun(false)
	const dash2 = await serveDashboard(ended, 0)
	try {
		const res = await fetch(`${dash2.url}/api/runs/run-1/drift/drift-1/revert`, { method: "POST", headers: { "content-type": "application/json" }, body: "{}" })
		assert.equal(res.status, 409)
		assert.match(((await res.json()) as { error: string }).error, /not running/)
	} finally {
		await dash2.close()
	}
})

test("bringup status lists drifted files like git status", async () => {
	const d: DriftFile = {
		live: true,
		entries: [
			{ id: "drift-1", path: "firmware/rev-7/include/pins.h", savedAt: "", savedRevision: 7, designRevision: 7, kind: "not-in-contract", items: ["+ #define DEBUG_LOG 1"], status: "open", adoptable: false },
			{ id: "drift-2", path: "firmware/rev-6/include/pins.h", savedAt: "", savedRevision: 6, designRevision: 8, kind: "stale", items: ["I2C_SCL GPIO9 → GPIO3"], status: "adopted", adoptable: true, requestId: "req-1" },
			{ id: "drift-3", path: "board/rev-7/dist/board/kicad/board.kicad_pcb", savedAt: "", savedRevision: 7, designRevision: 7, kind: "not-in-contract", items: ["board edits outside the outline"], status: "reverted", adoptable: false },
		],
	}
	assert.deepEqual(driftStatusLines(d, "out/run-1"), [
		"Drift in out/run-1 (run is live):",
		"  open      drift-1  firmware/rev-7/include/pins.h  (not in the contract, saved at rev 7)",
		"              + #define DEBUG_LOG 1",
		"  adopted   drift-2  firmware/rev-6/include/pins.h  → req-1 (stale, saved at rev 6, design at rev 8)",
		"              I2C_SCL GPIO9 → GPIO3",
		"  reverted  drift-3  board/rev-7/dist/board/kicad/board.kicad_pcb  (not in the contract, saved at rev 7)",
		"              board edits outside the outline",
	])
	assert.deepEqual(driftStatusLines({ live: false, entries: [] }, "out/run-2"), ["Drift in out/run-2 (run has ended): nothing drifted."])

	const dir = fakeRun(true)
	const printed: string[] = []
	const log = console.log
	console.log = (s: string) => void printed.push(s)
	try {
		assert.equal(await main(["status", dir]), 0)
	} finally {
		console.log = log
	}
	assert.match(printed.join("\n"), /^Drift in .*run-1 \(run is live\):/)
})
