import type { ChassisSpec } from "../tools/chassis.ts"
import { bodyOf, driveLimits, pivotX } from "./urdf.ts"

// Nav2 for the robot, from its design (ROS step 2, docs/ros.md): the footprint is the robot's own outline seen from above
// (the plate and the wheels, which stick out past a narrow plate), the controller's speed, turn rate and acceleration
// are the diff-drive controller's (the brief's speed, the drive's acceleration), the costmaps read the robot's own range
// sensor, and a competition robot gets its table as the map (catalog/rules/<id>.json limits.table, cited).
//
// The robot has no lidar, so nothing localizes it against the map: map -> odom is fixed at the start pose (launch
// arguments start_x, start_y, start_yaw), and the robot's position in the map is its odometry from there. On a table
// that is how a competition robot runs (wheel encoders plus a gyro); its drift is the odometry's (docs/ros.md).

const mm = (v: number) => v / 1000
const f = (v: number) => Number(v.toFixed(4)).toString()

export interface Arena {
	// The playing area's size (x along its length) and the walls around it, from the rules.
	sizeMm: [number, number]
	wallMm: number
	source: string
}

// The footprint in base_footprint's frame (x forward from the pivot, y left), m: the rectangle around the plate and the
// wheels. The caster, the boards and the beacon mast stand on the plate, inside it.
export function footprint(spec: ChassisSpec): [number, number][] {
	const b = bodyOf(spec), d = spec.drive, p = spec.plate
	const px = pivotX(spec)
	const wheelXs = [b.axleX - b.r, b.axleX + b.r, ...(b.skid ? [b.casterX - b.r, b.casterX + b.r] : [])]
	const front = Math.max(mm(p.lengthMm) / 2, ...wheelXs) - px
	const back = Math.min(-mm(p.lengthMm) / 2, ...wheelXs) - px
	const half = Math.max(mm(p.widthMm) / 2, mm(d.trackMm) / 2 + mm(d.wheelWidthMm) / 2)
	return [[front, half], [front, -half], [back, -half], [back, half]]
}

const radius = (pts: [number, number][]) => Math.max(...pts.map(([x, y]) => Math.hypot(x, y)))

// The table as an occupancy map: free inside, the walls occupied around it; 1 cm cells, origin at the wall's outer corner.
export function arenaMap(a: Arena, resolutionM = 0.01): { pgm: Buffer; yaml: string } {
	const w = Math.round(mm(a.sizeMm[0] + 2 * a.wallMm) / resolutionM), h = Math.round(mm(a.sizeMm[1] + 2 * a.wallMm) / resolutionM)
	const wall = Math.max(1, Math.round(mm(a.wallMm) / resolutionM))
	const header = Buffer.from(`P5\n# ${a.source}\n${w} ${h}\n255\n`)
	const px = Buffer.alloc(w * h)
	for (let r = 0; r < h; r++) for (let c = 0; c < w; c++) px[r * w + c] = r < wall || r >= h - wall || c < wall || c >= w - wall ? 0 : 254
	const yaml = `# Generated by Bringup from the competition's rules: ${a.source}
image: arena.pgm
mode: trinary
resolution: ${resolutionM}
origin: [${f(-mm(a.wallMm))}, ${f(-mm(a.wallMm))}, 0.0]  # the table's corner at (0, 0); its walls outside it
negate: 0
occupied_thresh: 0.65
free_thresh: 0.25
`
	return { pgm: Buffer.concat([header, px]), yaml }
}

