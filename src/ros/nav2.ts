// The robot's default start in the map: on a table, 0.5 m from its short side on the middle row, facing along it.
export const defaultStart = (arena?: Arena): [number, number] => (arena ? [0.5, mm(arena.sizeMm[1]) / 2] : [0, 0])

// The navigation launch file: Nav2's servers under one lifecycle manager, the fixed map -> odom at the start pose and,
// with a table, its map. The robot's own launch (bringup.launch.py nav:=true) includes it.
export function navigationLaunch(pkg: string, opts: { arena?: Arena; revision?: number } = {}): string {
	const stamp = opts.revision !== undefined ? ` (design revision ${opts.revision})` : ""
	const nodes = [...(opts.arena ? ["map_server"] : []), "controller_server", "planner_server", "behavior_server", "bt_navigator"]
	const [sx, sy] = defaultStart(opts.arena)
	return `# Generated by Bringup from the design contract${stamp} (src/ros/nav2.ts). Do not edit: change the design instead.
import os
from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node


def generate_launch_description():
    share = get_package_share_directory("${pkg}")
    params = os.path.join(share, "config", "nav2.yaml")
    start = [LaunchConfiguration(n) for n in ("start_x", "start_y", "start_yaw")]
    cmd_vel = [("cmd_vel", "/cmd_vel")]
    return LaunchDescription([
        DeclareLaunchArgument("start_x", default_value="${f(sx)}", description="the robot's start on the ${opts.arena ? "table" : "floor"}, m (map frame)"),
        DeclareLaunchArgument("start_y", default_value="${f(sy)}"),
        DeclareLaunchArgument("start_yaw", default_value="0.0", description="rad"),
        # No lidar: the robot's place in the map is its odometry from the start pose.
        Node(package="tf2_ros", executable="static_transform_publisher", arguments=["--x", start[0], "--y", start[1], "--yaw", start[2], "--frame-id", "map", "--child-frame-id", "odom"]),${opts.arena ? `
        Node(package="nav2_map_server", executable="map_server", name="map_server", parameters=[params, {"yaml_filename": os.path.join(share, "maps", "arena.yaml")}]),` : ""}
        Node(package="nav2_controller", executable="controller_server", parameters=[params], remappings=cmd_vel),
        Node(package="nav2_planner", executable="planner_server", name="planner_server", parameters=[params]),
        Node(package="nav2_behaviors", executable="behavior_server", name="behavior_server", parameters=[params], remappings=cmd_vel),
        Node(package="nav2_bt_navigator", executable="bt_navigator", name="bt_navigator", parameters=[params]),
        Node(package="nav2_lifecycle_manager", executable="lifecycle_manager", name="lifecycle_manager_navigation",
             parameters=[{"autostart": True, "node_names": ${JSON.stringify(nodes)}}]),
    ])
`
}

// The Nav2 demo's goal, in the map: from the default start, 0.7 m ahead and 0.3 m to the left. Inside the simulated room
// (py/mech/drive.py: its walls 1.5 m ahead, 1 m behind, 1 m to each side, which with the start at the table's middle row
// lie on the table's side walls), clear of the front wall by more than the robot.
export const NAV_GOAL_OFFSET: [number, number] = [0.7, 0.3]

// test/nav_goal.py: sends one NavigateToPose goal and judges it against the design: Nav2 reports success, the odometry
// ends within the goal checker's tolerance, in time for the distance at the brief's speed (x3, plus 15 s for the turns
// and the planner's first plan: an ESTIMATE). Writes JSON like the acceptance test's, and the end pose for the caller to
// compare with the simulation's own.
export function navGoalScript(spec: ChassisSpec, start: [number, number], goal: [number, number]): string {
	const { vmax } = driveLimits(spec)
	const dist = Math.hypot(goal[0] - start[0], goal[1] - start[1])
	const budget = (3 * dist) / vmax + 15
	return `#!/usr/bin/env python3
# Generated by Bringup from the design contract (src/ros/nav2.ts). One Nav2 goal, judged against the design.
import json, math, sys, time
import rclpy
from rclpy.action import ActionClient
from rclpy.node import Node
from nav_msgs.msg import Odometry
from nav2_msgs.action import NavigateToPose
from action_msgs.msg import GoalStatus

START = (${f(start[0])}, ${f(start[1])})
GOAL = (${f(goal[0])}, ${f(goal[1])})
TOL = 0.05  # the goal checker's 3 cm, plus 2 cm for the odometry's last tick: an ESTIMATE
BUDGET_S = ${f(budget)}  # 3x the distance at the brief's ${f(vmax)} m/s, plus 15 s (an ESTIMATE)


class Goal(Node):
    def __init__(self):
        super().__init__("bringup_nav_goal")
        self.odom = None
        self.create_subscription(Odometry, "/diff_drive_controller/odom", self.on_odom, 10)
        self.client = ActionClient(self, NavigateToPose, "/navigate_to_pose")

    def on_odom(self, m):
        self.odom = (m.pose.pose.position.x, m.pose.pose.position.y)


def main(out):
    rclpy.init()
    n = Goal()
    checks = []
    def check(name, ok, measured, expected):
        checks.append({"name": name, "pass": bool(ok), "measured": measured, "expected": expected})
    up = n.client.wait_for_server(timeout_sec=120.0)
    check("Nav2 is up (navigate_to_pose)", up, up, True)
    status, took, end = None, None, None
    if up:
        g = NavigateToPose.Goal()
        g.pose.header.frame_id = "map"
        g.pose.header.stamp = n.get_clock().now().to_msg()
        g.pose.pose.position.x, g.pose.pose.position.y = GOAL
        g.pose.pose.orientation.w = 1.0
        t0 = time.monotonic()
        fut = n.client.send_goal_async(g)
        rclpy.spin_until_future_complete(n, fut, timeout_sec=30.0)
        handle = fut.result()
        if handle is not None and handle.accepted:
            res = handle.get_result_async()
            rclpy.spin_until_future_complete(n, res, timeout_sec=BUDGET_S + 30.0)
            took = time.monotonic() - t0
            status = res.result().status if res.done() else None
            if not res.done():
                handle.cancel_goal_async()
        for _ in range(20):
            rclpy.spin_once(n, timeout_sec=0.05)
        if n.odom is not None:
            end = (START[0] + n.odom[0], START[1] + n.odom[1])  # map -> odom is the start pose (yaw 0)
    check("Nav2 reports the goal reached", status == GoalStatus.STATUS_SUCCEEDED, status, GoalStatus.STATUS_SUCCEEDED)
    err = math.hypot(end[0] - GOAL[0], end[1] - GOAL[1]) if end else None
    check("the odometry ends at the goal", err is not None and err <= TOL, None if err is None else round(err, 4), f"<= {TOL} m")
    check("in time for the distance at the brief's speed", took is not None and took <= BUDGET_S, None if took is None else round(took, 1), f"<= {BUDGET_S} s")
    json.dump({"pass": all(c["pass"] for c in checks), "checks": checks, "start": START, "goal": GOAL, "end": end}, open(out, "w"), indent=1)
    rclpy.shutdown()
    return 0 if all(c["pass"] for c in checks) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
`
}
