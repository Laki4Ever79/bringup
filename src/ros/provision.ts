import { spawnSync } from "node:child_process"
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import type { ContractSnapshot } from "../contract/types.ts"

// The robot's computer, set up from its design (ROS step 2, docs/ros.md): a Raspberry Pi 5 flashed with Ubuntu Server
// 24.04 boots once, installs ROS 2 Jazzy and what the robot's packages need, builds its colcon workspace, and from then
// on starts the robot (and Nav2) at every boot. Everything goes in one cloud-init user-data file that replaces the one
// on the card's system-boot partition: no keyboard, no screen, no typing on the Pi.

// The USB serial device the robot's board shows the Pi, from its parts: a USB-UART bridge's, else the MCU's own USB.
// udev names it /dev/bringup, so the port doesn't move when another USB device enumerates first.
const USB_IDS: { match: RegExp; vid: string; pid: string; what: string; source: string }[] = [
	{ match: /^CP2102/i, vid: "10c4", pid: "ea60", what: "Silicon Labs CP210x", source: "Silicon Labs AN571 (CP210x default VID 10C4, PID EA60)" },
	{ match: /^CH340/i, vid: "1a86", pid: "7523", what: "WCH CH340", source: "WCH CH340 datasheet (VID 1A86, PID 7523)" },
	{ match: /^ESP32-(S3|C3|C6|H2)/i, vid: "303a", pid: "1001", what: "Espressif USB Serial/JTAG", source: "ESP-IDF, USB Serial/JTAG Controller: 'VID 0x303A, PID 0x1001'" },
	{ match: /^STM32/i, vid: "0483", pid: "5740", what: "ST USB CDC (Virtual COM Port)", source: "ST USB device library CDC example (VID 0x0483, PID 0x5740)" },
]

export function robotUsbId(contract: ContractSnapshot | undefined): (typeof USB_IDS)[number] | null {
	const parts = ((contract?.values.parts ?? []) as { role?: string; mpn: string }[])
	const bridge = parts.find((p) => /usb-uart|usb-serial/.test(p.role ?? "")) ?? parts.find((p) => /^(CP2102|CH340)/i.test(p.mpn))
	const mcu = parts.find((p) => p.role === "mcu")
	for (const p of [bridge, mcu]) {
		const hit = p && USB_IDS.find((u) => u.match.test(p.mpn))
		if (hit) return hit
	}
	return null
}

// The apt packages the workspace's own package.xml files depend on (Jazzy's ros-jazzy-<name>), less the workspace's own.
export function aptPackages(wsSrc: string): string[] {
	const own = new Set<string>(), deps = new Set<string>()
	for (const d of readdirSync(wsSrc)) {
		const xml = join(wsSrc, d, "package.xml")
		if (!existsSync(xml)) continue
		const t = readFileSync(xml, "utf8")
		own.add(t.match(/<name>([^<]+)<\/name>/)![1])
		for (const m of t.matchAll(/<(?:exec_|build_)?depend>([^<]+)<\/(?:exec_|build_)?depend>/g)) deps.add(m[1])
	}
	return [...deps].filter((d) => !own.has(d)).sort().map((d) => `ros-jazzy-${d.replace(/_/g, "-")}`)
}

export interface ProvisionOpts {
	hostname?: string
	sshKey?: string // a public key line; without one, the password "robot" that must be changed at first login
	nav?: boolean // start Nav2 with the robot (default true)
	wifi?: { ssid: string; password: string }
	domainId?: number
	revision?: number
}

export function provisionFiles(wsDir: string, pkg: string, contract: ContractSnapshot | undefined, o: ProvisionOpts = {}): Record<string, string> {
	const tar = spawnSync("tar", ["czf", "-", "--exclude=build", "--exclude=install", "--exclude=log", "-C", wsDir, "src"], { maxBuffer: 64 << 20 })
	if (tar.status !== 0) throw new Error(`tar of ${wsDir} failed: ${tar.stderr}`)
	const host = o.hostname ?? "bringup-robot"
	const nav = o.nav ?? true
	const usb = robotUsbId(contract)
	const port = usb ? "/dev/bringup" : "/dev/ttyACM0"
	const stamp = o.revision !== undefined ? ` (design revision ${o.revision})` : ""
	const pkgs = [...aptPackages(join(wsDir, "src")), "ros-jazzy-ros-base", "ros-dev-tools"].sort()
	const indent = (s: string, n: number) => s.split("\n").map((l) => (l ? " ".repeat(n) + l : l)).join("\n")
	const service = `[Unit]
Description=The robot (Bringup${stamp}): ros2_control, its bridge to the firmware${nav ? ", Nav2" : ""}
Wants=network-online.target
After=network-online.target

[Service]
User=robot
Environment=ROS_DOMAIN_ID=${o.domainId ?? 0}
ExecStart=/bin/bash -c 'source /opt/ros/jazzy/setup.bash && source /home/robot/robot_ws/install/setup.bash && exec ros2 launch ${pkg} bringup.launch.py hardware:=bringup port:=${port} nav:=${nav}'
Restart=always
RestartSec=3

[Install]
WantedBy=multi-user.target
`
	// The ROS apt source the ROS 2 Jazzy install guide uses since 2025 (ros2-apt-source: its key renews itself).
	const firstBoot = `#!/bin/bash
# Generated by Bringup${stamp}. First boot: ROS 2 Jazzy, the robot's dependencies, its workspace, its service.
set -euxo pipefail
export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y curl ca-certificates software-properties-common
add-apt-repository -y universe
V=$(curl -fsSL https://api.github.com/repos/ros-infrastructure/ros-apt-source/releases/latest | grep -F '"tag_name"' | awk -F'"' '{print $4}')
curl -fsSL -o /tmp/ros2-apt-source.deb "https://github.com/ros-infrastructure/ros-apt-source/releases/download/$V/ros2-apt-source_$V.$(. /etc/os-release && echo $VERSION_CODENAME)_all.deb"
dpkg -i /tmp/ros2-apt-source.deb
apt-get update
apt-get install -y ${pkgs.join(" ")}
install -d -o robot -g robot /home/robot/robot_ws
tar xzf /opt/bringup/robot_ws.tar.gz -C /home/robot/robot_ws
chown -R robot:robot /home/robot/robot_ws
sudo -u robot bash -c 'source /opt/ros/jazzy/setup.bash && cd /home/robot/robot_ws && colcon build'
udevadm control --reload-rules && udevadm trigger
systemctl daemon-reload
systemctl enable --now bringup-robot.service
`
	const files: Record<string, string> = {}
	files["user-data"] = `#cloud-config
# Generated by Bringup from the design contract${stamp} (src/ros/provision.ts). Replace the user-data file on the
# system-boot partition of an Ubuntu Server 24.04 (64-bit) card for the Raspberry Pi 5 with this one. The first boot
# takes a while (ROS 2 Jazzy and the build): ~20-40 min on a Pi 5, an ESTIMATE. Its log: /var/log/cloud-init-output.log.
hostname: ${host}
users:
  - name: robot
    gecos: The robot's ROS user
    groups: [dialout, sudo]  # dialout: the board's serial port
    shell: /bin/bash
    lock_passwd: false${o.sshKey ? `
    ssh_authorized_keys:
      - ${o.sshKey.trim()}
ssh_pwauth: false` : `
chpasswd:
  expire: true  # the first login must change it
  users:
    - {name: robot, password: robot, type: text}
ssh_pwauth: true`}
write_files:
  - path: /opt/bringup/robot_ws.tar.gz
    encoding: b64
    permissions: "0644"
    content: ${tar.stdout.toString("base64")}
  - path: /opt/bringup/first-boot.sh
    permissions: "0755"
    content: |
${indent(firstBoot, 6)}
  - path: /etc/systemd/system/bringup-robot.service
    content: |
${indent(service, 6)}${usb ? `
  - path: /etc/udev/rules.d/99-bringup.rules
    content: |
      # The robot's board: ${usb.what} (${usb.source}). Named /dev/bringup.
      SUBSYSTEM=="tty", ATTRS{idVendor}=="${usb.vid}", ATTRS{idProduct}=="${usb.pid}", SYMLINK+="bringup", GROUP="dialout", MODE="0660"` : ""}
runcmd:
  - [bash, /opt/bringup/first-boot.sh]
`
	if (o.wifi)
		files["network-config"] = `# Generated by Bringup: replaces network-config on the system-boot partition. It holds the Wi-Fi password in clear.
network:
  version: 2
  wifis:
    wlan0:
      dhcp4: true
      optional: true
      access-points:
        ${JSON.stringify(o.wifi.ssid)}:
          password: ${JSON.stringify(o.wifi.password)}
`
	files["README.md"] = `# The robot's Raspberry Pi 5${stamp}

1. Flash Ubuntu Server 24.04 LTS (64-bit) for the Raspberry Pi 5 onto a card (Raspberry Pi Imager: no OS customisation).
2. Copy \`user-data\`${o.wifi ? " and `network-config`" : ""} onto the card's \`system-boot\` partition, replacing the ones there.
3. Put the card in the Pi, plug the robot's board into a USB port, power on. The first boot installs ROS 2 Jazzy,
   builds the workspace and starts \`bringup-robot.service\`; follow it with \`tail -f /var/log/cloud-init-output.log\`.
4. Log in as \`robot\`${o.sshKey ? " with your SSH key" : " (password `robot`, changed at first login)"} at \`${host}.local\`.
   \`systemctl status bringup-robot\`, \`journalctl -u bringup-robot -f\`.

The board's serial port: ${usb ? `\`/dev/bringup\` (${usb.what}, VID ${usb.vid} PID ${usb.pid})` : "`/dev/ttyACM0` (no known USB id for this board's parts)"}.
${nav ? `Nav2 starts with the robot: send a goal from RViz on a laptop on the same network (ROS_DOMAIN_ID ${o.domainId ?? 0}), or
\`ros2 action send_goal /navigate_to_pose nav2_msgs/action/NavigateToPose ...\`.` : "Nav2 is off (nav:=false)."}
`
	return files
}

export function writeProvision(dir: string, files: Record<string, string>): void {
	mkdirSync(dir, { recursive: true })
	for (const [name, text] of Object.entries(files)) writeFileSync(join(dir, name), text, { mode: name === "network-config" ? 0o600 : 0o644 })
}
