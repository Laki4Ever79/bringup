import type { ChassisSpec } from "../tools/chassis.ts"
import { maxWheelRadS } from "./urdf.ts"

// The robot's acceptance test (docs/ros.md), generated with its package: one rclpy script whose pass marks come from
// the design, run unchanged against every back end (mock hardware, the firmware in QEMU turning MuJoCo, the real board).
// It drives at the brief's speed, then asks for more than the motors give, and checks what ROS reports against the
// design; the result goes to acceptance.json (and stdout), one entry per check with the measured and expected values.
export function acceptanceScript(spec: ChassisSpec): string {
	const speed = spec.speedMps
	const top = maxWheelRadS(spec) * (spec.drive.wheelDiameterMm / 2000)
	const vmax = Math.min(top, Math.max(speed, 0.05))
	const range = spec.sensor.rangeMm / 1000
	return `#!/usr/bin/env python3
# Generated by Bringup from the design contract (src/ros/acceptance.ts). Do not edit: change the design instead.
# Pass marks from the design: speed ${speed} m/s, held to ${vmax.toFixed(3)} m/s; range sensor 0.03..${range} m.
import json, math, sys, time
import rclpy
from rclpy.node import Node
from geometry_msgs.msg import TwistStamped
from nav_msgs.msg import Odometry
from sensor_msgs.msg import Range

SPEED = ${speed}
VMAX = ${vmax.toFixed(4)}
RANGE_MAX = ${range}
TOL = 0.10  # 10 %: the open-loop odometry reports what was commanded, the simulation what the wheels did


class Acceptance(Node):
    def __init__(self):
        super().__init__("bringup_acceptance")
        self.pub = self.create_publisher(TwistStamped, "/cmd_vel", 10)
        self.odom = None
        self.ranges = []
        self.create_subscription(Odometry, "/diff_drive_controller/odom", lambda m: setattr(self, "odom", m), 10)
        self.create_subscription(Range, "/range_sensor_broadcaster/range", lambda m: self.ranges.append(m.range), 10)

    def drive(self, vx, seconds):
        end = time.monotonic() + seconds
        while time.monotonic() < end:
            m = TwistStamped()
            m.header.stamp = self.get_clock().now().to_msg()
            m.header.frame_id = "base_footprint"
            m.twist.linear.x = vx
            self.pub.publish(m)
            rclpy.spin_once(self, timeout_sec=0.05)

    def speed(self):
        return self.odom.twist.twist.linear.x if self.odom else float("nan")


def main():
    rclpy.init()
    n = Acceptance()
    checks = []
    def check(name, ok, measured, expected):
        checks.append({"name": name, "pass": bool(ok), "measured": measured, "expected": expected})
    start = time.monotonic()
    while n.odom is None and time.monotonic() - start < 30:
        rclpy.spin_once(n, timeout_sec=0.2)
    check("odometry is published", n.odom is not None, n.odom is not None, True)
    n.drive(SPEED, 3.0)
    v = n.speed()
    check("drives at the brief's speed", abs(v - SPEED) <= TOL * SPEED, round(v, 3), SPEED)
    n.drive(VMAX * 3, 2.0)
    v = n.speed()
    check("held to the design's top speed", v <= VMAX * (1 + TOL), round(v, 3), round(VMAX, 3))
    n.drive(0.0, 1.0)
    finite = [r for r in n.ranges if math.isfinite(r)]
    check("range readings arrive", len(n.ranges) > 0, len(n.ranges), "> 0")
    check("range within the sensor's datasheet span", all(0.0 <= r <= RANGE_MAX + 0.01 for r in finite), max(finite) if finite else None, RANGE_MAX)
    result = {"pass": all(c["pass"] for c in checks), "checks": checks}
    out = sys.argv[1] if len(sys.argv) > 1 else "acceptance.json"
    with open(out, "w") as f:
        json.dump(result, f, indent=1)
    print(json.dumps(result))
    rclpy.shutdown()
    sys.exit(0 if result["pass"] else 1)


if __name__ == "__main__":
    main()
`
}
