import type { ChassisSpec } from "../tools/chassis.ts"
import { maxWheelRadS } from "./urdf.ts"

// The robot's acceptance test (docs/ros.md), generated with its package: one rclpy script whose pass marks come from
// the design, run unchanged against every back end (mock hardware, the firmware in QEMU turning MuJoCo, the real board).
// It drives at the brief's speed, then asks for more than the motors give, and checks what ROS reports against the
// design; the result goes to acceptance.json (and stdout), one entry per check with the measured and expected values.
export function acceptanceScript(spec: ChassisSpec): string {
	const speed = spec.speedMps
	const top = maxWheelRadS(spec) * (spec.drive.wheelDiameterMm / 2000)
	const vmax = Math.min(top, Math.max(speed, 0.05))
	const range = spec.sensor.rangeMm / 1000
	const encoders = !!spec.motor.encoderCountsPerRev
	const imu = !!spec.imu
	const track = spec.drive.trackMm / 1000
	return `#!/usr/bin/env python3
# Generated by Bringup from the design contract (src/ros/acceptance.ts). Do not edit: change the design instead.
# Pass marks from the design: speed ${speed} m/s, held to ${vmax.toFixed(3)} m/s; range sensor 0.03..${range} m.
import json, math, sys, time
import rclpy
from rclpy.node import Node
from geometry_msgs.msg import TwistStamped
from nav_msgs.msg import Odometry
from sensor_msgs.msg import Imu, Range

SPEED = ${speed}
VMAX = ${vmax.toFixed(4)}
RANGE_MAX = ${range}
TOL = 0.10  # 10 %: ${encoders ? "the odometry is the encoders' count, the speed what the firmware's duty gives" : "the open-loop odometry reports what was commanded, the simulation what the wheels did"}
IMU = ${imu ? "True" : "False"}  # an IMU on the robot: its heading on /imu_sensor_broadcaster/imu
TURN_RATE = ${((2 * Math.min(vmax, speed || vmax)) / track / 2).toFixed(3)}  # rad/s: half the wheels' top speed, opposite
TURN_S = min(3.0, 1.5 / TURN_RATE)  # about 1.5 rad: well inside half a turn, so the headings' wrap can't confuse the check
HEADING_TOL = 0.25  # odometry against the gyro over a turn: 25 % (the encoders' heading under-reads on wheel slip)
BACKEND = sys.argv[2] if len(sys.argv) > 2 else "real"  # mock hardware has no gyro: the turn check needs a real or simulated one


def unwrap(seen, yaw):
    # A heading continued from the last one, so a turn past half a revolution isn't folded back (a 4.77 rad turn read
    # as -1.51 rad, 23 Nov 2026).
    return yaw if not seen else seen[-1] + math.remainder(yaw - seen[-1], 2 * math.pi)


class Acceptance(Node):
    def __init__(self):
        super().__init__("bringup_acceptance")
        self.pub = self.create_publisher(TwistStamped, "/cmd_vel", 10)
        self.odom = None
        self.ranges = []
        self.speeds = []
        self.create_subscription(Odometry, "/diff_drive_controller/odom", self.on_odom, 10)
        self.create_subscription(Range, "/range_sensor_broadcaster/range", lambda m: self.ranges.append(m.range), 10)
        self.imu = []
        if IMU:
            self.create_subscription(Imu, "/imu_sensor_broadcaster/imu", lambda m: self.imu.append(unwrap(self.imu, 2 * math.atan2(m.orientation.z, m.orientation.w))), 10)

    def drive(self, vx, seconds, wz=0.0):
        end = time.monotonic() + seconds
        while time.monotonic() < end:
            m = TwistStamped()
            m.header.stamp = self.get_clock().now().to_msg()
            m.header.frame_id = "base_footprint"
            m.twist.linear.x = vx
            m.twist.angular.z = wz
            self.pub.publish(m)
            rclpy.spin_once(self, timeout_sec=0.05)

    def on_odom(self, m):
        q = m.pose.pose.orientation
        self.odom_yaw = unwrap([self.odom_yaw] if self.odom else [], 2 * math.atan2(q.z, q.w))
        self.odom = m
        self.speeds.append((time.monotonic(), m.twist.twist.linear.x))

    def mean_speed(self, seconds):
        # The odometry's speed averaged over the last seconds of a drive: one reading can land on a stop or a jolt.
        now = time.monotonic()
        v = [x for t, x in self.speeds if now - t <= seconds]
        return sum(v) / len(v) if v else float("nan")

    def yaw(self):
        return self.odom_yaw if self.odom else float("nan")

    def speed(self):
        return self.odom.twist.twist.linear.x if self.odom else float("nan")


def main():
    rclpy.init()
    n = Acceptance()
    checks = []
    # A value that never arrived (no odometry: nan) is written as null: JSON has no NaN, and the run reads this file
    # with JSON.parse (mock rover run, 16 Nov 2026: "measured": NaN left the acceptance unread).
    # (named apart from the readings below: a later "finite = [...]" in this scope made it a list, and every check raised)
    def json_safe(x):
        return None if isinstance(x, float) and not math.isfinite(x) else x

    def check(name, ok, measured, expected):
        checks.append({"name": name, "pass": bool(ok), "measured": json_safe(measured), "expected": json_safe(expected)})
    start = time.monotonic()
    while n.odom is None and time.monotonic() - start < 30:
        rclpy.spin_once(n, timeout_sec=0.2)
    check("odometry is published", n.odom is not None, n.odom is not None, True)
    # Two seconds at the brief's speed (0.6 m at 0.3 m/s: short of a course's far wall), the speed read over the last one.
    n.drive(SPEED, 2.0)
    v = n.mean_speed(1.0)
    check("drives at the brief's speed", abs(v - SPEED) <= TOL * SPEED, round(v, 3), SPEED)
    # Asked for three times the top speed, in reverse (back toward the start, away from what is ahead): it must move,
    # and no faster than the design's top speed (a robot stopped by the wall read 0 and passed, 23 Nov 2026).
    n.drive(0.0, 0.5)
    n.drive(-VMAX * 3, 1.5)
    v = -n.mean_speed(0.75)
    check("held to the design's top speed", VMAX * 0.5 <= v <= VMAX * (1 + TOL), round(v, 3), round(VMAX, 3))
    n.drive(0.0, 1.0)
    finite = [r for r in n.ranges if math.isfinite(r)]
    check("range readings arrive", len(n.ranges) > 0, len(n.ranges), "> 0")
    check("range within the sensor's datasheet span", all(0.0 <= r <= RANGE_MAX + 0.01 for r in finite), max(finite) if finite else None, RANGE_MAX)
    if IMU:
        check("IMU readings arrive", len(n.imu) > 0, len(n.imu), "> 0")
        if BACKEND != "mock":
            # A turn in place: the odometry's heading change against the gyro's, both measured on the robot.
            odo0, gyro0 = n.yaw(), (n.imu[-1] if n.imu else float("nan"))
            n.drive(0.0, TURN_S, TURN_RATE)
            n.drive(0.0, 1.0)
            d_odo = n.yaw() - odo0
            d_gyro = (n.imu[-1] if n.imu else float("nan")) - gyro0
            ok = abs(d_gyro) > 0.2 and abs(d_odo - d_gyro) <= HEADING_TOL * abs(d_gyro)
            check("odometry's turn agrees with the gyro", ok, {"odometry_rad": round(d_odo, 3), "gyro_rad": round(d_gyro, 3)}, f"within {int(HEADING_TOL * 100)} % of the gyro (> 0.2 rad)")
    result = {"pass": all(c["pass"] for c in checks), "checks": checks}
    out = sys.argv[1] if len(sys.argv) > 1 else "acceptance.json"
    with open(out, "w") as f:
        json.dump(result, f, indent=1, allow_nan=False)
    print(json.dumps(result, allow_nan=False))
    rclpy.shutdown()
    sys.exit(0 if result["pass"] else 1)


if __name__ == "__main__":
    main()
`
}
