import { mkdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import type { ChassisSpec } from "../tools/chassis.ts"
import { controllersYaml, robotUrdf, type RosHardware } from "./urdf.ts"
import { acceptanceScript } from "./acceptance.ts"

// The robot's ROS 2 package (docs/ros.md), written beside each chassis build: an ament_cmake package that installs
// the URDF, the controllers' settings and a launch file (robot_state_publisher, the ros2_control node, the joint state
// broadcaster and the diff-drive controller). `colcon build` it in any Jazzy workspace; `ros2 launch <pkg>
// bringup.launch.py hardware:=mock` drives the mock hardware (commands mirrored back), `hardware:=bringup` the robot's
// own firmware through the bridge.

export const rosPackageName = (robot: string) => `${robot.replace(/[^a-z0-9_]/gi, "_").toLowerCase()}_bringup`

export function writeRosPackage(dir: string, spec: ChassisSpec, opts: { robot?: string; revision?: number } = {}): string {
	const robot = opts.robot ?? "rover"
	const pkg = rosPackageName(robot)
	const root = join(dir, pkg)
	for (const d of ["urdf", "config", "launch", "test"]) mkdirSync(join(root, d), { recursive: true })
	writeFileSync(join(root, "test", "acceptance.py"), acceptanceScript(spec), { mode: 0o755 })
	const stamp = opts.revision !== undefined ? ` (design revision ${opts.revision})` : ""
	for (const hw of ["mock", "bringup"] as RosHardware[]) writeFileSync(join(root, "urdf", `${robot}.${hw}.urdf`), robotUrdf(spec, { name: robot, hardware: hw }))
	writeFileSync(join(root, "config", "controllers.yaml"), controllersYaml(spec))
	writeFileSync(
		join(root, "package.xml"),
		`<?xml version="1.0"?>
<package format="3">
  <name>${pkg}</name>
  <version>0.0.${opts.revision ?? 0}</version>
  <description>The ${robot} robot, generated by Bringup from its design contract${stamp}.</description>
  <maintainer email="bringup@example.invalid">Bringup</maintainer>
  <license>Apache-2.0</license>
  <buildtool_depend>ament_cmake</buildtool_depend>
  <exec_depend>robot_state_publisher</exec_depend>
  <exec_depend>controller_manager</exec_depend>
  <exec_depend>diff_drive_controller</exec_depend>
  <exec_depend>joint_state_broadcaster</exec_depend>
  <exec_depend>range_sensor_broadcaster</exec_depend>
  <exec_depend>bringup_hardware</exec_depend>
  <export><build_type>ament_cmake</build_type></export>
</package>
`,
	)
	writeFileSync(
		join(root, "CMakeLists.txt"),
		`cmake_minimum_required(VERSION 3.8)
project(${pkg})
find_package(ament_cmake REQUIRED)
install(DIRECTORY urdf config launch test DESTINATION share/\${PROJECT_NAME})
ament_package()
`,
	)
	writeFileSync(
		join(root, "launch", "bringup.launch.py"),
		`# Generated by Bringup from the design contract${stamp}. Do not edit: change the design instead.
import os
from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, OpaqueFunction
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node


def nodes(context):
    share = get_package_share_directory("${pkg}")
    hardware = LaunchConfiguration("hardware").perform(context)
    with open(os.path.join(share, "urdf", f"${robot}.{hardware}.urdf")) as f:
        description = f.read()
    controllers = os.path.join(share, "config", "controllers.yaml")
    return [
        Node(package="robot_state_publisher", executable="robot_state_publisher", parameters=[{"robot_description": description}]),
        Node(package="controller_manager", executable="ros2_control_node", parameters=[controllers], remappings=[("~/robot_description", "/robot_description")]),
        Node(package="controller_manager", executable="spawner", arguments=["joint_state_broadcaster"]),
        Node(package="controller_manager", executable="spawner", arguments=["diff_drive_controller", "--controller-ros-args", "-r /diff_drive_controller/cmd_vel:=/cmd_vel"]),
        Node(package="controller_manager", executable="spawner", arguments=["range_sensor_broadcaster"]),
    ]


def generate_launch_description():
    return LaunchDescription([
        DeclareLaunchArgument("hardware", default_value="mock", description="mock (commands mirrored back) or bringup (the robot's own firmware)"),
        OpaqueFunction(function=nodes),
    ])
`,
	)
	return root
}
