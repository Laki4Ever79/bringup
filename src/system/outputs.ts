// What a system of boards leaves on disk: the cable drawing (cable.md, and cable.yml for WireViz), and the system
// report. Both are regenerated from the boards' contracts and the spec on every check.
import type { BoardLink, ContractSnapshot } from "../contract/types.ts"
import { LINK_CONNECTOR, uartSignals } from "../contract/links.ts"
import { connectorRef } from "./derive.ts"
import type { SystemFinding } from "./checks.ts"
import type { LinkTest } from "./linktest.ts"
import type { SystemLink, SystemSpec } from "./spec.ts"

const PINS = ["GND", "VCC", "IO1", "IO2"] as const

// What each connector pin carries on one board's side of a link.
function pinSignals(l: SystemLink, link: BoardLink | undefined): Record<(typeof PINS)[number], string> {
	const io = (pin: "IO1" | "IO2") => {
		if (!link) return "?"
		if (link.kind === "i2c") return pin === "IO1" ? "SDA" : "SCL"
		const { tx, rx } = uartSignals(link)
		return link.txOn === pin ? tx : rx
	}
	return { GND: "GND", VCC: l.power ? "3V3" : "not connected", IO1: io("IO1"), IO2: io("IO2") }
}

export function cableMarkdown(spec: SystemSpec, contracts: Record<string, ContractSnapshot | undefined>): string {
	const lines = [`# Cables: ${spec.name}`, "", `Each link is a straight JST SH 4-pin cable (${LINK_CONNECTOR.mpn} on both boards, pin 1 to pin 1). Generated by Bringup from the system spec and the boards' contracts.`, "", "These are the connectors Qwiic and STEMMA QT use, but they are not Qwiic ports: a link's IO pins carry what this file says, and VCC (pin 2) is connected only on a link that carries power. Don't plug a Qwiic device in.", ""]
	for (const l of spec.links) {
		const ref = connectorRef(l)
		const [la, lb] = [l.a.board, l.b.board].map((b) => contracts[b]?.values.links?.find((x) => x.id === l.id))
		const [sa, sb] = [pinSignals(l, la), pinSignals(l, lb)]
		lines.push(`## ${l.id}: ${l.a.board} ${ref} to ${l.b.board} ${ref}, ${l.kind.toUpperCase()}, ${l.cable.lengthMm} mm`, "")
		lines.push(`| Pin | Wire | ${l.a.board} | ${l.b.board} |`, "|---|---|---|---|")
		PINS.forEach((p, i) => lines.push(`| ${i + 1} | ${p === "VCC" && !l.power ? "leave out (or cut)" : ["black", "red", "blue", "yellow"][i]} | ${sa[p]} | ${sb[p]} |`))
		if (l.power) lines.push("", `VCC carries ${l.power.from}'s 3V3 to ${l.power.from === l.a.board ? l.b.board : l.a.board}.`)
		lines.push("")
	}
	return lines.join("\n")
}

// WireViz's YAML (https://github.com/wireviz/WireViz): `wireviz cable.yml` draws it, if WireViz is installed.
export function wirevizYaml(spec: SystemSpec, contracts: Record<string, ContractSnapshot | undefined>): string {
	const out: string[] = ["# Generated by Bringup. Render with: wireviz cable.yml", "connectors:"]
	for (const l of spec.links)
		for (const board of [l.a.board, l.b.board]) {
			const s = pinSignals(l, contracts[board]?.values.links?.find((x) => x.id === l.id))
			out.push(`  ${board}.${connectorRef(l)}:`, `    type: JST SH`, `    subtype: ${LINK_CONNECTOR.mpn}`, `    pincount: 4`, `    pinlabels: [${PINS.map((p) => JSON.stringify(s[p])).join(", ")}]`)
		}
	out.push("cables:")
	for (const l of spec.links) out.push(`  ${l.id}:`, `    wirecount: 4`, `    length: ${l.cable.lengthMm / 1000}`, `    gauge: 28 AWG`, `    colors: [BK, RD, BU, YE]`)
	out.push("connections:")
	for (const l of spec.links) out.push(`  -`, `    - ${l.a.board}.${connectorRef(l)}: [1-4]`, `    - ${l.id}: [1-4]`, `    - ${l.b.board}.${connectorRef(l)}: [1-4]`)
	return out.join("\n") + "\n"
}

export function systemReport(spec: SystemSpec, contracts: Record<string, ContractSnapshot | undefined>, findings: SystemFinding[], status: string, sent: { board: string; text: string }[], tests: LinkTest[] = []): string {
	const real = findings.filter((f) => f.kind !== "link-pending")
	const boardLine = (name: string) => {
		const s = contracts[name]
		const spec_ = spec.boards.find((b) => b.name === name)!
		return `| ${name} | ${spec_.run ? "existing run (fixed)" : "designed here"} | ${s ? `rev ${s.revision}` : "no contract yet"} | ${s?.values.outline ? `${s.values.outline.widthMm}×${s.values.outline.heightMm} mm` : "?"} | ${(s?.values.links ?? []).map((l) => `${l.id} ${l.kind.toUpperCase()} on ${l.connector}`).join(", ") || "none"} |`
	}
	return [
		`# System report: ${spec.name}`,
		"",
		`Status: ${status}`,
		`System findings: ${real.length}`,
		...real.map((f) => `- ${f.kind} (${f.boards.join(", ")}): ${f.message}${f.estimate ? " [estimate]" : ""}`),
		...findings.filter((f) => f.kind === "link-pending").map((f) => `- waiting: ${f.message}`),
		"",
		"## Boards",
		"",
		"| Board | How | Contract | Board size | Links |",
		"|---|---|---|---|---|",
		...spec.boards.map((b) => boardLine(b.name)),
		"",
		"## Links",
		"",
		"| Link | Between | Kind | Power | Cable | Messages |",
		"|---|---|---|---|---|---|",
		...spec.links.map((l) => `| ${l.id} | ${l.a.board} ↔ ${l.b.board} | ${l.kind === "uart" ? `UART ${l.baud ?? 115200} baud` : `I2C ${l.i2c?.khz ?? 100} kHz, controller ${l.i2c?.controller}`} | ${l.power ? `from ${l.power.from}` : "each its own"} | ${l.cable.lengthMm} mm (cable.md) | ${(l.messages ?? []).map((m) => `${m.name} from ${m.from}`).join(", ") || "none"} |`),
		"",
		...(tests.length ? ["## Link tests", "", "| Link | Result | What happened |", "|---|---|---|", ...tests.map((t) => `| ${t.link} | ${!t.ran ? "not run" : t.passed ? "pass" : "FAIL"} | ${t.detail} |`), "", "Each UART link's two firmwares (the link-test build, from each board's own contract) run in QEMU joined by a virtual cable; each message must arrive with a known reading in it. The product firmware deep-sleeps, so on real boards a receiver hears a link while it is awake: on USB power, or during its own wake.", ""] : []),
		...(sent.length ? ["## Asked of the boards", "", ...sent.map((s) => `- ${s.board}: ${s.text}`), ""] : []),
		"Each board's own report is in boards/<name>/report.md.",
		"",
	].join("\n")
}
