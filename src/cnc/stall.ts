// The spindle's stall stop (lead-2, after gap 11): a grblHAL plugin, generated with the board's numbers, that reads the
// spindle's current (SPINDLE_I: its INA180 on a 10 mOhm shunt under the MOSFET), averages it, divides by the PWM duty (the
// low-side shunt carries the motor current only while the MOSFET conducts), and stops the spindle with grblHAL's spindle
// alarm when it stays over a threshold. The detector is a pure header (bringup_stall.h), compiled and tested on the host;
// the plugin (bringup_stall.c) hooks it into grblHAL (my_plugin_init, grbl.on_execute_realtime) and the ST HAL's ADC.
// Both are ours (Apache-2.0); they are built only inside grblHAL's tree (GPLv3), never copied into this repository's.
import type { ContractSnapshot } from "../contract/types.ts"
import { mcuPinName } from "../mcu/pins.ts"

// The stall: no maker states a 775 spindle's stall current, so the trip is an ESTIMATE: twice the run current, held under
// the brick's limit (a stall can't draw more than the brick gives, and the trip must fire before it does); held for
// STALL_HOLD_MS so a cut's load step doesn't trip it. The MOSFET's thermal time constant is seconds (catalog AO4468:
// ~1.3 W at the brick's current, RthJA 75 C/W), so 300 ms is well inside it.
export const STALL_FACTOR = 2
export const STALL_BRICK_SHARE = 0.9
export const STALL_HOLD_MS = 300
// Below this PWM duty the division by it amplifies noise: no judgement there (the spindle barely turns anyway).
export const STALL_MIN_DUTY = 0.1
// The current's average: an exponential one over this long, a few PWM periods at grblHAL's spindle frequency.
export const STALL_AVG_MS = 20

export interface StallParams {
	thresholdA: number
	holdMs: number
	gainVV: number
	shuntOhm: number
	vrefV: number
	adcChannel: number
	pin: string
}

// ADC1's channel for an STM32F4 pin (RM0383 §11.3: PA0-PA7 are IN0-IN7, PB0/PB1 IN8/IN9, PC0-PC5 IN10-IN15).
export function adcChannel(pin: string): number | null {
	const m = /^P([ABC])(\d+)$/.exec(pin)
	if (!m) return null
	const n = Number(m[2])
	if (m[1] === "A" && n <= 7) return n
	if (m[1] === "B" && n <= 1) return 8 + n
	if (m[1] === "C" && n <= 5) return 10 + n
	return null
}

export function stallParams(s: ContractSnapshot, cat: { boardParts?: unknown; mech?: { spindles?: { mpn: string; amps?: number }[] } }): StallParams | null {
	const m = s.values.cnc
	const parts = s.values.parts ?? []
	const sense = parts.find((p) => p.role === "current-sense")
	const pin = (s.values.pins ?? []).find((p) => p.partRef === sense?.ref && p.partPin === "OUT")
	const entry = ((cat.boardParts ?? []) as { mpn: string; gainVV?: number; support?: { shuntOhm?: number }[] }[]).find((x) => x.mpn === sense?.mpn)
	const run = cat.mech?.spindles?.find((x) => x.mpn === m?.spindle.part)?.amps
	const shunt = entry?.support?.find((x) => x.shuntOhm)?.shuntOhm
	if (!m || !sense || !pin || !entry?.gainVV || !shunt || !run) return null
	const name = mcuPinName(parts, pin.gpio)
	const ch = adcChannel(name)
	if (ch === null) return null
	const thresholdA = Math.round(Math.min(STALL_FACTOR * run, STALL_BRICK_SHARE * m.input.amps) * 100) / 100
	return { thresholdA, holdMs: STALL_HOLD_MS, gainVV: entry.gainVV, shuntOhm: shunt, vrefV: 3.3, adcChannel: ch, pin: name }
}

// A C float literal: always a decimal point (6 would print as "6f", which isn't C).
const cf = (x: number) => `${Number.isInteger(x) ? x.toFixed(1) : String(x)}f`

export function stallHeader(p: StallParams): string {
	return `// Generated by Bringup: the spindle's stall detector (pure: no grblHAL, no HAL; tested on the host).
// Trip: ${p.thresholdA} A held ${p.holdMs} ms (an ESTIMATE: twice the spindle's run current, under 0.9 of the brick's).
#ifndef BRINGUP_STALL_H
#define BRINGUP_STALL_H

#include <stdbool.h>
#include <stdint.h>

#ifndef STALL_THRESHOLD_A
#define STALL_THRESHOLD_A ${cf(p.thresholdA)}
#endif
#ifndef STALL_HOLD_MS
#define STALL_HOLD_MS ${p.holdMs}u
#endif
#define STALL_GAIN_VV ${cf(p.gainVV)}
#define STALL_SHUNT_OHM ${cf(p.shuntOhm)}
#define STALL_MIN_DUTY ${cf(STALL_MIN_DUTY)}
#define STALL_AVG_MS ${cf(STALL_AVG_MS)}

typedef struct {
    float avg_a;    // the shunt's average current, A
    uint32_t over_ms; // how long the motor's current has been over the threshold
} bringup_stall_t;

// One sample: the amplifier's output (V), the PWM duty (0..1) and the time since the last sample (ms). True: stalled.
static inline bool bringup_stall_update (bringup_stall_t *s, float sense_v, float duty, uint32_t dt_ms)
{
    float k = (float)dt_ms / STALL_AVG_MS;
    if(k > 1.0f)
        k = 1.0f;
    s->avg_a += k * (sense_v / (STALL_GAIN_VV * STALL_SHUNT_OHM) - s->avg_a);
    if(duty < STALL_MIN_DUTY) {
        s->over_ms = 0;
        return false;
    }
    if(s->avg_a / duty >= STALL_THRESHOLD_A) {
        s->over_ms += dt_ms;
        return s->over_ms >= STALL_HOLD_MS;
    }
    s->over_ms = 0;
    return false;
}

#endif
`
}

export function stallPlugin(p: StallParams): string {
	return `// Generated by Bringup: the spindle's stall stop, a grblHAL plugin (my_plugin_init). It reads the spindle's current on
// ${p.pin} (ADC1 channel ${p.adcChannel}: its INA180 at ${p.gainVV} V/V on a ${p.shuntOhm * 1000} mOhm shunt), divides its average by the PWM duty,
// and on a stall turns the spindle off and raises grblHAL's spindle alarm (reset and unlock to go on).
#include "driver.h"
#include "grbl/hal.h"
#include "grbl/spindle_control.h"
#include "grbl/system.h"
#include "bringup_stall.h"

static on_execute_realtime_ptr on_execute_realtime;
static ADC_HandleTypeDef adc = {
    .Instance = ADC1,
    .Init = {
        .Resolution = ADC_RESOLUTION_12B,
        .ScanConvMode = DISABLE,
        .ContinuousConvMode = DISABLE,
        .DiscontinuousConvMode = DISABLE,
        .ExternalTrigConvEdge = ADC_EXTERNALTRIGCONVEDGE_NONE,
        .ExternalTrigConv = ADC_SOFTWARE_START,
        .DataAlign = ADC_DATAALIGN_RIGHT,
        .NbrOfConversion = 1,
        .DMAContinuousRequests = DISABLE,
        .EOCSelection = ADC_EOC_SINGLE_CONV
    }
};
static bringup_stall_t stall = {0};
static uint32_t last_ms = 0;
static bool adc_ok = false;

static float spindle_duty (spindle_ptrs_t *spindle)
{
    if(!(spindle && spindle->param && spindle->param->state.on && spindle->get_pwm && spindle->context.pwm && spindle->context.pwm->period))
        return 0.0f;
    return (float)spindle->get_pwm(spindle, spindle->param->rpm_overridden) / (float)spindle->context.pwm->period;
}

static void stall_poll (sys_state_t state)
{
    on_execute_realtime(state);

    uint32_t now = hal.get_elapsed_ticks();
    if(!adc_ok || now == last_ms)
        return;
    uint32_t dt = now - last_ms;
    last_ms = now;

    HAL_ADC_Start(&adc);
    if(HAL_ADC_PollForConversion(&adc, 1) != HAL_OK)
        return;
    float sense_v = (float)HAL_ADC_GetValue(&adc) * (${cf(p.vrefV)} / 4095.0f);

    spindle_ptrs_t *spindle = spindle_get(0);
    if(bringup_stall_update(&stall, sense_v, spindle_duty(spindle), dt)) {
        if(spindle)
            spindle_set_state(spindle, (spindle_state_t){0}, 0.0f);
        system_raise_alarm(Alarm_Spindle);
        stall = (bringup_stall_t){0};
    }
}

void my_plugin_init (void)
{
    GPIO_InitTypeDef gpio = {
        .Pin = GPIO_PIN_${/\d+$/.exec(p.pin)![0]},
        .Mode = GPIO_MODE_ANALOG,
        .Pull = GPIO_NOPULL
    };
    ADC_ChannelConfTypeDef channel = {
        .Channel = ADC_CHANNEL_${p.adcChannel},
        .Rank = 1,
        .SamplingTime = ADC_SAMPLETIME_84CYCLES
    };

    __HAL_RCC_GPIO${p.pin[1]}_CLK_ENABLE();
    HAL_GPIO_Init(GPIO${p.pin[1]}, &gpio);
    __HAL_RCC_ADC1_CLK_ENABLE();
    adc_ok = HAL_ADC_Init(&adc) == HAL_OK && HAL_ADC_ConfigChannel(&adc, &channel) == HAL_OK;

    on_execute_realtime = grbl.on_execute_realtime;
    grbl.on_execute_realtime = stall_poll;
}
`
}
