// A CNC's grblHAL configuration from the contract (gap 11): the board map (boards/my_machine_map.h for grblHAL's
// STM32F4xx driver) from the pin map, and the machine's settings from the cnc field. Macro and setting names as read in
// grblHAL's sources on 27 Nov 2026 (STM32F4xx boards/btt_skr_2.0_map.h and blackpill_map.h for the map, Src/tmc_uart.c
// for the Trinamic UART, core settings.h for the $ numbers), then checked in its cloned source (27 Nov 2026, STM32F4xx
// b0cd1bb): Src/serial.c's ports, grbl/driver_opts2.h's TRINAMIC_STREAM, grbl/config.h's input polarity, protocol.c's
// e-stop alarm.
import type { ContractSnapshot } from "../contract/types.ts"
import type { MechCatalog } from "../mechanics/catalog.ts"
import { mcuPinName } from "../mcu/pins.ts"
import { ACCEL_MM_S2 } from "./checks.ts"

// The signals the map needs, by the scripted design's names (src/inference/scripts.ts CNC_DESIGN): the drivers' STEP and
// DIR per motor (X, Y1, Y2 the ganged second Y motor = grblHAL's M3, Z), one shared enable, the limits, the spindle's PWM,
// the e-stop's trip (grblHAL's RESET input) and the drivers' UART.
export const GRBLHAL_SIGNALS = ["X_STEP", "X_DIR", "Y1_STEP", "Y1_DIR", "Y2_STEP", "Y2_DIR", "Z_STEP", "Z_DIR", "STEPPERS_EN", "LIMIT_X", "LIMIT_Y", "LIMIT_Z", "SPINDLE_PWM", "ESTOP_TRIP", "STEPPER_UART", "STEPPER_UART_TX"] as const
// The spindle's PWM frequency, Hz: an ESTIMATE for a brushed 775 motor through a MOSFET (no maker states one).
export const SPINDLE_PWM_HZ = 1000

const portPin = (name: string): [string, number] | null => {
	const m = /^P([A-H])(\d+)$/.exec(name)
	return m ? [`GPIO${m[1]}`, Number(m[2])] : null
}

export function grblhalPins(s: ContractSnapshot): { found: Map<string, [string, number]>; missing: string[] } {
	const parts = s.values.parts ?? []
	const found = new Map<string, [string, number]>()
	for (const p of s.values.pins ?? []) {
		const pp = portPin(mcuPinName(parts, p.gpio))
		if (pp) found.set(p.signal, pp)
	}
	return { found, missing: GRBLHAL_SIGNALS.filter((x) => !found.has(x)) }
}

// Spare GPIOs for grblHAL's spindle enable, in order (UFQFPN48 names; not USB's PA11/PA12, SWD's PA13/PA14 or BOOT1 PB2).
const SPARE_PINS = ["PB9", "PB8", "PB7", "PB6", "PB5", "PB4", "PB3", "PC14", "PC15"]

export function grblhalMap(s: ContractSnapshot): string {
	const { found } = grblhalPins(s)
	const used = new Set((s.values.pins ?? []).map((p) => mcuPinName(s.values.parts ?? [], p.gpio)))
	const spare = SPARE_PINS.filter((x) => !used.has(x)).map(portPin)[0] ?? null
	const def = (macro: string, signal: string) => {
		const pp = found.get(signal)
		return pp ? [`#define ${macro}_PORT ${pp[0]}`, `#define ${macro}_PIN ${pp[1]}`] : [`// ${macro}: no ${signal} in the contract's pins`]
	}
	return [
		"// Generated by Bringup from the contract's pin map: grblHAL STM32F4xx board map (boards/my_machine_map.h,",
		"// selected with -D BOARD_MY_MACHINE=). Pins on several ports, so each one is named (GPIO_BITBAND), as the BTT SKR 2.0",
		"// map does.",
		"",
		'#define BOARD_NAME "Bringup CNC"',
		"",
		...def("X_STEP", "X_STEP"), ...def("Y_STEP", "Y1_STEP"), ...def("Z_STEP", "Z_STEP"),
		"#define STEP_OUTMODE GPIO_BITBAND",
		...def("X_DIRECTION", "X_DIR"), ...def("Y_DIRECTION", "Y1_DIR"), ...def("Z_DIRECTION", "Z_DIR"),
		"#define DIRECTION_OUTMODE GPIO_BITBAND",
		"",
		"// The gantry's second Y motor (the drivers' fourth, UART address 3 = its motor index).",
		"#if N_ABC_MOTORS > 0",
		"#define M3_AVAILABLE",
		...def("M3_STEP", "Y2_STEP"), ...def("M3_DIRECTION", "Y2_DIR"),
		"#endif",
		"",
		"// One enable for every driver: the MCU's STEPPERS_EN into the e-stop's OR gate, whose output is every TMC2209's ENN.",
		...def("STEPPERS_ENABLE", "STEPPERS_EN"),
		"",
		"// NC limit switches to GND with 10k pull-ups: closed reads low, tripped (or a cut wire) reads high.",
		...def("X_LIMIT", "LIMIT_X"), ...def("Y_LIMIT", "LIMIT_Y"), ...def("Z_LIMIT", "LIMIT_Z"),
		"#define LIMIT_INMODE GPIO_BITBAND",
		"",
		"// grblHAL's PWM-only spindle doesn't build (27 Nov 2026: Src/driver_spindles.c calls the one-argument spindle_dir() with",
		"// two), so its PWM spindle without direction (SPINDLE_PWM0_NODIR) takes an enable pin: a spare GPIO, wired to nothing.",
		"// The PWM alone runs this board's spindle, its gate held off by its pull-down.",
		"#if DRIVER_SPINDLE_ENABLE & SPINDLE_ENA",
		...(spare ? [`#define SPINDLE_ENABLE_PORT ${spare[0]}`, `#define SPINDLE_ENABLE_PIN ${spare[1]}`] : ["// SPINDLE_ENABLE: no spare GPIO left"]),
		"#endif",
		"#if DRIVER_SPINDLE_ENABLE & SPINDLE_PWM",
		...def("SPINDLE_PWM", "SPINDLE_PWM"),
		"#endif",
		"",
		"// The e-stop's ESTOP_TRIP (high when the stop is pressed or its cable cut) as grblHAL's reset/E-stop input.",
		"#if CONTROL_ENABLE & CONTROL_HALT",
		...def("RESET", "ESTOP_TRIP"),
		"#endif",
		"",
		"// The four TMC2209s on one single-wire UART (RX on the line, TX through 1 kOhm): grblHAL's shared Trinamic stream,",
		"// each driver addressed by its motor index (X 0, Y 1, Z 2, M3 3), as the board's MS1/MS2 straps set them.",
		"// USART1 is SERIAL_PORT 1 (Src/serial.c: TX PA9, RX PA10); with the console on USB it is serial stream instance 0, so",
		"// the Trinamic stream is 0 (grblHAL's default, 1, is a second serial port this board doesn't have).",
		"#if TRINAMIC_UART_ENABLE",
		"#undef TRINAMIC_UART_ENABLE",
		"#define TRINAMIC_UART_ENABLE 1",
		`#define SERIAL_PORT 1 // TX ${found.get("STEPPER_UART_TX")?.join(" ") ?? "?"}, RX ${found.get("STEPPER_UART")?.join(" ") ?? "?"}`,
		"#define TRINAMIC_STREAM 0",
		"#endif",
		"",
	].join("\n")
}

// The settings ($ numbers, grblHAL core settings.h) from the machine: steps/mm from the stepper's step angle, the
// driver's microsteps and the screw's lead; rates from the brief's rapids; travel from the axes; limits and homing on.
export function grblhalSettings(s: ContractSnapshot, mech: MechCatalog): { id: number; value: number; note: string }[] | null {
	const m = s.values.cnc, t = s.values.cncTargets
	if (!m) return null
	const out: { id: number; value: number; note: string }[] = []
	m.axes.forEach((a, i) => {
		const stepper = mech.steppers?.find((x) => x.mpn === a.motor)
		const screw = (mech.driveTrain ?? []).find((x) => x.kind === "leadscrew" && x.mpn === a.screw) as { leadMm?: number } | undefined
		if (!stepper || !screw?.leadMm) return
		const steps = ((360 / stepper.stepDeg) * a.driver.microsteps) / screw.leadMm
		const ax = a.name.toUpperCase()
		out.push({ id: 100 + i, value: Math.round(steps * 1000) / 1000, note: `${ax} steps/mm: ${360 / stepper.stepDeg} steps/rev × ${a.driver.microsteps} microsteps / ${screw.leadMm} mm lead` })
		if (t) out.push({ id: 110 + i, value: t.rapidMmMin, note: `${ax} max rate, mm/min (the brief's rapids)` })
		out.push({ id: 120 + i, value: ACCEL_MM_S2, note: `${ax} acceleration, mm/s² (the thrust check's, an estimate)` })
		out.push({ id: 130 + i, value: a.travelMm, note: `${ax} max travel, mm` })
	})
	const sp = mech.spindles?.find((x) => x.mpn === m.spindle.part) as { noLoadRpm?: number } | undefined
	if (sp?.noLoadRpm) out.push({ id: 30, value: sp.noLoadRpm, note: "spindle max rpm (its no-load speed)" })
	out.push({ id: 31, value: 0, note: "spindle min rpm" })
	out.push({ id: 33, value: SPINDLE_PWM_HZ, note: "spindle PWM frequency, Hz (an ESTIMATE: no maker states one for a 775 motor)" })
	out.push({ id: 20, value: 1, note: "soft limits on" })
	out.push({ id: 21, value: 1, note: "hard limits on" })
	// No restart on its own (lead-2, gap 7): homing on and the boot alarm forced, so after power returns (an e-stop
	// released) nothing moves until the operator resets and homes; the spindle's gate stays off by its pull-down.
	out.push({ id: 22, value: 1, note: "homing on" })
	out.push({ id: 64, value: 1, note: "force the boot alarm: after a power-up or a released e-stop nothing runs until reset and homing" })
	return out.sort((a, b) => a.id - b.id)
}

export function grblhalSettingsText(settings: { id: number; value: number; note: string }[]): string {
	return [
		"; Generated by Bringup: grblHAL settings for this machine, sent once over the serial console.",
		"; The NC switches need no inversion ($5=0, $14=0, grblHAL's defaults: inputs normal-low, NC to ground); still check",
		"; each limit and the e-stop trip ($? shows the pins) before the first move.",
		"; The spindle's stall stop is the bringup_stall plugin (its INA180's current, averaged and divided by the PWM duty): a",
		"; stall turns the spindle off and raises the spindle alarm (ALARM:14); reset and unlock to go on.",
		...settings.map((x) => `$${x.id}=${x.value} ; ${x.note}`),
		"",
	].join("\n")
}

