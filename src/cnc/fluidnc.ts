// A CNC's FluidNC configuration from the contract (gap 11's FluidNC half, gap 14's chip): config.yaml from the pin map
// and the cnc field. Keys, types and defaults as FluidNC's own schema gives them (FluidNC/docs/config_items.yaml,
// generated from its sources; the clone at tools/FluidNC, bdring/FluidNC 5b8fbfd, read 27 Nov 2026):
//   - pins are "gpio.<n>", ":pu" a pull-up, ":low" active low (an input or output is active high otherwise);
//   - each TMC2209 runs over a top-level uartN (uart_num, required) at its addr, with a real r_sense_ohms (the schema:
//     "0.0 is not a real, functional value");
//   - axes.shared_stepper_disable_pin drives every driver's disable at once; control.estop_pin is the user's e-stop;
//   - a spindle type (PWM) is a top-level section.
// The machine's numbers (steps per mm, rates, acceleration, travel, the spindle's top speed) are grblHAL's settings'
// (grblhal.ts grblhalSettings): one machine, two firmwares, the same numbers.
import type { ContractSnapshot } from "../contract/types.ts"
import type { MechCatalog } from "../mechanics/catalog.ts"
import { mcuPinName } from "../mcu/pins.ts"
import { profileForPart } from "../mcu/profile.ts"
import { SPINDLE_PWM_HZ, grblhalSettings } from "./grblhal.ts"
import { CNC_SIGNALS } from "./signals.ts"
import { cncMotors, senseResistor } from "./board.ts"

// The same signals as grblHAL's map (the scripted design's names).
export const FLUIDNC_SIGNALS = CNC_SIGNALS
const INPUTS = new Set(["LIMIT_X", "LIMIT_Y", "LIMIT_Z", "ESTOP_TRIP", "STEPPER_UART"])
// Inputs the board leaves to the MCU's pull-up: the limit switches' SIG (NC to ground: closed reads low, a tripped switch
// or a cut cable reads high). The e-stop's trip and the UART's RX are driven by the board.
const PULLED_UP = new Set(["LIMIT_X", "LIMIT_Y", "LIMIT_Z"])

export function fluidncPins(s: ContractSnapshot): { found: Map<string, number>; missing: string[] } {
	const parts = s.values.parts ?? []
	const found = new Map<string, number>()
	for (const p of s.values.pins ?? []) {
		const m = /^GPIO(\d+)$/.exec(mcuPinName(parts, p.gpio))
		if (m) found.set(p.signal, Number(m[1]))
	}
	return { found, missing: FLUIDNC_SIGNALS.filter((x) => !found.has(x)) }
}

// Pins FluidNC can't use as the map puts them, on the classic ESP32 (ESP32 datasheet; WROOM-32E datasheet Table 3):
// GPIO34-39 are input only and have no internal pull-up; the strapping pins (the profile's: 0, 2, 5, 12, 15) set the boot
// mode and, for GPIO12, the flash voltage, so an input pulled or driven high at reset can stop the module booting.
export function fluidncPinProblems(s: ContractSnapshot): string[] {
	const mcu = (s.values.parts ?? []).find((p) => p.role === "mcu")
	const prof = mcu ? profileForPart(mcu) : null
	const straps = new Set((prof?.pins ?? []).filter((p) => p.reserved === "strap").map((p) => p.index))
	const out: string[] = []
	for (const [signal, gpio] of fluidncPins(s).found) {
		if (!(FLUIDNC_SIGNALS as readonly string[]).includes(signal)) continue
		if (gpio >= 34 && gpio <= 39 && !INPUTS.has(signal)) out.push(`${signal} is an output on GPIO${gpio}, which is input only`)
		else if (gpio >= 34 && gpio <= 39 && PULLED_UP.has(signal)) out.push(`${signal} needs the MCU's pull-up, which GPIO${gpio} doesn't have`)
		if (straps.has(gpio)) out.push(`${signal} is on GPIO${gpio}, a strapping pin: its level at reset sets the boot mode`)
	}
	return out
}

const pin = (n: number | undefined, attrs = "") => (n === undefined ? "NO_PIN" : `gpio.${n}${attrs}`)
const num = (v: number) => (Number.isInteger(v) ? v.toFixed(1) : String(+v.toFixed(3)))

// config.yaml, or null without a machine, its settings or a pin for every signal.
export function fluidncConfig(s: ContractSnapshot, mech: MechCatalog): string | null {
	const m = s.values.cnc
	const settings = grblhalSettings(s, mech)
	const { found, missing } = fluidncPins(s)
	if (!m || !settings || missing.length) return null
	const set = (id: number) => settings.find((x) => x.id === id)?.value
	const motors = cncMotors(s)
	const lines: string[] = [
		"# Generated by Bringup: FluidNC's config.yaml for this machine (keys from FluidNC's docs/config_items.yaml).",
		"# Upload it to the controller's flash (FluidNC's WebUI or $Config/Filename); check each limit and the e-stop with ? before",
		"# the first move.",
		"board: Bringup CNC",
		"name: Bringup CNC",
		"",
		"stepping:",
		"  engine: RMT",
		"  idle_ms: 255",
		"  pulse_us: 4",
		"  dir_delay_us: 1",
		"  disable_delay_us: 0",
		"",
		"# The four TMC2209s on one single-wire UART: RX on the line, TX through the board's 1 kOhm.",
		"uart1:",
		`  txd_pin: ${pin(found.get("STEPPER_UART_TX"))}`,
		`  rxd_pin: ${pin(found.get("STEPPER_UART"))}`,
		"  baud: 115200",
		"  mode: 8N1",
		"",
		"kinematics:",
		"  Cartesian:",
		"",
		"# Homing first (the board's must_home below), then soft limits keep every move inside the travel.",
		"start:",
		"  must_home: true",
		"",
		"axes:",
		"  # Every driver's ENN through the board's OR gate (STEPPERS_EN or the e-stop's trip): high disables.",
		`  shared_stepper_disable_pin: ${pin(found.get("STEPPERS_EN"))}`,
		"  homing_runs: 2",
	]
	m.axes.forEach((a, i) => {
		const ax = a.name.toUpperCase()
		const limit = found.get(`LIMIT_${ax}`)
		const mine = motors.filter((x) => x.axis === a.name)
		lines.push(
			`  ${a.name}:`,
			`    steps_per_mm: ${num(set(100 + i) ?? 0)}`,
			`    max_rate_mm_per_min: ${num(set(110 + i) ?? 1000)}`,
			`    acceleration_mm_per_sec2: ${num(set(120 + i) ?? 25)}`,
			`    max_travel_mm: ${num(set(130 + i) ?? a.travelMm)}`,
			"    soft_limits: true",
			"    homing:",
			// Z clears the work first (cycle 1), then X and Y together (cycle 2), each toward its switch.
			`      cycle: ${a.name === "z" ? 1 : 2}`,
			`      positive_direction: ${a.homeAt === "max"}`,
			`      mpos_mm: ${num(a.homeAt === "max" ? a.travelMm : 0)}`,
		)
		mine.forEach((mo, k) => {
			const step = found.get(`${mo.label}_STEP`) ?? found.get(`${ax}_STEP`)
			const dir = found.get(`${mo.label}_DIR`) ?? found.get(`${ax}_DIR`)
			const r = senseResistor(mo.currentA)
			lines.push(
				`    motor${k}:`,
				// One switch per axis, on its first motor: the ganged Y's second motor homes with it.
				...(k === 0 ? [`      ${a.homeAt === "max" ? "limit_pos_pin" : "limit_neg_pin"}: ${pin(limit, ":pu")}`, "      hard_limits: true", "      pulloff_mm: 1.0"] : ["      hard_limits: false"]),
				"      tmc_2209:",
				"        uart_num: 1",
				`        addr: ${mo.addr}`,
				`        r_sense_ohms: ${r ? r.ohms : 0.11}`,
				`        run_amps: ${num(mo.currentA)}`,
				`        hold_amps: ${num(mo.currentA / 2)}`,
				`        microsteps: ${a.driver.microsteps}`,
				"        use_enable: false",
				"        run_mode: StealthChop",
				"        homing_mode: StealthChop",
				`        step_pin: ${pin(step)}`,
				`        direction_pin: ${pin(dir)}`,
				"        disable_pin: NO_PIN",
			)
		})
	})
	const rpm = set(30)
	lines.push(
		"",
		"# The spindle: the MOSFET's gate through the 5 V buffer; off on any alarm (the stall stop's too).",
		"PWM:",
		`  pwm_hz: ${SPINDLE_PWM_HZ}`,
		`  output_pin: ${pin(found.get("SPINDLE_PWM"))}`,
		"  enable_pin: NO_PIN",
		"  direction_pin: NO_PIN",
		"  off_on_alarm: true",
		...(rpm ? [`  speed_map: 0=0.000% ${rpm}=100.000%`] : []),
		"",
		"# The e-stop's trip line (high when pressed or its cable is cut): FluidNC's hard stop and critical alarm. The board's",
		"# P-FET has already cut the motors' and the spindle's power.",
		"control:",
		`  estop_pin: ${pin(found.get("ESTOP_TRIP"))}`,
		"",
	)
	return lines.join("\n")
}
