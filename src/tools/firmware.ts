const TIMEOUT_MS = 600_000

// Declares py/quantize.py's model array for the template (templates/fw/src/main.cpp includes it when present).
const MODEL_DATA_HEADER = "// Generated by Bringup: the converted model, linked from model_data.cc. Do not edit.\n#pragma once\n#include <stdint.h>\nextern const uint8_t g_model[];\nextern const unsigned int g_model_len;\n"
const LOG_LINES = 60
const ERROR_LINES = 20

// The build's tail, preceded by its compiler errors when they scrolled out of it. With NimBLE in the build, hundreds of
// library compile lines can follow the error, and the agents read this log when a firmware build fails.
export function buildLog(output: string): string {
	const lines = output.trimEnd().split("\n")
	const tail = lines.slice(-LOG_LINES)
	const errors = lines.slice(0, -LOG_LINES).filter((l) => /\berror\b|static assertion/i.test(l)).slice(0, ERROR_LINES)
	return [...(errors.length ? [...errors, "…"] : []), ...tail].join("\n")
}

// The engineer's Wi-Fi and MQTT credentials (BRINGUP_SECRETS: a secrets.h of their own) are force-included by the
// compiler from where they are, never copied into the firmware folder: a linked folder is a git repo that commits
// what is generated there.
function secretsFlags(): Record<string, string> {
	const path = process.env.BRINGUP_SECRETS
	if (!path || !existsSync(path)) return {}
	const own = process.env.PLATFORMIO_BUILD_FLAGS ? `${process.env.PLATFORMIO_BUILD_FLAGS} ` : ""
	return { PLATFORMIO_BUILD_FLAGS: `${own}-include "${resolvePath(path)}"` }
}

function run(cmd: string, args: string[]): Promise<{ code: number | null; output: string }> {
	return new Promise((resolve) => {
		let output = ""
		const child = spawn(cmd, args, { stdio: ["ignore", "pipe", "pipe"], timeout: TIMEOUT_MS, env: { ...process.env, ...secretsFlags() } })
		child.stdout.on("data", (d) => { output += d })
		child.stderr.on("data", (d) => { output += d })
		child.on("error", (e) => { output += `\n${e.message}`; resolve({ code: null, output }) })
		child.on("close", (code) => resolve({ code, output }))
	})
}

// Copies templates/fw into dir, writes include/pins.h, include/behavior.h and include/model.h and compiles it. A failed
// build returns ok: false.
export async function buildFirmware(pio: string, root: string, dir: string, s: ContractSnapshot, revision: number, opts: { modelData?: string } = {}): Promise<FirmwareArtifact> {
	const header = await prepareFirmware(root, dir, s, opts)
	const { code, output } = await run(pio, ["run", "-d", dir])
	const artifact: FirmwareArtifact = {
		revision,
		ok: code === 0,
		pins: parsePinsHeader(header),
		sensor: parseSensorHeader(header),
		log: buildLog(output),
	}
	// The drivers run on the host against simulated chips, with this build's headers (driver-tests.ts). Their output
	// stays next to the firmware as evidence.
	if (artifact.ok) {
		const t = await runDriverTests(dir, s)
		artifact.driverTests = { ok: t.ok, drivers: t.drivers, passed: t.passed.length, failed: t.failed, ...(t.skipped ? { skipped: t.skipped } : {}) }
		await writeFile(join(dir, "driver-tests.txt"), t.skipped ? `skipped: ${t.skipped}\n` : `${t.log}\n`)
	}
	return artifact
}

// The template copied into dir with the design's headers (pins.h, behavior.h, model.h); returns pins.h. Every env
// in the template builds from these, so the product, data-collection and factory-test firmware agree on the pins.
export async function prepareFirmware(root: string, dir: string, s: ContractSnapshot, opts: { modelData?: string } = {}): Promise<string> {
	// A CNC on grblHAL (gap 11): its board map and settings beside the firmware, from the pin map and the machine. The
	// product firmware still builds below, the proof that the pin map compiles on the chip; grblHAL itself builds from its
	// own repository with this map (grblhal/README.txt).
	if (s.values.cnc?.firmware === "grblhal") await writeGrblhal(dir, s)
	if (s.values.cnc?.firmware === "fluidnc") await writeFluidnc(dir, s)
	// A robot arm gets the arm firmware (templates/fw-arm): IK, moves and the pick plan behind one servo interface.
	if (s.values.arm && s.values.armTargets) {
		const arm = armHeader(s)
		await cp(join(root, "templates/fw-arm"), dir, { recursive: true })
		await mkdir(join(dir, "include"), { recursive: true })
		await writeFile(join(dir, "include/arm.h"), arm)
		const env = envFor(mcuProfileOf(s.values.parts), "app")
		const ini = join(dir, "platformio.ini")
		const text = await readFile(ini, "utf8")
		if (!new RegExp(`^\\[env:${env}\\]`, "m").test(text)) throw new Error(`the arm firmware has no build for the ${mcuProfileOf(s.values.parts)?.mpn} (no [env:${env}] in templates/fw-arm/platformio.ini)`)
		await writeFile(ini, text.replace(/^default_envs = .*$/m, `default_envs = ${env}`))
		return arm
	}
	// A robot (docs/mechanics.md) gets the rover firmware: the control logic behind the four-function hardware layer.
	if (s.values.mechanics && s.values.motion) {
		const rover = roverHeader(s)
		await cp(join(root, "templates/fw-rover"), dir, { recursive: true })
		await mkdir(join(dir, "include"), { recursive: true })
		await writeFile(join(dir, "include/hw_pins.h"), rover)
		await copyDrivers(root, dir)
		// The payload goes out as BTHome with the logger's encoder: one file, checked once (test/bthome.test.ts).
		await cp(join(root, "templates/fw/include/bthome.h"), join(dir, "include/bthome.h"))
		// Its links to the system's other boards: the same link.h and frame code as the product firmware (a board with no
		// links gets stubs).
		await writeFile(join(dir, "include/link.h"), linkHeader(s))
		await writeDsdl(dir, s)
		await cp(join(root, "templates/fw/include/linkframe.h"), join(dir, "include/linkframe.h"))
		await cp(join(root, "templates/fw/include/linkcbor.h"), join(dir, "include/linkcbor.h"))
		await cp(join(root, "templates/fw/include/linkcyphal.h"), join(dir, "include/linkcyphal.h"))
		// The robot's own chip (an ESP32-S3 moved up for its pins, contract/mcu-move.ts): `pio run` builds that chip's env
		// of the rover template, never the C3's on another chip.
		const roverEnv = envFor(mcuProfileOf(s.values.parts), "app")
		const rIni = join(dir, "platformio.ini")
		const rText = await readFile(rIni, "utf8")
		if (!new RegExp(`^\\[env:${roverEnv}\\]`, "m").test(rText)) throw new Error(`the rover firmware has no build for the ${mcuProfileOf(s.values.parts)?.mpn} (no [env:${roverEnv}] in templates/fw-rover/platformio.ini)`)
		await writeFile(rIni, rText.replace(/^default_envs = .*$/m, `default_envs = ${roverEnv}`))
		return rover
	}
	const header = pinsHeader(s)
	await cp(join(root, "templates/fw"), dir, { recursive: true })
	await mkdir(join(dir, "include"), { recursive: true })
	// A converted model (py/quantize.py model_data.cc) replaces the weights placeholder, so flash holds the real model.
	// Without one, a model left in a reused dir is removed, or __has_include would link it silently.
	if (opts.modelData && s.values.model) {
		await cp(opts.modelData, join(dir, "src/model_data.cc"))
		await writeFile(join(dir, "include/model_data.h"), MODEL_DATA_HEADER)
	} else {
		await rm(join(dir, "src/model_data.cc"), { force: true })
		await rm(join(dir, "include/model_data.h"), { force: true })
	}
	await writeFile(join(dir, "include/pins.h"), header)
	await copyDrivers(root, dir)
	await writeFile(join(dir, "include/behavior.h"), behaviorHeader(s))
	await writeFile(join(dir, "include/model.h"), modelHeader(s))
	await writeFile(join(dir, "include/connectivity.h"), connectivityHeader(s))
	await writeFile(join(dir, "include/link.h"), linkHeader(s))
	await writeDsdl(dir, s)
	// The data format, and the reader made from the same source: whoever reads the device decodes what it writes.
	await writeFile(join(dir, "include/dataformat.h"), dataFormatHeader())
	await mkdir(join(dir, "reader"), { recursive: true })
	await writeFile(join(dir, "reader/bringup_reader.py"), readerPython(s))
	// What the firmware is built from (CycloneDX), and where the design stands against the radio-product rules.
	await writeFile(join(dir, "compliance.md"), complianceMarkdown(s))
	const ini = join(dir, "platformio.ini")
	const text = await readFile(ini, "utf8")
	await writeFile(join(dir, "sbom.cdx.json"), sbomJson(s, text, s.revision))
	const profile = mcuProfileOf(s.values.parts)
	// Another ESP32-family chip: the C3's envs cloned for it (esp32FamilyEnvs), its product env the default; the
	// partition table below goes on its product env.
	const appEnv = envFor(profile, "app")
	if (profile && profile.firmware.arch === "esp32" && appEnv !== "esp32c3") {
		const own = `${text.replace(/^default_envs = .*$/m, `default_envs = ${appEnv}`).trimEnd()}\n\n${esp32FamilyEnvs(text, profile)}`
		await writeFile(ini, own.replace(new RegExp(`(\\[env:${appEnv}\\]\\n(?:[^\\[]*?\\n)?board = [^\\n]+\\n)(board_build\\.partitions = .*\\n)?`), `$1board_build.partitions = ${partitionTable(s)}\n`))
		return header
	}
	if (profile && profile.firmware.arch !== "esp32") {
		// Another chip: its envs, generated from its profile, appended; `pio run` with no -e builds its product env. The
		// template's ESP32 envs stay in the file, unbuilt.
		const own = text.replace(/^default_envs = .*$/m, `default_envs = ${envFor(profile, "app")}`)
		await writeFile(ini, `${own.trimEnd()}\n\n${platformioEnvs(profile)}`)
		return header
	}
	// The product firmware's partition table follows connectivity.updates: two firmware slots for updates, else one.
	const table = partitionTable(s)
	await writeFile(ini, text.replace(/(\[env:esp32c3\]\n(?:[^\[]*?\n)?board = esp32-c3-devkitm-1\n)(board_build\.partitions = .*\n)?/, `$1board_build.partitions = ${table}\n`))
	return header
}

// The motor and sensor drivers both firmwares include (include/drivers), and their host tests with the host's stand-ins
// for Arduino.h and Wire.h (test_host; driver-tests.ts runs them). test_host sits outside src/ and test/, so no
// PlatformIO env builds it.
async function copyDrivers(root: string, dir: string): Promise<void> {
	await mkdir(join(dir, "include/drivers"), { recursive: true })
	for (const f of ["sensirion.h", "drv8833.h", "vl53l0x.h", "lsm6ds3.h"]) await cp(join(root, "templates/drivers", f), join(dir, "include/drivers", f))
	await cp(join(root, "templates/drivers/host"), join(dir, "test_host"), { recursive: true })
}

// The env a firmware dir prepareFirmware wrote builds for this purpose: its product env (default_envs, which
// prepareFirmware set from envFor(mcuProfileOf(parts))) with the purpose's suffix, as envFor names it.
export async function firmwareEnv(dir: string, purpose: FirmwarePurpose): Promise<string> {
	const text = await readFile(join(dir, "platformio.ini"), "utf8").catch(() => "")
	const app = /^default_envs = (\S+)\s*$/m.exec(text)?.[1] ?? envFor(null, "app")
	return purpose === "app" ? app : `${app}_${purpose}`
}

// The factory-test firmware (env esp32c3_test, src/factory_test.cpp) for this revision, in its own dir.
export async function buildTestFirmware(pio: string, root: string, dir: string, s: ContractSnapshot): Promise<{ ok: boolean; log: string; pins: Record<string, number> }> {
	const header = await prepareFirmware(root, dir, s)
	await writeFile(join(dir, "include/testkit.h"), testkitHeader(s))
	const { code, output } = await run(pio, ["run", "-d", dir, "-e", envFor(mcuProfileOf(s.values.parts), "test")])
	return { ok: code === 0, log: buildLog(output), pins: parsePinsHeader(header) }
}

// The link-test firmware (env esp32c3_linktest: the product firmware with -DLINK_TEST) in a firmware dir buildFirmware
// already wrote, so it runs the board's own link.h (docs/system.md).
// The link-test build: esp32c3_linktest for QEMU (UART0 output, 10 s), or esp32c3_linktest_usb for the bench; by
// default the dir's own chip's link test (firmwareEnv).
export async function buildLinkTestFirmware(pio: string, dir: string, env?: string): Promise<{ ok: boolean; log: string }> {
	const { code, output } = await run(pio, ["run", "-d", dir, "-e", env ?? (await firmwareEnv(dir, "linktest"))])
	return { ok: code === 0, log: buildLog(output) }
}

export interface CollectFirmware {
	ok: boolean
	revision: number
	pathHash: string | null
	log: string
}

// The data-collection firmware (env esp32c3_collect, src/collect.cpp) in a firmware dir buildFirmware already wrote:
// the same pins.h and model.h, so it reads the sensor exactly as the design says. On demand (bringup
// collect-firmware), not on every rebuild: each revision's dir is a fresh copy, so it would compile the Arduino core
// a second time per revision.
export async function buildCollectFirmware(pio: string, dir: string, revision: number): Promise<CollectFirmware> {
	const header = await readFile(join(dir, "include/model.h"), "utf8").catch(() => "")
	const pathHash = /#define MODEL_PATH_HASH "([0-9a-f]{12})"/.exec(header)?.[1] ?? null
	if (!pathHash) return { ok: false, revision, pathHash, log: "model.h has no sensor path: the design has no model with a microphone" }
	const { code, output } = await run(pio, ["run", "-d", dir, "-e", await firmwareEnv(dir, "collect")])
	return { ok: code === 0, revision, pathHash, log: buildLog(output) }
}

export interface DeviceModelCheck {
	ran: boolean
	ok: boolean
	// What TensorFlow Lite Micro allocated on the target (arena_used_bytes), bytes.
	arenaUsedBytes?: number
	log: string
}

// The converted model run once on the design's MCU (env esp32c3_infer, src/infer.cpp, in QEMU) in a firmware dir that
// buildFirmware wrote with the model linked (opts.modelData). Not run when QEMU isn't installed.
export async function checkModelOnDevice(pio: string, root: string, dir: string): Promise<DeviceModelCheck> {
	const env = await firmwareEnv(dir, "infer")
	const build = await run(pio, ["run", "-d", dir, "-e", env])
	if (build.code !== 0) return { ran: false, ok: false, log: buildLog(build.output) }
	const { image, log } = await mergeFlash(dir, env)
	if (!image) return { ran: false, ok: false, log }
	const serial = await runImage(root, image, /BRINGUP-INFER (ok|FAIL)[^\n]*\n/, 180_000)
	if (serial === null) return { ran: false, ok: false, log: "QEMU is not installed (tools/qemu)" }
	const line = /BRINGUP-INFER (ok|FAIL)([^\n]*)/.exec(serial)
	if (!line) return { ran: true, ok: false, log: serial.slice(-2000) }
	const used = /arena_used=(\d+)/.exec(line[2])
	return { ran: true, ok: line[1] === "ok", arenaUsedBytes: used ? Number(used[1]) : undefined, log: line[0] }
}

// The CAN messages' DSDL definitions beside the firmware (codegen/firmware.ts dsdlFiles), for yakut or pycyphal.
async function writeDsdl(dir: string, s: ContractSnapshot): Promise<void> {
	for (const f of dsdlFiles(s)) {
		await mkdir(dirname(join(dir, f.path)), { recursive: true })
		await writeFile(join(dir, f.path), f.text)
	}
}

async function writeGrblhal(dir: string, s: ContractSnapshot): Promise<void> {
	const out = join(dir, "grblhal")
	await mkdir(out, { recursive: true })
	await writeFile(join(out, "my_machine_map.h"), grblhalMap(s))
	const cat = defaultCheckCatalog()
	const settings = cat ? grblhalSettings(s, cat.mech) : null
	if (settings) await writeFile(join(out, "settings.txt"), grblhalSettingsText(settings))
	await writeFile(join(out, "platformio_env.ini"), grblhalEnv())
	// The spindle's stall stop (its plugin and detector), when the board measures the spindle's current.
	const stall = cat ? stallParams(s, cat) : null
	if (stall) {
		await writeFile(join(out, "bringup_stall.h"), stallHeader(stall))
		await writeFile(join(out, "bringup_stall.c"), stallPlugin(stall))
	}
	await writeFile(join(out, "README.txt"), GRBLHAL_README)
}

// FluidNC for the CNC (src/cnc/fluidnc.ts): its config.yaml and how to put it on the controller. Pin problems the checks
// also report (cnc-wiring) are listed in the README, so a config written before the pins are fixed says what's wrong.
async function writeFluidnc(dir: string, s: ContractSnapshot): Promise<void> {
	const cat = defaultCheckCatalog()
	const config = cat ? fluidncConfig(s, cat.mech) : null
	if (!config) return
	const out = join(dir, "fluidnc")
	await mkdir(out, { recursive: true })
	await writeFile(join(out, "config.yaml"), config)
	const problems = fluidncPinProblems(s)
	await writeFile(join(out, "README.txt"), FLUIDNC_README + (problems.length ? `\nPIN PROBLEMS (fix the pin map before flashing):\n${problems.map((p) => `- ${p}`).join("\n")}\n` : ""))
}

