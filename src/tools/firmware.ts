const TIMEOUT_MS = 600_000

// Declares py/quantize.py's model array for the template (templates/fw/src/main.cpp includes it when present).
const MODEL_DATA_HEADER = "// Generated by Bringup: the converted model, linked from model_data.cc. Do not edit.\n#pragma once\n#include <stdint.h>\nextern const uint8_t g_model[];\nextern const unsigned int g_model_len;\n"
const LOG_LINES = 60
const ERROR_LINES = 20

// The build's tail, preceded by its compiler errors when they scrolled out of it. With NimBLE in the build, hundreds of
// library compile lines can follow the error, and the agents read this log when a firmware build fails.
export function buildLog(output: string): string {
	const lines = output.trimEnd().split("\n")
	const tail = lines.slice(-LOG_LINES)
	const errors = lines.slice(0, -LOG_LINES).filter((l) => /\berror\b|static assertion/i.test(l)).slice(0, ERROR_LINES)
	return [...(errors.length ? [...errors, "…"] : []), ...tail].join("\n")
}

// The engineer's Wi-Fi and MQTT credentials (BRINGUP_SECRETS: a secrets.h of their own) are force-included by the
// compiler from where they are, never copied into the firmware folder: a linked folder is a git repo that commits
// what is generated there.
function secretsFlags(): Record<string, string> {
	const path = process.env.BRINGUP_SECRETS
	if (!path || !existsSync(path)) return {}
	const own = process.env.PLATFORMIO_BUILD_FLAGS ? `${process.env.PLATFORMIO_BUILD_FLAGS} ` : ""
	return { PLATFORMIO_BUILD_FLAGS: `${own}-include "${resolvePath(path)}"` }
}

function run(cmd: string, args: string[]): Promise<{ code: number | null; output: string }> {
	return new Promise((resolve) => {
		let output = ""
		const child = spawn(cmd, args, { stdio: ["ignore", "pipe", "pipe"], timeout: TIMEOUT_MS, env: { ...process.env, ...secretsFlags() } })
		child.stdout.on("data", (d) => { output += d })
		child.stderr.on("data", (d) => { output += d })
		child.on("error", (e) => { output += `\n${e.message}`; resolve({ code: null, output }) })
		child.on("close", (code) => resolve({ code, output }))
	})
}

// Copies templates/fw into dir, writes include/pins.h, include/behavior.h and include/model.h and compiles it. A failed
// build returns ok: false.
export async function buildFirmware(pio: string, root: string, dir: string, s: ContractSnapshot, revision: number, opts: { modelData?: string } = {}): Promise<FirmwareArtifact> {
	const header = await prepareFirmware(root, dir, s, opts)
	const { code, output } = await run(pio, ["run", "-d", dir])
	const artifact: FirmwareArtifact = {
		revision,
		ok: code === 0,
		pins: parsePinsHeader(header),
		sensor: parseSensorHeader(header),
		log: buildLog(output),
	}
	return artifact
}

// The template copied into dir with the design's headers (pins.h, behavior.h, model.h); returns pins.h. Every env
// in the template builds from these, so the product, data-collection and factory-test firmware agree on the pins.
export async function prepareFirmware(root: string, dir: string, s: ContractSnapshot, opts: { modelData?: string } = {}): Promise<string> {
	const header = pinsHeader(s)
	await cp(join(root, "templates/fw"), dir, { recursive: true })
	await mkdir(join(dir, "include"), { recursive: true })
	// A converted model (py/quantize.py model_data.cc) replaces the weights placeholder, so flash holds the real model.
	// Without one, a model left in a reused dir is removed, or __has_include would link it silently.
	if (opts.modelData && s.values.model) {
		await cp(opts.modelData, join(dir, "src/model_data.cc"))
		await writeFile(join(dir, "include/model_data.h"), MODEL_DATA_HEADER)
	} else {
		await rm(join(dir, "src/model_data.cc"), { force: true })
		await rm(join(dir, "include/model_data.h"), { force: true })
	}
	await writeFile(join(dir, "include/pins.h"), header)
	await writeFile(join(dir, "include/behavior.h"), behaviorHeader(s))
	await writeFile(join(dir, "include/model.h"), modelHeader(s))
	await writeFile(join(dir, "include/connectivity.h"), connectivityHeader(s))
	await writeFile(join(dir, "include/link.h"), linkHeader(s))
	// The data format, and the reader made from the same source: whoever reads the device decodes what it writes.
	await writeFile(join(dir, "include/dataformat.h"), dataFormatHeader())
	await mkdir(join(dir, "reader"), { recursive: true })
	await writeFile(join(dir, "reader/bringup_reader.py"), readerPython(s))
	// What the firmware is built from (CycloneDX), and where the design stands against the radio-product rules.
	await writeFile(join(dir, "compliance.md"), complianceMarkdown(s))
	// The product firmware's partition table follows connectivity.updates: two firmware slots for updates, else one.
	const ini = join(dir, "platformio.ini")
	const table = partitionTable(s)
	const text = await readFile(ini, "utf8")
	await writeFile(join(dir, "sbom.cdx.json"), sbomJson(s, text, s.revision))
	await writeFile(ini, text.replace(/(\[env:esp32c3\]\n(?:[^\[]*?\n)?board = esp32-c3-devkitm-1\n)(board_build\.partitions = .*\n)?/, `$1board_build.partitions = ${table}\n`))
	return header
}

// The factory-test firmware (env esp32c3_test, src/factory_test.cpp) for this revision, in its own dir.
export async function buildTestFirmware(pio: string, root: string, dir: string, s: ContractSnapshot): Promise<{ ok: boolean; log: string; pins: Record<string, number> }> {
	const header = await prepareFirmware(root, dir, s)
	await writeFile(join(dir, "include/testkit.h"), testkitHeader(s))
	const { code, output } = await run(pio, ["run", "-d", dir, "-e", "esp32c3_test"])
	return { ok: code === 0, log: buildLog(output), pins: parsePinsHeader(header) }
}

// The link-test firmware (env esp32c3_linktest: the product firmware with -DLINK_TEST) in a firmware dir buildFirmware
// already wrote, so it runs the board's own link.h (docs/system.md).
export async function buildLinkTestFirmware(pio: string, dir: string): Promise<{ ok: boolean; log: string }> {
	const { code, output } = await run(pio, ["run", "-d", dir, "-e", "esp32c3_linktest"])
	return { ok: code === 0, log: buildLog(output) }
}

export interface CollectFirmware {
	ok: boolean
	revision: number
	pathHash: string | null
	log: string
}

// The data-collection firmware (env esp32c3_collect, src/collect.cpp) in a firmware dir buildFirmware already wrote:
// the same pins.h and model.h, so it reads the sensor exactly as the design says. On demand (bringup
// collect-firmware), not on every rebuild: each revision's dir is a fresh copy, so it would compile the Arduino core
// a second time per revision.
export async function buildCollectFirmware(pio: string, dir: string, revision: number): Promise<CollectFirmware> {
	const header = await readFile(join(dir, "include/model.h"), "utf8").catch(() => "")
	const pathHash = /#define MODEL_PATH_HASH "([0-9a-f]{12})"/.exec(header)?.[1] ?? null
	if (!pathHash) return { ok: false, revision, pathHash, log: "model.h has no sensor path: the design has no model with a microphone" }
	const { code, output } = await run(pio, ["run", "-d", dir, "-e", "esp32c3_collect"])
	return { ok: code === 0, revision, pathHash, log: buildLog(output) }
}

export interface DeviceModelCheck {
	ran: boolean
	ok: boolean
	// What TensorFlow Lite Micro allocated on the target (arena_used_bytes), bytes.
	arenaUsedBytes?: number
	log: string
}

// The converted model run once on the design's MCU (env esp32c3_infer, src/infer.cpp, in QEMU) in a firmware dir that
// buildFirmware wrote with the model linked (opts.modelData). Not run when QEMU isn't installed.
export async function checkModelOnDevice(pio: string, root: string, dir: string): Promise<DeviceModelCheck> {
	const build = await run(pio, ["run", "-d", dir, "-e", "esp32c3_infer"])
	if (build.code !== 0) return { ran: false, ok: false, log: buildLog(build.output) }
	const { image, log } = await mergeFlash(dir, "esp32c3_infer")
	if (!image) return { ran: false, ok: false, log }
	const serial = await runImage(root, image, /BRINGUP-INFER (ok|FAIL)[^\n]*\n/, 180_000)
	if (serial === null) return { ran: false, ok: false, log: "QEMU is not installed (tools/qemu)" }
	const line = /BRINGUP-INFER (ok|FAIL)([^\n]*)/.exec(serial)
	if (!line) return { ran: true, ok: false, log: serial.slice(-2000) }
	const used = /arena_used=(\d+)/.exec(line[2])
	return { ran: true, ok: line[1] === "ok", arenaUsedBytes: used ? Number(used[1]) : undefined, log: line[0] }
}

