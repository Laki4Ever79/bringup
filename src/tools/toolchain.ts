// The toolchain image (docker/toolchain/Dockerfile): tscircuit, Python with build123d and MuJoCo, and PlatformIO for a
// machine that never ran `npm run setup`, such as an `npx bringup-mcp` install. Without it such a machine stubbed every
// build (bringup-mcp 0.2.0 in an empty folder, 25 Nov 2026). Each tool runs through a small shim script, so the callers
// keep calling env.tsci, env.python and env.pio as before: the shim runs the tool in the image as the calling user, with
// the caller's folders mounted at their own paths (the paths in the arguments stay valid) and host networking (ports on
// localhost reach it, as a local process).
import { createHash } from "node:crypto"
import { chmodSync, existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs"
import { homedir, tmpdir } from "node:os"
import { join, resolve, sep } from "node:path"
import { run } from "./exec.ts"
import { KICAD_IMAGE } from "./env.ts"

export const TOOLCHAIN_DOCKERFILE = "docker/toolchain/Dockerfile"
// Everything the image is built from: a change to any of them changes the tag, so a stale image is never used.
const INPUTS = [TOOLCHAIN_DOCKERFILE, `${TOOLCHAIN_DOCKERFILE}.dockerignore`, "src/setup/tools-node/package.json", "src/setup/tools-node/package-lock.json", "templates/fw/platformio.ini", "templates/fw-rover/platformio.ini"]
// Where each tool lives in the image.
export const IN_IMAGE = { tsci: "/opt/bringup/tools/node/node_modules/.bin/tsci", python: "/opt/bringup/.venv/bin/python", pio: "/opt/bringup/.venv/bin/pio" } as const
export type Tool = keyof typeof IN_IMAGE
// Settings the callers pass to the tools through the environment (drive.ts: PLATFORMIO_BUILD_FLAGS, PYTHONPATH).
const FORWARD = /^(PYTHONPATH|PLATFORMIO_[A-Z_]+|MUJOCO_GL|BRINGUP_[A-Z_]+)$/

export function toolchainImage(root: string): string | null {
	const h = createHash("sha256")
	for (const f of INPUTS) {
		const p = join(root, f)
		if (!existsSync(p)) return null
		h.update(f).update("\0").update(readFileSync(p)).update("\0")
	}
	return `bringup-toolchain:${h.digest("hex").slice(0, 12)}`
}

export async function dockerUsable(): Promise<boolean> {
	return (await run("docker", ["info", "--format", "{{.ServerVersion}}"], { timeoutMs: 15_000 })).code === 0
}

export async function imagePresent(image: string): Promise<boolean> {
	return (await run("docker", ["image", "inspect", image], { timeoutMs: 15_000 })).code === 0
}

// The folders a tool may be handed paths in: the package (py/ scripts, templates), the temporary folder (board builds),
// the home folder (~/.bringup/runs, an npx cache) and the current folder. Nested ones are covered by their parent.
export function mountDirs(root: string, extra: string[] = []): string[] {
	const real = (d: string) => (existsSync(d) ? realpathSync(d) : null)
	const dirs = [root, tmpdir(), homedir(), process.cwd(), ...extra].map(real).filter((d): d is string => d !== null && d !== sep)
	const unique = [...new Set(dirs)].sort((a, b) => a.length - b.length)
	return unique.filter((d, i) => !unique.slice(0, i).some((p) => d.startsWith(p + sep)))
}

const q = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`

// The shim for one tool: a bash script that runs it in the image. The caller's current folder is mounted too when it
// lies outside the fixed ones, and the forwarded settings go along by name (docker reads their values from the shim's
// environment, so none is written into the script).
export function shimScript(tool: Tool, image: string, dirs: string[]): string {
	return [
		"#!/usr/bin/env bash",
		`# Generated by Bringup (src/tools/toolchain.ts): runs ${tool} in the toolchain image ${image}.`,
		`dirs=(${dirs.map(q).join(" ")})`,
		`args=(run --rm -i --init --network host -u "$(id -u):$(id -g)" -e HOME="$HOME" -w "$PWD")`,
		`inside() { local d; for d in "\${dirs[@]}"; do case "$1/" in "$d"/*) return 0;; esac; done; return 1; }`,
		`for d in "\${dirs[@]}"; do args+=(-v "$d:$d"); done`,
		`inside "$PWD" || args+=(-v "$PWD:$PWD")`,
		`for v in $(compgen -e); do [[ $v =~ ${FORWARD.source} ]] && args+=(-e "$v"); done`,
		`exec docker "\${args[@]}" ${q(image)} ${IN_IMAGE[tool]} "$@"`,
		"",
	].join("\n")
}

// Writes the three shims for this image and returns their paths. One folder per user and image, rewritten each time
// (the mount list can differ between runs).
export function writeShims(image: string, dirs: string[]): Record<Tool, string> {
	const uid = process.getuid?.() ?? 0
	const dir = join(tmpdir(), `bringup-toolchain-${uid}-${image.split(":")[1]}`)
	mkdirSync(dir, { recursive: true })
	const out = {} as Record<Tool, string>
	for (const tool of Object.keys(IN_IMAGE) as Tool[]) {
		const p = join(dir, tool)
		writeFileSync(p, shimScript(tool, image, dirs))
		chmodSync(p, 0o755)
		out[tool] = p
	}
	return out
}

export interface Prepared {
	ok: boolean
	image: string | null
	// What it had to do: build the toolchain image, pull KiCad's (first run only).
	built: boolean
	pulledKicad: boolean
	ms: number
	error?: string
}

// Makes sure both images are on this machine: builds the toolchain image from the package's Dockerfile and pulls
// KiCad's. Minutes and a few GB on the first run; nothing after that. Its output goes to log line by line.
export async function prepareToolchain(root: string, log: (line: string) => void, timeoutMs = 3_600_000): Promise<Prepared> {
	const t0 = Date.now()
	const image = toolchainImage(root)
	const done = (p: Omit<Prepared, "ms" | "image">): Prepared => ({ ...p, image, ms: Date.now() - t0 })
	if (!image) return done({ ok: false, built: false, pulledKicad: false, error: `the toolchain's Dockerfile or its inputs are missing under ${root}` })
	if (!(await dockerUsable())) return done({ ok: false, built: false, pulledKicad: false, error: "Docker isn't usable here (not installed, not running, or it needs sudo)" })
	let built = false
	if (!(await imagePresent(image))) {
		log(`toolchain: building ${image} from ${TOOLCHAIN_DOCKERFILE} (first run only: several minutes and a few GB)`)
		const r = await run("docker", ["build", "-f", join(root, TOOLCHAIN_DOCKERFILE), "-t", image, resolve(root)], { timeoutMs })
		if (r.code !== 0) return done({ ok: false, built: false, pulledKicad: false, error: `docker build failed: ${r.stderr.trim().split("\n").slice(-5).join("\n")}` })
		built = true
	}
	let pulledKicad = false
	if (!(await imagePresent(KICAD_IMAGE))) {
		log(`toolchain: pulling ${KICAD_IMAGE} (first run only)`)
		const r = await run("docker", ["pull", KICAD_IMAGE], { timeoutMs })
		if (r.code !== 0) return done({ ok: false, built, pulledKicad: false, error: `docker pull ${KICAD_IMAGE} failed: ${r.stderr.trim().split("\n").slice(-3).join("\n")}` })
		pulledKicad = true
	}
	return done({ ok: true, built, pulledKicad })
}
