import type { McuProfile } from "./profile.ts"
import { pinIndex, pinName } from "./pins.ts"

// The firmware side of a profile (docs/mcu.md, Firmware): the PlatformIO env each build runs under, the env's text,
// and how pins.h spells a pin. One template (templates/fw) builds for every profile; its HAL (include/hal.h) picks the
// vendor code by the core's ARDUINO_ARCH_* macro.

export type FirmwarePurpose = "app" | "test" | "collect" | "infer" | "linktest" | "linktest_usb"

// The env name: the profile's firmware.env (the ESP32-C3 keeps "esp32c3", so saved runs and docs still match), else
// its id with dashes as underscores; a purpose other than the product app adds its suffix.
export function envFor(p: McuProfile | null | undefined, purpose: FirmwarePurpose = "app"): string {
	const base = p ? (p.firmware.env ?? p.id.replace(/[^A-Za-z0-9_]/g, "_")) : "esp32c3"
	return purpose === "app" ? base : `${base}_${purpose}`
}

// How pins.h writes a pin: the index for cores that number GPIOs (ESP32, RP2040), the core's own macro for the others
// (PA5 on STM32duino, which its variant defines).
export function pinSpelling(p: McuProfile | null | undefined, index: number): string {
	return p?.firmware.pinStyle === "name" ? pinName(p, index) : String(index)
}

// Libraries hal.h needs on each core, beside the profile's own (exact versions, like every library the template pins).
// STM32: the core's EEPROM emulation (built in, named so the library finder builds it: hal.h includes it by macro) and
// STM32duino Low Power with the RTC it sleeps on (July 2025 releases, built against core 2.12 / framework 4.21200).
const HAL_LIBS: Partial<Record<McuProfile["firmware"]["arch"], string[]>> = {
	stm32: ["EEPROM", "stm32duino/STM32duino Low Power@1.5.0", "stm32duino/STM32duino RTC@1.8.0"],
}
// RP2040 (Arduino's mbed core, framework-arduino-mbed 4.6.0) and nRF52 (Adafruit nRF52 core 1.7.0): everything hal.h
// uses ships with the core (Wire, mbed's LittleFileSystem and FlashIAPBlockDevice; Adafruit's InternalFileSystem and
// Bluefruit52Lib), so nothing is added.

// Core libraries the env must not build. PlatformIO's library finder (chain mode) follows every literal #include, also
// in code an #if leaves out: main.cpp's Wi-Fi path (#include <WiFi.h>) would pull in the mbed core's WiFi library,
// which only builds for boards with a WHD radio (Portenta) and fails on the RP2040.
const HAL_LIB_IGNORE: Partial<Record<McuProfile["firmware"]["arch"], string[]>> = {
	rp2040: ["WiFi"],
}
// Compiler flags hal.h needs on each core. None so far: newlib-nano's float printf (PIO_FRAMEWORK_ARDUINO_NANOLIB_FLOAT_PRINTF)
// would cost about 19 KB of the STM32G031's 64 KB, so hal.h prints readings with halFixed() instead.
const HAL_FLAGS: Partial<Record<McuProfile["firmware"]["arch"], string[]>> = {}

// The purposes a profile's generated envs cover: the product and its link test. The factory-test, data-collection and
// model-check firmware use ESP32 drivers (ESP_I2S, bootloader_random, ESP-TF) and build for the ESP32 only so far.
export const GENERATED_PURPOSES: readonly FirmwarePurpose[] = ["app", "linktest"]

// platformio.ini env sections for a profile, from its firmware block: the product env and the link test (-DLINK_TEST).
// The ESP32-C3's envs are written by hand in templates/fw/platformio.ini and are never generated.
// profile.firmware.flags holds both ini lines ("board_build.flash_mode = dio") and compiler flags ("-DX"); each goes
// where it belongs.
export function platformioEnvs(p: McuProfile): string {
	const f = p.firmware
	const iniLines = (f.flags ?? []).filter((x) => /^\s*[\w.]+\s*=/.test(x))
	const cflags = [...(HAL_FLAGS[f.arch] ?? []), ...(f.flags ?? []).filter((x) => !/^\s*[\w.]+\s*=/.test(x))]
	const libs = [...(HAL_LIBS[f.arch] ?? []), ...(f.libs ?? [])]
	const section = (purpose: FirmwarePurpose, extra: string[]) => {
		const flags = [...cflags, ...extra]
		return [
			`[env:${envFor(p, purpose)}]`,
			`platform = ${f.platform}`,
			`board = ${f.board}`,
			`framework = ${f.framework}`,
			...iniLines,
			...(libs.length ? ["lib_deps =", ...libs.map((l) => `    ${l}`)] : []),
			...(HAL_LIB_IGNORE[f.arch]?.length ? [`lib_ignore = ${HAL_LIB_IGNORE[f.arch]!.join(", ")}`] : []),
			...(flags.length ? ["build_flags =", ...flags.map((x) => `    ${x}`)] : []),
		].join("\n")
	}
	return [
		`; Generated by Bringup for the ${p.mpn} (catalog/mcu/${p.id}.json, src/mcu/firmware.ts platformioEnvs). Do not edit.`,
		section("app", []),
		"",
		`; The link test (docs/system.md): the product firmware with -DLINK_TEST.`,
		// link.h prints f32 message fields with %.2f: the link test (29 KB on the STM32G031) can afford newlib-nano's float
		// printf (about 19 KB), which the product (45 KB) leaves out.
		section("linktest", ["-DLINK_TEST=1", ...(f.arch === "stm32" ? ["-DPIO_FRAMEWORK_ARDUINO_NANOLIB_FLOAT_PRINTF"] : [])]),
		"",
	].join("\n")
}
