import type { PinAssignment } from "../contract/types.ts"
import { pinName } from "./pins.ts"
import type { McuProfile } from "./profile.ts"

// The design's pin map as a Zephyr devicetree overlay (docs/mcu.md, Zephyr): the vendor-neutral firmware target. The
// same contract pins become pinctrl for the peripherals (STM32: hal_stm32's &i2c1_scl_pb6 labels; nRF: NRF_PSEL groups)
// and <name>-gpios under zephyr,user for plain pins. Building it needs the Zephyr SDK, which Bringup doesn't install
// yet; the overlay is generated and read back by the adopt reader (src/adopt/firmware.ts dtsPins).

// Which peripheral instance carries a bus, from the pins the contract gives: the one whose signals both pins carry.
function busInstance(p: McuProfile, kind: "i2c" | "uart", pins: { fn: string; index: number }[]): string | null {
	for (const inst of p.peripherals[kind]) {
		if (inst === p.console?.instance) continue
		if (pins.every(({ fn, index }) => p.pins.find((x) => x.index === index)?.signals.some((s) => s === "*" || s === `${inst}_${fn}`))) return inst
	}
	return null
}

const gpioRef = (p: McuProfile, index: number) =>
	p.vendor === "st" ? `&gpio${"abcdefghijk"[Math.floor(index / 16)]} ${index % 16}` : p.vendor === "nordic" ? `&gpio${Math.floor(index / 32)} ${index % 32}` : `&gpio0 ${index}`

// Zephyr's node for an instance: STM32 keeps ST's names lower-cased (usart1, i2c1); nRF's TWIM0/UARTE1 are i2c0/uart1.
const zNode = (p: McuProfile, inst: string) => (p.vendor === "nordic" ? inst.toLowerCase().replace(/^twim/, "i2c").replace(/^uarte/, "uart").replace(/^spim/, "spi") : inst.toLowerCase())

export function zephyrOverlay(p: McuProfile, pins: PinAssignment[]): { overlay: string; board: string | null } | { error: string } {
	if (p.vendor !== "st" && p.vendor !== "nordic") return { error: `no Zephyr overlay generator for ${p.vendor} yet (docs/mcu.md, Not done)` }
	const lines = ["/* Generated by Bringup from the design contract (docs/mcu.md, Zephyr). Do not edit. */", ""]
	const by = new Map(pins.map((x) => [x.signal, x]))
	const used = new Set<string>()
	const buses: { node: string; groups: [string, number][] }[] = []
	// The I2C bus and each UART link (<id>_TX/<id>_RX).
	const sda = by.get("I2C_SDA"), scl = by.get("I2C_SCL")
	if (sda && scl) {
		const inst = busInstance(p, "i2c", [{ fn: "SDA", index: sda.gpio }, { fn: "SCL", index: scl.gpio }])
		if (!inst) return { error: `I2C_SDA on ${pinName(p, sda.gpio)} and I2C_SCL on ${pinName(p, scl.gpio)} are not one I2C instance's pins on the ${p.mpn}` }
		buses.push({ node: zNode(p, inst), groups: [[`${inst}_SCL`, scl.gpio], [`${inst}_SDA`, sda.gpio]] })
		used.add("I2C_SDA").add("I2C_SCL")
	}
	for (const tx of pins.filter((x) => /_TX$/.test(x.signal))) {
		const rx = by.get(tx.signal.replace(/_TX$/, "_RX"))
		if (!rx) continue
		const inst = busInstance(p, "uart", [{ fn: "TX", index: tx.gpio }, { fn: "RX", index: rx.gpio }])
		if (!inst) return { error: `${tx.signal} and ${rx.signal} are not one UART instance's pins on the ${p.mpn}` }
		buses.push({ node: zNode(p, inst), groups: [[`${inst}_TX`, tx.gpio], [`${inst}_RX`, rx.gpio]] })
		used.add(tx.signal).add(rx.signal)
	}
	for (const b of buses) {
		if (p.vendor === "st") {
			const refs = b.groups.map(([sig, idx]) => `&${sig.toLowerCase()}_${pinName(p, idx).toLowerCase()}`)
			lines.push(`&${b.node} {`, `\tpinctrl-0 = <${refs.join(" ")}>;`, `\tpinctrl-names = "default";`, `\tstatus = "okay";`, `};`, "")
		} else {
			const psel = b.groups.map(([sig, idx]) => {
				const fn = sig.split("_").pop()!
				const kind = b.node.startsWith("i2c") ? "TWIM" : "UART"
				return `NRF_PSEL(${kind}_${fn}, ${Math.floor(idx / 32)}, ${idx % 32})`
			})
			lines.push(`&pinctrl {`, `\t${b.node}_default: ${b.node}_default {`, `\t\tgroup1 {`, `\t\t\tpsels = <${psel.join(">, <")}>;`, `\t\t};`, `\t};`, `};`, "")
			lines.push(`&${b.node} {`, `\tpinctrl-0 = <&${b.node}_default>;`, `\tpinctrl-names = "default";`, `\tstatus = "okay";`, `};`, "")
		}
	}
	const plain = pins.filter((x) => !used.has(x.signal))
	if (plain.length) {
		lines.push("/ {", "\tzephyr,user {")
		for (const x of plain) lines.push(`\t\t${x.signal.toLowerCase().replace(/_/g, "-")}-gpios = <${gpioRef(p, x.gpio)} GPIO_ACTIVE_HIGH>;`)
		lines.push("\t};", "};", "")
	}
	return { overlay: lines.join("\n"), board: p.firmware.zephyrBoard ?? null }
}
