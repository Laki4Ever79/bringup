// A `static const uint32_t NAME = N;` of the firmware template (templates/fw/src/main.cpp), so what the reviewer and the
// battery check are told about the firmware is read from the firmware itself. NaN if it is not there.
export function templateConstant(name: string): number {
	const main = readFileSync(resolve(import.meta.dirname, "../../templates/fw/src/main.cpp"), "utf8")
	return Number(new RegExp(`static const uint32_t ${name} = (\\d+)`).exec(main)?.[1] ?? NaN)
}

// The product firmware's wake (templates/fw): the reading (sensor, flash write, LED blink) takes about BLE_READING_MS,
// then it advertises over BLE for the rest of the contract's activeMs, never less than BLE_MIN_ADVERTISE_MS.
export const BLE_READING_MS = 30
export const BLE_MIN_ADVERTISE_MS = 50

export function bleAdvertiseMs(d: DutyCycle): number {
	return Math.max(BLE_MIN_ADVERTISE_MS, Math.round(d.activeMs - BLE_READING_MS))
}

export function macroName(signal: string): string {
	return `PIN_${signal.toUpperCase().replace(/[^A-Z0-9]/g, "_")}`
}

// The template's LittleFS partition: "spiffs" in Arduino-ESP32's default.csv (0x290000, 0x160000 bytes). A tenth is
// left for LittleFS's own blocks; the rest holds 4-byte readings.
export const HISTORY_PARTITION_BYTES = 0x160000
export const HISTORY_CAPACITY_BYTES = Math.floor(HISTORY_PARTITION_BYTES * 0.9)
export const HISTORY_RECORD_BYTES = 4
export const DEFAULT_HISTORY_DAYS = 30
export const DEFAULT_PERIOD_S = 300

// The firmware template's driver for a temperature/humidity sensor part (templates/fw/src/main.cpp), or null.
export function sensorDriver(mpn: string): "SHT40" | "SHTC3" | null {
	if (/^SHTC3/i.test(mpn)) return "SHTC3"
	if (/^SHT4/i.test(mpn)) return "SHT40"
	return null
}

// The history store of a chip whose profile doesn't give one (STM32 EEPROM emulation: at least a 1 KB flash page).
export const DEFAULT_HISTORY_STORE_BYTES = 1024
// The key-value slots hal.h keeps in front of the history on an EEPROM store (HAL_KV_BYTES: 8 slots of 8 bytes).
export const HAL_KV_BYTES = 64

// The design's chip, when it isn't an ESP32: its profile drives the parts of pins.h only other cores need. A design
// with no profile (every contract before profiles) or an ESP32 gets the header it always had.
function otherArch(s: ContractSnapshot): McuProfile | null {
	const p = mcuProfileOf(s.values.parts)
	return p && p.firmware.arch !== "esp32" ? p : null
}

// How many bytes of readings the chip's history store holds (pins.h HISTORY_BYTES): the profile's figure, less hal.h's
// key-value slots on an EEPROM store.
export function historyBytes(p: McuProfile): number {
	const h = p.firmware.history
	const bytes = h?.bytes ?? DEFAULT_HISTORY_STORE_BYTES
	return (h?.store ?? "eeprom") === "eeprom" ? bytes - HAL_KV_BYTES : bytes
}

// include/pins.h for the firmware template: one #define per pin assignment, and the sensor driver the parts call for.
// Pins are spelled as the chip's core does (pinSpelling: 4 on the ESP32, PB7 on STM32duino).
export function pinsHeader(s: ContractSnapshot): string {
	const lines = ["// Generated by Bringup from the design contract. Do not edit.", "#pragma once", ""]
	const profile = mcuProfileOf(s.values.parts)
	const other = otherArch(s)
	for (const p of s.values.pins ?? []) lines.push(`#define ${macroName(p.signal)} ${pinSpelling(profile, p.gpio)}`)
	const sensor = (s.values.parts ?? []).find((p) => p.role === "sensor")
	const driver = sensor ? sensorDriver(sensor.mpn) : null
	if (driver) lines.push(`#define SENSOR_${driver} 1`)
	// The product firmware deep-sleeps this long between readings; without a duty cycle it keeps the template's default.
	const period = s.values.requirements?.dutyCycle?.periodS
	if (period !== undefined && period > 0) lines.push(`#define DUTY_PERIOD_S ${Math.round(period)}`)
	// How many days of readings the firmware keeps; without one it keeps the template's default. A chip with a small
	// store keeps what fits.
	const days = s.values.requirements?.historyDays
	if (other) lines.push(...historyLines(other, days, period !== undefined && period > 0 ? period : DEFAULT_PERIOD_S))
	else if (days !== undefined) lines.push(`#define HISTORY_DAYS ${days}`)
	const duty = s.values.requirements?.dutyCycle
	if (duty) lines.push(`#define BLE_ADVERTISE_MS ${bleAdvertiseMs(duty)}`)
	// The VBUS-sense pin the board generator wired (codegen/circuit.ts usbWake): the firmware stays awake while it is high.
	const wake = usbWake(s)
	if (wake?.gpio != null) lines.push(`#define PIN_USB_SENSE ${pinSpelling(profile, wake.gpio)}`)
	// The console the firmware logs on and the simulator reads (hal.h): the profile's UART on its fixed pins. The ESP32
	// keeps its UART0 + USB console in hal.h.
	// The console pins spelled as the core wants them, like every other pin (PA2 on STM32duino, 0 on the RP2040 and nRF52
	// cores, which number pins by the same index the profile uses).
	const consolePin = (name: string) => {
		const index = other ? pinIndex(other, name) : null
		return index === null ? name : pinSpelling(other, index)
	}
	if (other?.console) lines.push(`#define BRINGUP_CONSOLE_INSTANCE ${other.console.instance}`, `#define BRINGUP_CONSOLE_TX ${consolePin(other.console.tx)}`, `#define BRINGUP_CONSOLE_RX ${consolePin(other.console.rx)}`)
	lines.push(`#define BRINGUP_REVISION ${s.revision}`, "")
	return lines.join("\n")
}

// HISTORY_BYTES and HISTORY_DAYS for a chip whose store is small: the days asked for (or the template's 30), capped to
// what the store holds at this period, with a comment saying so. Under a day's worth, the firmware keeps what fits.
function historyLines(p: McuProfile, days: number | undefined, periodS: number): string[] {
	const bytes = historyBytes(p)
	const want = days ?? DEFAULT_HISTORY_DAYS
	const fitDays = Math.floor(((bytes / HISTORY_RECORD_BYTES) * periodS) / 86400)
	const out = [`#define HISTORY_BYTES ${bytes}  // ${p.mpn} ${p.firmware.history?.store ?? "eeprom"} store${p.firmware.history ? `: ${p.firmware.history.source}` : ", Bringup's default"}`]
	if (want <= fitDays) return days === undefined ? out : [...out, `#define HISTORY_DAYS ${days}`]
	const capped = Math.max(1, fitDays)
	const hours = Math.floor(((bytes / HISTORY_RECORD_BYTES) * periodS) / 3600)
	out.push(`// The ${p.mpn} holds ${bytes / HISTORY_RECORD_BYTES} readings (${hours} h at one every ${periodS} s), not ${want} days: capped${fitDays < 1 ? "; the firmware keeps what fits" : ""}.`, `#define HISTORY_DAYS ${capped}`)
	return out
}

// The sensor driver a header selects, so checks run against what was compiled.
export function parseSensorHeader(text: string): string | null {
	return /^#define SENSOR_(\w+) 1\s*$/m.exec(text)?.[1] ?? null
}

// Reads the pins back out of a header, so checks run against what was compiled.
export function parsePinsHeader(text: string): Record<string, number> {
	const pins: Record<string, number> = {}
	// A pin is a number (ESP32) or the core's name for it (PB7 on STM32duino), read back as the contract's index.
	for (const m of text.matchAll(/^#define PIN_(\w+) (-?\d+|[A-Za-z][\w.]*)\s*$/gm)) {
		const index = /^-?\d+$/.test(m[2]) ? Number(m[2]) : pinIndex(null, m[2])
		if (index !== null) pins[m[1]] = index
	}
	// The rover's hw_pins.h (src/mechanics/firmware.ts) names its pins after the contract's signals directly.
	for (const m of text.matchAll(/^#define (MOT_[AB]IN[12]|I2C_SDA|I2C_SCL) (-?\d+)\s*$/gm)) pins[m[1]] = Number(m[2])
	return pins
}

// Without a behavior field the LED blinks at 1 Hz and tilt changes nothing (90° is never exceeded).
export const DEFAULT_BEHAVIOR = { blinkMs: 1000, tiltBlinkMs: 1000, tiltDeg: 90 }

// include/behavior.h for the firmware template: the contract's behavior field as #defines.
export function behaviorHeader(s: ContractSnapshot): string {
	const b = s.values.behavior ?? DEFAULT_BEHAVIOR
	return [
		"// Generated by Bringup from the design contract. Do not edit.",
		"#pragma once",
		"",
		`#define BEHAVIOR_BLINK_MS ${Math.round(b.blinkMs)}`,
		`#define BEHAVIOR_TILT_BLINK_MS ${Math.round(b.tiltBlinkMs)}`,
		`#define BEHAVIOR_TILT_DEG ${Math.round(b.tiltDeg)}`,
		"",
	].join("\n")
}

// include/model.h for the firmware template: the contract's model field as #defines. The template reserves the tensor
// arena in RAM and a weights placeholder in flash of these sizes, so `pio run` counts the model in the firmware's own
// RAM and flash, and a model that doesn't fit fails the link. A real model (model_data.cc) replaces the placeholder.
export function modelHeader(s: ContractSnapshot): string {
	const m = s.values.model
	const lines = ["// Generated by Bringup from the design contract. Do not edit.", "#pragma once", ""]
	if (!m) return [...lines, "#define MODEL_PRESENT 0", ""].join("\n")
	return [
		...lines,
		"#define MODEL_PRESENT 1",
		`// ${m.task.replace(/\s+/g, " ")}; ${m.runtime}, ${m.quantization}`,
		`#define MODEL_SENSOR_${m.sensor.toUpperCase()} 1`,
		`#define MODEL_SAMPLE_RATE_HZ ${Math.round(m.sampleRateHz)}`,
		`#define MODEL_WINDOW_MS ${Math.round(m.windowMs)}`,
		`#define MODEL_CHANNELS ${Math.round(m.channels)}`,
		`#define MODEL_WINDOW_SAMPLES ${Math.round((m.sampleRateHz * m.windowMs) / 1000)}`,
		`#define MODEL_ARENA_BYTES ${Math.round(m.arenaKb * 1024)}`,
		`#define MODEL_WEIGHTS_BYTES ${Math.round(m.weightsKb * 1024)}`,
		`#define MODEL_INT8 ${m.quantization === "int8" ? 1 : 0}`,
		`#define MODEL_LISTEN_ALWAYS ${m.listening === "always" ? 1 : 0}`,
		...pathLines(s),
		"",
	].join("\n")
}

// The sensor path's hash, which the data-collection firmware stamps on every recording, and how it reads a microphone.
function pathLines(s: ContractSnapshot): string[] {
	const path = sensorPath(s)
	if (!path) return []
	const out = ["", `// Sensor path ${JSON.stringify(path)}`, `#define MODEL_PATH_HASH "${pathHash(path)}"`]
	if (path.capture) out.push(`#define MIC_SLOT_BITS ${path.capture.slotBits}`, `#define MIC_SAMPLE_BITS ${path.capture.sampleBits}`, `#define MIC_SHIFT ${path.capture.shift}`, `#define MIC_CHANNEL_LEFT ${path.capture.channel === "left" ? 1 : 0}`)
	return out
}


// include/connectivity.h: which radio code the product firmware compiles, how readings leave, and how often Wi-Fi
// uploads (in wakes of the duty cycle). Without a connectivity field: Bluetooth LE with its GATT service.
export function connectivityHeader(s: ContractSnapshot): string {
	const c = connectivityOf(s)
	const periodS = s.values.requirements?.dutyCycle?.periodS ?? DEFAULT_PERIOD_S
	const head = ["// Generated by Bringup from the contract's connectivity field. Do not edit.", "#pragma once"]
	// A chip without a radio (its profile's radio is empty): no radio code at all; readings stay on the device.
	const profile = mcuProfileOf(s.values.parts)
	if (profile && profile.radio.length === 0) return [...head, `// The ${profile.mpn} has no radio: readings stay in its history.`, "#define RADIO_NONE 1"].join("\n") + "\n"
	const lines = [...head, `#define RADIO_${c.radio.toUpperCase()} 1`]
	for (const r of c.report) lines.push(`#define REPORT_${r.toUpperCase()} 1`)
	if (c.radio === "wifi") {
		const every = Math.max(1, Math.round((c.uploadPeriodS ?? periodS) / periodS))
		lines.push(`#define UPLOAD_EVERY ${every}  // ${c.uploadPeriodS} s between uploads / ${periodS} s between readings`)
	}
	if (c.updates === "ota") lines.push("#define UPDATES_OTA 1")
	return lines.join("\n") + "\n"
}

// include/link.h: this board's links to other boards (docs/system.md), the messages that cross them, and the code
// main.cpp calls: linkBegin() at boot, linkSendReading() after each reading, linkPoll(ms) while it is awake. Both boards
// of a link get the same message struct from the same system definition; the frame carries its hash (linkframe.h), so
// a receiver drops a message built against another definition. A board with no links gets stubs that do nothing.
const C_TYPE = { u8: "uint8_t", u16: "uint16_t", i16: "int16_t", u32: "uint32_t", f32: "float" } as const
// How a sent "reading" field is filled from the reading, by its name; any other field is sent as 0.
const READING_FILL: Record<string, string> = { tempCx100: "(int16_t)lroundf(t * 100)", rhx100: "(uint16_t)lroundf(rh * 100)", tempC: "t", rh: "rh", ok: "ok ? 1 : 0" }
// How each field type goes into CBOR (linkcbor.h): unsigned and signed integers, floats as single precision.
const CBOR_PUT = { u8: "u", u16: "u", i16: "i", u32: "u", f32: "f" } as const
const PRINTF = { u8: ["%u", "(unsigned)"], u16: ["%u", "(unsigned)"], i16: ["%d", "(int)"], u32: ["%lu", "(unsigned long)"], f32: ["%.2f", "(double)"] } as const

// ESP-IDF's TWAI timing macros (driver/twai.h) for each CAN bit rate the spec allows (spec.ts CAN_BUS_MAX_M).
const CAN_TIMING: Record<number, string> = { 1000: "1MBITS", 800: "800KBITS", 500: "500KBITS", 250: "250KBITS", 125: "125KBITS", 50: "50KBITS", 20: "20KBITS", 10: "10KBITS" }

// Each CAN message as a DSDL definition (dsdl/bringup/<Name>.1.0.dsdl), so yakut or pycyphal decode the bus with this
// board's own definitions: the fields in the order they travel, sealed (a fixed size, the frame's 7 bytes at most).
const DSDL_TYPE = { u8: "uint8", u16: "uint16", i16: "int16", u32: "uint32", f32: "float32" } as const
export function dsdlFiles(s: ContractSnapshot): { path: string; text: string }[] {
	const seen = new Map<string, { path: string; text: string }>()
	for (const l of s.values.links ?? [])
		if (l.kind === "can")
			for (const m of l.messages ?? []) {
				const name = m.name.split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join("")
				seen.set(name, { path: `dsdl/bringup/${name}.1.0.dsdl`, text: [`# Generated by Bringup: message ${m.name} on Cyphal subject-ID ${cyphalSubject(m.hash)}, fields in the order they travel.`, ...m.fields.map((f) => `${DSDL_TYPE[f.type]} ${f.name}`), "@sealed", ""].join("\n") })
			}
	return [...seen.values()]
}

export function linkHeader(s: ContractSnapshot): string {
	const links = s.values.links ?? []
	const L = (id: string) => `LINK_${id.toUpperCase().replace(/[^A-Z0-9]/g, "_")}`
	const M = (name: string) => `MSG_${name.toUpperCase().replace(/[^A-Z0-9]/g, "_")}`
	const lines = ["// Generated by Bringup from the design contract. Do not edit.", "#pragma once", "#include <stdint.h>", "", `#define LINK_COUNT ${links.length}`]
	// STM32duino: a UART is a HardwareSerial made on its pins (the core picks the peripheral from its pin map), and Wire
	// takes its pins by setSDA/setSCL before begin(). The ESP32 code is as it always was.
	const stm = mcuProfileOf(s.values.parts)?.firmware.arch === "stm32"
	const ser = stm ? "LinkSerial" : "Serial1"
	// Only a link with its pins assigned gets code: the architect gives a UART its TX and RX (or an I2C link its bus) a
	// turn after its connector, and a firmware built in between failed on PIN_L1_TX (the rover, 14 Nov 2026). Until then
	// link-unwired tells the architect, and the link here is defines and a note.
	const signals = new Set((s.values.pins ?? []).map((p) => p.signal))
	const wired = (l: (typeof links)[number]) =>
		l.kind === "uart" ? signals.has(`${l.id}_TX`) && signals.has(`${l.id}_RX`) : l.kind === "can" ? signals.has(canSignals(l).tx) && signals.has(canSignals(l).rx) : signals.has("I2C_SDA") && signals.has("I2C_SCL")
	const live = links.filter(wired)
	const target = live.find((l) => l.kind === "i2c" && l.i2c?.role === "target")
	if (target) lines.push(`// This board is an I2C target: it joins the bus at its address instead of driving it.`, `#define LINK_I2C_TARGET 1`)
	const structs = new Map<string, NonNullable<(typeof links)[number]["messages"]>[number]>()
	for (const l of links) {
		lines.push("", `// ${l.id}: ${l.kind.toUpperCase()} to ${l.peer} on ${l.connector}${l.supply === "out" ? ", powering it" : l.supply === "in" ? ", powered by it" : ""}`, `#define ${L(l.id)}_PEER "${l.peer}"`)
		if (!wired(l)) lines.push(`// ${l.id} has no ${l.kind === "uart" ? "TX and RX" : l.kind === "can" ? "CAN TX and RX" : "SDA and SCL"} pins yet: its code is left out until the contract assigns them.`)
		if (l.kind === "can" && l.can) lines.push(`#define ${L(l.id)}_CAN 1`, `#define ${L(l.id)}_CAN_KBPS ${l.can.kbps}`, `#define ${L(l.id)}_CAN_NODE ${l.can.node ?? 1} // Cyphal/CAN node-ID, the source of this board's frames`)
		if (l.kind === "uart") lines.push(`#define ${L(l.id)}_UART 1`, `#define ${L(l.id)}_BAUD ${l.baud}`)
		if (l.kind === "i2c" && l.i2c) {
			lines.push(`#define ${L(l.id)}_I2C 1`, `#define ${L(l.id)}_I2C_KHZ ${l.i2c.khz}`, `#define ${L(l.id)}_I2C_${l.i2c.role === "controller" ? "CONTROLLER" : "TARGET"} 1`)
			if (l.i2c.address !== undefined) lines.push(`#define ${L(l.id)}_I2C_ADDRESS 0x${l.i2c.address.toString(16).padStart(2, "0")}`)
			if (l.i2c.peerAddress !== undefined) lines.push(`#define ${L(l.id)}_I2C_PEER_ADDRESS 0x${l.i2c.peerAddress.toString(16).padStart(2, "0")}`)
		}
		for (const m of l.messages ?? []) {
			lines.push(`#define ${M(m.name)}_HASH 0x${m.hash.slice(0, 8)}UL`)
			if (l.kind === "can") lines.push(`#define ${M(m.name)}_SUBJECT ${cyphalSubject(m.hash)} // Cyphal subject-ID`)
			structs.set(m.name, m)
		}
	}
	for (const m of structs.values()) lines.push("", `struct __attribute__((packed)) ${m.name}_msg {`, ...m.fields.map((f) => `\t${C_TYPE[f.type]} ${f.name};`), "};")
	// The code main.cpp calls, compiled only into the firmware.
	const uart = live.find((l) => l.kind === "uart")
	// A CAN link (ESP32 TWAI; the chip has one controller, so one CAN link): each message is one frame, its 29-bit
	// extended identifier the message's definition hash (so a frame names what it carries, as linkframe's hash does on
	// UART and I2C), its data the packed struct (8 bytes at most, the spec's check). STM32 bxCAN is not generated yet.
	const can = stm ? undefined : live.find((l) => l.kind === "can")
	// On an STM32 (bxCAN, the HAL's CAN driver: the profile's firmware flags enable HAL_CAN_MODULE_ENABLED), the same frames.
	const canStmLink = stm ? live.find((l) => l.kind === "can") : undefined
	const canStm = Boolean(canStmLink)
	// The reading goes out in each message named "reading", or "reading_<x>" (on a CAN bus each node's own: one frame
	// identifier per sender). A bus's segments share one controller: a message is sent once per bus, not per segment.
	const isReading = (name: string) => name === "reading" || name.startsWith("reading_")
	const sentOnBus = new Set<string>()
	const sends = live.flatMap((l) =>
		(l.messages ?? [])
			.filter((m) => m.dir === "send" && isReading(m.name))
			.filter((m) => {
				if (l.kind !== "can") return true
				const key = `${canName(l)}:${m.hash}`
				if (sentOnBus.has(key)) return false
				sentOnBus.add(key)
				return true
			})
			.map((m) => ({ l, m })),
	)
	// A Cyphal frame names its message by its subject-ID: the link it belongs to is the one that defines it (a bus's
	// segments all hear every frame). Its payload is the frame's data less the tail byte.
	const canReceives = live.filter((l) => l.kind === "can").flatMap((l) => (l.messages ?? []).filter((m) => m.dir === "receive").map((m) => ({ l, m })))
	const receives = live.flatMap((l) => (l.messages ?? []).filter((m) => m.dir === "receive").map((m) => ({ l, m })))
	const body: string[] = ["", "#ifdef ARDUINO", "#include <Wire.h>", "#include \"linkframe.h\"", "#include \"linkcbor.h\"", "#include \"linkcyphal.h\""]
	// On UART and I2C a message's payload is CBOR (linkcbor.h, RFC 8949): a map of its field names to their values. A CAN
	// frame keeps the packed struct (8 bytes; CBOR's field names wouldn't fit).
	const cborMsgs = [...new Map(links.filter((l) => l.kind !== "can").flatMap((l) => l.messages ?? []).map((m) => [m.name, m])).values()]
	for (const m of cborMsgs) {
		body.push(`static inline uint8_t ${m.name}_to_cbor(const ${m.name}_msg &m, uint8_t *p) {`, `\tLinkCborWriter w(p, LINK_MAX_PAYLOAD);`, `\tw.map(${m.fields.length});`)
		for (const f of m.fields) body.push(`\tw.key("${f.name}");`, `\tw.${CBOR_PUT[f.type]}(m.${f.name});`)
		body.push(`\treturn w.ok ? w.n : 0;`, `}`)
		body.push(`static inline bool ${m.name}_from_cbor(const uint8_t *p, uint8_t len, ${m.name}_msg &m) {`, `\tdouble v;`)
		for (const f of m.fields) body.push(`\tif (!linkCborNumber(p, len, "${f.name}", v)) return false;`, `\tm.${f.name} = (${C_TYPE[f.type]})v;`)
		body.push(`\treturn true;`, `}`)
	}
	if (can) body.push("#include \"driver/twai.h\"")
	if (canStmLink) body.push(
		"#ifndef HAL_CAN_MODULE_ENABLED",
		"#error \"Bringup: this STM32's firmware flags don't enable HAL_CAN_MODULE_ENABLED (catalog/mcu: a profile with bxCAN lists it)\"",
		"#endif",
		"static CAN_HandleTypeDef linkCan;",
	)
	// A CAN frame's identifier holds 29 of the hash's 32 bits: every link on this board compares those.
	body.push(`#define LINK_HASH_MASK 0xFFFFFFFFUL`)
	if (receives.length) {
		body.push("static void linkReceived(const char *link, uint32_t hash, const uint8_t *p, uint8_t len) {")
		for (const { l, m } of receives) {
			const fmt = m.fields.map((f) => `${f.name}=${PRINTF[f.type][0]}`).join(" ")
			const args = m.fields.map((f) => `, ${PRINTF[f.type][1]}x.${f.name}`).join("")
			const match = `(hash & LINK_HASH_MASK) == (${M(m.name)}_HASH & LINK_HASH_MASK)`
			if (l.kind === "can") body.push(`\tif (${match} && len == sizeof(${m.name}_msg)) {`, `\t\t${m.name}_msg x;`, `\t\tmemcpy(&x, p, sizeof x);`)
			// The hash names the message: a payload that doesn't carry its fields is dropped, and said so.
			else body.push(`\tif (${match}) {`, `\t\t${m.name}_msg x;`, `\t\tif (!${m.name}_from_cbor(p, len, x)) {`, `\t\t\tLog.printf("LINK %s ${m.name}: the payload isn't a CBOR map with its fields, dropped\\n", link);`, `\t\t\treturn;`, `\t\t}`)
			body.push(`\t\tLog.printf("LINK %s ${m.name} from ${l.peer}: ${fmt}\\n", link${args});`, `\t\treturn;`, "\t}")
		}
		body.push(`\tLog.printf("LINK %s: a frame with an unknown definition (hash %08lx), dropped\\n", link, (unsigned long)hash);`, "}")
		// A CAN frame: a Cyphal single-frame message transfer whose subject-ID names the message (linkcyphal.h).
		if (canReceives.length)
			body.push(
				"static void linkCanReceived(uint32_t id, const uint8_t *d, uint8_t len) {",
				"\tuint16_t subject;",
				"\tuint8_t node;",
				"\tif (!linkCyphalMessage(id, d, len, subject, node)) return;",
				...canReceives.flatMap(({ l, m }) => [`\tif (subject == ${M(m.name)}_SUBJECT) {`, `\t\tlinkReceived("${l.id}", ${M(m.name)}_HASH, d, (uint8_t)(len - 1));`, `\t\treturn;`, `\t}`]),
				`\tLog.printf("LINK CAN: subject %u from node %u is not one of ours, dropped\\n", (unsigned)subject, (unsigned)node);`,
				"}",
			)
	}
	if (target) body.push(`static LinkFrameReader linkTargetReader;`, `static volatile bool linkTargetGot = false;`, `static uint8_t linkTargetFrame[LINK_MAX_PAYLOAD];`, `static uint8_t linkTargetLen = 0;`, `static uint32_t linkTargetHash = 0;`, `// Runs in the I2C driver's context: keep the frame for linkPoll().`, `static void linkOnReceive(int) {`, `\tconst uint8_t *p;`, `\tuint8_t len;`, `\tuint32_t hash;`, `\twhile (Wire.available()) if (linkTargetReader.feed((uint8_t)Wire.read(), hash, p, len) && !linkTargetGot) {`, `\t\tmemcpy(linkTargetFrame, p, len);`, `\t\tlinkTargetLen = len;`, `\t\tlinkTargetHash = hash;`, `\t\tlinkTargetGot = true;`, `\t}`, `}`)
	// An I2C target can't start a transfer: what it sends waits in one frame, which the controller reads (onRequest).
	// It is handed over once and then cleared, so the controller never hears the same reading twice; an empty answer is
	// one 0x00 byte, which the controller's reader skips.
	const targetSends = target && sends.some((x) => x.l.id === target.id)
	if (targetSends)
		body.push(
			`static uint8_t linkReplyFrame[LINK_FRAME_MAX];`,
			`static volatile uint8_t linkReplyLen = 0;`,
			`struct LinkBufferOut : public Print {`,
			`	uint8_t buf[LINK_FRAME_MAX];`,
			`	uint8_t n = 0;`,
			`	size_t write(uint8_t c) override { if (n < sizeof buf) buf[n++] = c; return 1; }`,
			`};`,
			`static void linkOnRequest() {`,
			`	if (linkReplyLen) {`,
			`		Wire.write(linkReplyFrame, linkReplyLen);`,
			`		linkReplyLen = 0;`,
			`	} else Wire.write((uint8_t)0);`,
			`}`,
		)
	// One read per target that sends (a target sends one message per link; the spec check says so).
	const i2cIns = receives.filter((r, i) => r.l.kind === "i2c" && r.l.i2c?.role === "controller" && receives.findIndex((x) => x.l.id === r.l.id) === i)
	for (const { l } of i2cIns) body.push(`static LinkFrameReader linkI2cReader_${l.id};`, `static uint32_t linkI2cLastRead_${l.id} = 0;`)
	if (uart) body.push(`static LinkFrameReader linkUartReader;`)
	if (uart && stm) body.push(`static HardwareSerial LinkSerial(${macroName(`${uart.id}_RX`)}, ${macroName(`${uart.id}_TX`)});`)
	body.push("static void linkBegin() {")
	if (uart) body.push(stm ? `\tLinkSerial.begin(${L(uart.id)}_BAUD, SERIAL_8N1);` : `\tSerial1.begin(${L(uart.id)}_BAUD, SERIAL_8N1, ${macroName(`${uart.id}_RX`)}, ${macroName(`${uart.id}_TX`)});`)
	if (can) {
		const timing = CAN_TIMING[can.can!.kbps]
		body.push(
			`\ttwai_general_config_t g = TWAI_GENERAL_CONFIG_DEFAULT((gpio_num_t)${macroName(canSignals(can).tx)}, (gpio_num_t)${macroName(canSignals(can).rx)}, TWAI_MODE_NORMAL);`,
			`\ttwai_timing_config_t tc = TWAI_TIMING_CONFIG_${timing}();`,
			`\ttwai_filter_config_t f = TWAI_FILTER_CONFIG_ACCEPT_ALL();`,
			`\tif (twai_driver_install(&g, &tc, &f) != ESP_OK || twai_start() != ESP_OK) Log.println("LINK ${can.id}: the CAN controller didn't start");`,
		)
	}
	if (canStmLink) {
		const id = canStmLink.id
		body.push(
			// The pins and the controller from the core's pin map (it applies an STM32F1's AFIO remap for PB8/PB9).
			`\tconst PinName rx = digitalPinToPinName(${macroName(canSignals(canStmLink).rx)}), tx = digitalPinToPinName(${macroName(canSignals(canStmLink).tx)});`,
			`\tlinkCan.Instance = (CAN_TypeDef *)pinmap_peripheral(rx, PinMap_CAN_RD);`,
			`\t__HAL_RCC_CAN1_CLK_ENABLE();`,
			`\tpinmap_pinout(rx, PinMap_CAN_RD);`,
			`\tpinmap_pinout(tx, PinMap_CAN_TD);`,
			// Bit timing from the bus clock at run time: N time quanta a bit (8..25), sampled at about 87.5 %.
			`\tconst uint32_t pclk = HAL_RCC_GetPCLK1Freq(), bps = ${L(id)}_CAN_KBPS * 1000UL;`,
			`\tuint32_t n = 0;`,
			`\tfor (uint32_t q = 25; q >= 8 && !n; q--) if (pclk % (bps * q) == 0) { const uint32_t b1 = (q * 7 + 4) / 8 - 1; if (b1 <= 16 && q - 1 - b1 <= 8 && q - 1 - b1 >= 1) n = q; }`,
			`\tif (!n) Log.println("LINK ${id}: no CAN bit timing for this bus clock");`,
			`\telse {`,
			`\tconst uint32_t bs1 = (n * 7 + 4) / 8 - 1, bs2 = n - 1 - bs1;`,
			`\tlinkCan.Init.Prescaler = pclk / (bps * n);`,
			`\tlinkCan.Init.Mode = CAN_MODE_NORMAL;`,
			`\tlinkCan.Init.SyncJumpWidth = CAN_SJW_1TQ;`,
			`\tlinkCan.Init.TimeSeg1 = (bs1 - 1) << CAN_BTR_TS1_Pos;`,
			`\tlinkCan.Init.TimeSeg2 = (bs2 - 1) << CAN_BTR_TS2_Pos;`,
			`\tlinkCan.Init.TimeTriggeredMode = DISABLE;`,
			`\tlinkCan.Init.AutoBusOff = ENABLE;`,
			`\tlinkCan.Init.AutoWakeUp = DISABLE;`,
			`\tlinkCan.Init.AutoRetransmission = ENABLE;`,
			`\tlinkCan.Init.ReceiveFifoLocked = DISABLE;`,
			`\tlinkCan.Init.TransmitFifoPriority = DISABLE;`,
			// Every frame into FIFO 0: the definition hash in each frame's identifier says what it is (linkReceived).
			`\tCAN_FilterTypeDef flt = {};`,
			`\tflt.FilterBank = 0;`,
			`\tflt.FilterMode = CAN_FILTERMODE_IDMASK;`,
			`\tflt.FilterScale = CAN_FILTERSCALE_32BIT;`,
			`\tflt.FilterFIFOAssignment = CAN_RX_FIFO0;`,
			`\tflt.FilterActivation = ENABLE;`,
			`\tflt.SlaveStartFilterBank = 14;`,
			`\tif (HAL_CAN_Init(&linkCan) != HAL_OK || HAL_CAN_ConfigFilter(&linkCan, &flt) != HAL_OK || HAL_CAN_Start(&linkCan) != HAL_OK) Log.println("LINK ${id}: the CAN controller didn't start");`,
			`\t}`,
		)
	}
	if (targetSends) body.push(`\tWire.onRequest(linkOnRequest);`)
	if (target && stm) body.push(`\tWire.onReceive(linkOnReceive);`, `\tWire.setSDA(PIN_I2C_SDA);`, `\tWire.setSCL(PIN_I2C_SCL);`, `\tWire.begin((uint8_t)${L(target.id)}_I2C_ADDRESS);`, `\tWire.setClock(${L(target.id)}_I2C_KHZ * 1000UL);`)
	else if (target) body.push(`\tWire.onReceive(linkOnReceive);`, `\tWire.begin((uint8_t)${L(target.id)}_I2C_ADDRESS, PIN_I2C_SDA, PIN_I2C_SCL, ${L(target.id)}_I2C_KHZ * 1000UL);`)
	body.push("}", "static void linkSendReading(bool ok, float t, float rh) {", "\t(void)ok;", "\t(void)t;", "\t(void)rh;")
	for (const { l, m } of sends) {
		// A failed reading goes out only in a message that can say so (an ok field); otherwise it isn't sent.
		body.push(m.fields.some((f) => f.name === "ok") ? `\t{` : `\tif (ok) {`, `\t\t${m.name}_msg m = {};`, ...m.fields.map((f) => `\t\tm.${f.name} = ${READING_FILL[f.name] ?? "0"};${READING_FILL[f.name] ? "" : " // not a reading field: sent as 0"}`))
		if (l.kind !== "can") body.push(`\t\tuint8_t pl[LINK_MAX_PAYLOAD];`, `\t\tconst uint8_t plen = ${m.name}_to_cbor(m, pl);`)
		// Cyphal/CAN: the fields, then the tail byte with this message's transfer-ID, counting up mod 32.
		if (l.kind === "can") body.push(`\t\tstatic uint8_t tid = 0;`, `\t\tuint8_t cf[8];`, `\t\tmemcpy(cf, &m, sizeof m);`, `\t\tcf[sizeof m] = linkCyphalTail(tid++);`)
		if (l.kind === "uart") body.push(`\t\tlinkFrameWrite(${ser}, ${M(m.name)}_HASH, pl, plen);`, `\t\t${ser}.flush();`)
		else if (l.kind === "can" && stm) body.push(`\t\tCAN_TxHeaderTypeDef h = {};`, `\t\th.ExtId = linkCyphalId(LINK_CYPHAL_PRIORITY_NOMINAL, ${M(m.name)}_SUBJECT, ${L(l.id)}_CAN_NODE);`, `\t\th.IDE = CAN_ID_EXT;`, `\t\th.RTR = CAN_RTR_DATA;`, `\t\th.DLC = sizeof m + 1;`, `\t\tuint32_t mailbox;`, `\t\tif (HAL_CAN_AddTxMessage(&linkCan, &h, cf, &mailbox) != HAL_OK) Log.println("LINK ${l.id}: no CAN frame sent (no free mailbox, or bus off)");`)
		else if (l.kind === "can") body.push(`\t\ttwai_message_t f = {};`, `\t\tf.extd = 1;`, `\t\tf.identifier = linkCyphalId(LINK_CYPHAL_PRIORITY_NOMINAL, ${M(m.name)}_SUBJECT, ${L(l.id)}_CAN_NODE);`, `\t\tf.data_length_code = sizeof m + 1;`, `\t\tmemcpy(f.data, cf, sizeof m + 1);`, `\t\tif (twai_transmit(&f, pdMS_TO_TICKS(20)) != ESP_OK) Log.println("LINK ${l.id}: no CAN frame sent (bus off, or nobody acknowledged)");`)
		else if (l.i2c?.role === "target") body.push(`\t\tLinkBufferOut out;`, `\t\tlinkFrameWrite(out, ${M(m.name)}_HASH, pl, plen);`, `\t\tlinkReplyLen = 0;`, `\t\tmemcpy(linkReplyFrame, out.buf, out.n);`, `\t\t__atomic_store_n(&linkReplyLen, out.n, __ATOMIC_RELEASE); // last, and after the copy: the request handler sees a whole frame or none`)
		else body.push(`\t\tWire.beginTransmission((uint8_t)${L(l.id)}_I2C_PEER_ADDRESS);`, `\t\tlinkFrameWrite(Wire, ${M(m.name)}_HASH, pl, plen);`, `\t\tconst uint8_t err = Wire.endTransmission();`, `\t\tif (err) Log.printf("LINK ${l.id}: ${l.peer} didn't answer at 0x%02x (%u)\\n", ${L(l.id)}_I2C_PEER_ADDRESS, err);`)
		body.push(`\t\tLog.println("LINK ${l.id} sent ${m.name}");`, `\t}`)
	}
	body.push("}", "// Listens for ms milliseconds (a board that receives nothing just waits).", "static void linkPoll(uint32_t ms) {")
	if (!receives.length) body.push("\tdelay(ms);")
	else {
		body.push("\tconst uint32_t start = millis();", "\tdo {")
		const uartIn = receives.find((r) => r.l.kind === "uart")
		if (uartIn) body.push(`\t\tconst uint8_t *p;`, `\t\tuint8_t len;`, `\t\tuint32_t hash;`, `\t\twhile (${ser}.available()) if (linkUartReader.feed((uint8_t)${ser}.read(), hash, p, len)) linkReceived("${uartIn.l.id}", hash, p, len);`)
		// The controller reads the target's frame, at most every 200 ms: the target answers once per frame.
		for (const i2cIn of i2cIns)
			body.push(
				`\t\tif (millis() - linkI2cLastRead_${i2cIn.l.id} >= 200) {`,
				`\t\t\tlinkI2cLastRead_${i2cIn.l.id} = millis();`,
				`\t\t\tconst uint8_t *ip;`,
				`\t\t\tuint8_t ilen;`,
				`\t\t\tuint32_t ihash;`,
				// Each reply stands alone: start the reader fresh, and ask for the largest frame, so a target built against a
				// longer definition is still read whole and reported as unknown, never cut short and lost.
				`\t\t\tlinkI2cReader_${i2cIn.l.id}.n = 0;`,
				`\t\t\tWire.requestFrom((uint8_t)${L(i2cIn.l.id)}_I2C_PEER_ADDRESS, (uint8_t)(LINK_FRAME_MAX));`,
				`\t\t\twhile (Wire.available()) if (linkI2cReader_${i2cIn.l.id}.feed((uint8_t)Wire.read(), ihash, ip, ilen)) linkReceived("${i2cIn.l.id}", ihash, ip, ilen);`,
				`\t\t}`,
			)
		const canIn = receives.find((r) => r.l.kind === "can")
		if (canStm && canIn) body.push(`\t\tCAN_RxHeaderTypeDef rh;`, `\t\tuint8_t rd[8];`, `\t\twhile (HAL_CAN_GetRxFifoFillLevel(&linkCan, CAN_RX_FIFO0) && HAL_CAN_GetRxMessage(&linkCan, CAN_RX_FIFO0, &rh, rd) == HAL_OK) if (rh.IDE == CAN_ID_EXT && rh.RTR == CAN_RTR_DATA) linkCanReceived(rh.ExtId, rd, (uint8_t)rh.DLC);`)
		if (can && canIn) body.push(`\t\ttwai_message_t f;`, `\t\twhile (twai_receive(&f, 0) == ESP_OK) if (f.extd && !f.rtr) linkCanReceived(f.identifier, f.data, f.data_length_code);`)
		if (target) body.push(`\t\tif (linkTargetGot) {`, `\t\t\tlinkReceived("${target.id}", linkTargetHash, linkTargetFrame, linkTargetLen);`, `\t\t\tlinkTargetGot = false;`, `\t\t}`)
		body.push("\t\tdelay(5);", "\t} while (millis() - start < ms);")
	}
	body.push("}", "#endif")
	return [...lines, ...body, ""].join("\n")
}
