// A `static const uint32_t NAME = N;` of the firmware template (templates/fw/src/main.cpp), so what the reviewer and the
// battery check are told about the firmware is read from the firmware itself. NaN if it is not there.
export function templateConstant(name: string): number {
	const main = readFileSync(resolve(import.meta.dirname, "../../templates/fw/src/main.cpp"), "utf8")
	return Number(new RegExp(`static const uint32_t ${name} = (\\d+)`).exec(main)?.[1] ?? NaN)
}

// The product firmware's wake (templates/fw): the reading (sensor, flash write, LED blink) takes about BLE_READING_MS,
// then it advertises over BLE for the rest of the contract's activeMs, never less than BLE_MIN_ADVERTISE_MS.
export const BLE_READING_MS = 30
export const BLE_MIN_ADVERTISE_MS = 50

export function bleAdvertiseMs(d: DutyCycle): number {
	return Math.max(BLE_MIN_ADVERTISE_MS, Math.round(d.activeMs - BLE_READING_MS))
}

export function macroName(signal: string): string {
	return `PIN_${signal.toUpperCase().replace(/[^A-Z0-9]/g, "_")}`
}

// The template's LittleFS partition: "spiffs" in Arduino-ESP32's default.csv (0x290000, 0x160000 bytes). A tenth is
// left for LittleFS's own blocks; the rest holds 4-byte readings.
export const HISTORY_PARTITION_BYTES = 0x160000
export const HISTORY_CAPACITY_BYTES = Math.floor(HISTORY_PARTITION_BYTES * 0.9)
export const HISTORY_RECORD_BYTES = 4
export const DEFAULT_HISTORY_DAYS = 30
export const DEFAULT_PERIOD_S = 300

// The firmware template's driver for a temperature/humidity sensor part (templates/fw/src/main.cpp), or null.
export function sensorDriver(mpn: string): "SHT40" | "SHTC3" | null {
	if (/^SHTC3/i.test(mpn)) return "SHTC3"
	if (/^SHT4/i.test(mpn)) return "SHT40"
	return null
}

// include/pins.h for the firmware template: one #define per pin assignment, and the sensor driver the parts call for.
export function pinsHeader(s: ContractSnapshot): string {
	const lines = ["// Generated by Bringup from the design contract. Do not edit.", "#pragma once", ""]
	for (const p of s.values.pins ?? []) lines.push(`#define ${macroName(p.signal)} ${p.gpio}`)
	const sensor = (s.values.parts ?? []).find((p) => p.role === "sensor")
	const driver = sensor ? sensorDriver(sensor.mpn) : null
	if (driver) lines.push(`#define SENSOR_${driver} 1`)
	// The product firmware deep-sleeps this long between readings; without a duty cycle it keeps the template's default.
	const period = s.values.requirements?.dutyCycle?.periodS
	if (period !== undefined && period > 0) lines.push(`#define DUTY_PERIOD_S ${Math.round(period)}`)
	// How many days of readings the firmware keeps; without one it keeps the template's default.
	const days = s.values.requirements?.historyDays
	if (days !== undefined) lines.push(`#define HISTORY_DAYS ${days}`)
	const duty = s.values.requirements?.dutyCycle
	if (duty) lines.push(`#define BLE_ADVERTISE_MS ${bleAdvertiseMs(duty)}`)
	// The VBUS-sense pin the board generator wired (codegen/circuit.ts usbWake): the firmware stays awake while it is high.
	const wake = usbWake(s)
	if (wake?.gpio != null) lines.push(`#define PIN_USB_SENSE ${wake.gpio}`)
	lines.push(`#define BRINGUP_REVISION ${s.revision}`, "")
	return lines.join("\n")
}

// The sensor driver a header selects, so checks run against what was compiled.
export function parseSensorHeader(text: string): string | null {
	return /^#define SENSOR_(\w+) 1\s*$/m.exec(text)?.[1] ?? null
}

// Reads the pins back out of a header, so checks run against what was compiled.
export function parsePinsHeader(text: string): Record<string, number> {
	const pins: Record<string, number> = {}
	for (const m of text.matchAll(/^#define PIN_(\w+) (-?\d+)\s*$/gm)) pins[m[1]] = Number(m[2])
	// The rover's hw_pins.h (src/mechanics/firmware.ts) names its pins after the contract's signals directly.
	for (const m of text.matchAll(/^#define (MOT_[AB]IN[12]|I2C_SDA|I2C_SCL) (-?\d+)\s*$/gm)) pins[m[1]] = Number(m[2])
	return pins
}

// Without a behavior field the LED blinks at 1 Hz and tilt changes nothing (90° is never exceeded).
export const DEFAULT_BEHAVIOR = { blinkMs: 1000, tiltBlinkMs: 1000, tiltDeg: 90 }

// include/behavior.h for the firmware template: the contract's behavior field as #defines.
export function behaviorHeader(s: ContractSnapshot): string {
	const b = s.values.behavior ?? DEFAULT_BEHAVIOR
	return [
		"// Generated by Bringup from the design contract. Do not edit.",
		"#pragma once",
		"",
		`#define BEHAVIOR_BLINK_MS ${Math.round(b.blinkMs)}`,
		`#define BEHAVIOR_TILT_BLINK_MS ${Math.round(b.tiltBlinkMs)}`,
		`#define BEHAVIOR_TILT_DEG ${Math.round(b.tiltDeg)}`,
		"",
	].join("\n")
}

// include/model.h for the firmware template: the contract's model field as #defines. The template reserves the tensor
// arena in RAM and a weights placeholder in flash of these sizes, so `pio run` counts the model in the firmware's own
// RAM and flash, and a model that doesn't fit fails the link. A real model (model_data.cc) replaces the placeholder.
export function modelHeader(s: ContractSnapshot): string {
	const m = s.values.model
	const lines = ["// Generated by Bringup from the design contract. Do not edit.", "#pragma once", ""]
	if (!m) return [...lines, "#define MODEL_PRESENT 0", ""].join("\n")
	return [
		...lines,
		"#define MODEL_PRESENT 1",
		`// ${m.task.replace(/\s+/g, " ")}; ${m.runtime}, ${m.quantization}`,
		`#define MODEL_SENSOR_${m.sensor.toUpperCase()} 1`,
		`#define MODEL_SAMPLE_RATE_HZ ${Math.round(m.sampleRateHz)}`,
		`#define MODEL_WINDOW_MS ${Math.round(m.windowMs)}`,
		`#define MODEL_CHANNELS ${Math.round(m.channels)}`,
		`#define MODEL_WINDOW_SAMPLES ${Math.round((m.sampleRateHz * m.windowMs) / 1000)}`,
		`#define MODEL_ARENA_BYTES ${Math.round(m.arenaKb * 1024)}`,
		`#define MODEL_WEIGHTS_BYTES ${Math.round(m.weightsKb * 1024)}`,
		`#define MODEL_INT8 ${m.quantization === "int8" ? 1 : 0}`,
		`#define MODEL_LISTEN_ALWAYS ${m.listening === "always" ? 1 : 0}`,
		...pathLines(s),
		"",
	].join("\n")
}

// The sensor path's hash, which the data-collection firmware stamps on every recording, and how it reads a microphone.
function pathLines(s: ContractSnapshot): string[] {
	const path = sensorPath(s)
	if (!path) return []
	const out = ["", `// Sensor path ${JSON.stringify(path)}`, `#define MODEL_PATH_HASH "${pathHash(path)}"`]
	if (path.capture) out.push(`#define MIC_SLOT_BITS ${path.capture.slotBits}`, `#define MIC_SAMPLE_BITS ${path.capture.sampleBits}`, `#define MIC_SHIFT ${path.capture.shift}`, `#define MIC_CHANNEL_LEFT ${path.capture.channel === "left" ? 1 : 0}`)
	return out
}


// include/connectivity.h: which radio code the product firmware compiles, how readings leave, and how often Wi-Fi
// uploads (in wakes of the duty cycle). Without a connectivity field: Bluetooth LE with its GATT service.
export function connectivityHeader(s: ContractSnapshot): string {
	const c = connectivityOf(s)
	const periodS = s.values.requirements?.dutyCycle?.periodS ?? DEFAULT_PERIOD_S
	const lines = ["// Generated by Bringup from the contract's connectivity field. Do not edit.", "#pragma once", `#define RADIO_${c.radio.toUpperCase()} 1`]
	for (const r of c.report) lines.push(`#define REPORT_${r.toUpperCase()} 1`)
	if (c.radio === "wifi") {
		const every = Math.max(1, Math.round((c.uploadPeriodS ?? periodS) / periodS))
		lines.push(`#define UPLOAD_EVERY ${every}  // ${c.uploadPeriodS} s between uploads / ${periodS} s between readings`)
	}
	if (c.updates === "ota") lines.push("#define UPDATES_OTA 1")
	return lines.join("\n") + "\n"
}

// include/link.h: this board's links to other boards (docs/system.md), the messages that cross them, and the code
// main.cpp calls: linkBegin() at boot, linkSendReading() after each reading, linkPoll(ms) while it is awake. Both boards
// of a link get the same message struct from the same system definition; the frame carries its hash (linkframe.h), so
// a receiver drops a message built against another definition. A board with no links gets stubs that do nothing.
const C_TYPE = { u8: "uint8_t", u16: "uint16_t", i16: "int16_t", u32: "uint32_t", f32: "float" } as const
// How a sent "reading" field is filled from the reading, by its name; any other field is sent as 0.
const READING_FILL: Record<string, string> = { tempCx100: "(int16_t)lroundf(t * 100)", rhx100: "(uint16_t)lroundf(rh * 100)", tempC: "t", rh: "rh", ok: "ok ? 1 : 0" }
const PRINTF = { u8: ["%u", "(unsigned)"], u16: ["%u", "(unsigned)"], i16: ["%d", "(int)"], u32: ["%lu", "(unsigned long)"], f32: ["%.2f", "(double)"] } as const

export function linkHeader(s: ContractSnapshot): string {
	const links = s.values.links ?? []
	const L = (id: string) => `LINK_${id.toUpperCase().replace(/[^A-Z0-9]/g, "_")}`
	const M = (name: string) => `MSG_${name.toUpperCase().replace(/[^A-Z0-9]/g, "_")}`
	const lines = ["// Generated by Bringup from the design contract. Do not edit.", "#pragma once", "#include <stdint.h>", "", `#define LINK_COUNT ${links.length}`]
	const target = links.find((l) => l.kind === "i2c" && l.i2c?.role === "target")
	if (target) lines.push(`// This board is an I2C target: it joins the bus at its address instead of driving it.`, `#define LINK_I2C_TARGET 1`)
	const structs = new Map<string, NonNullable<(typeof links)[number]["messages"]>[number]>()
	for (const l of links) {
		lines.push("", `// ${l.id}: ${l.kind.toUpperCase()} to ${l.peer} on ${l.connector}${l.supply === "out" ? ", powering it" : l.supply === "in" ? ", powered by it" : ""}`, `#define ${L(l.id)}_PEER "${l.peer}"`)
		if (l.kind === "uart") lines.push(`#define ${L(l.id)}_UART 1`, `#define ${L(l.id)}_BAUD ${l.baud}`)
		if (l.kind === "i2c" && l.i2c) {
			lines.push(`#define ${L(l.id)}_I2C 1`, `#define ${L(l.id)}_I2C_KHZ ${l.i2c.khz}`, `#define ${L(l.id)}_I2C_${l.i2c.role === "controller" ? "CONTROLLER" : "TARGET"} 1`)
			if (l.i2c.address !== undefined) lines.push(`#define ${L(l.id)}_I2C_ADDRESS 0x${l.i2c.address.toString(16).padStart(2, "0")}`)
			if (l.i2c.peerAddress !== undefined) lines.push(`#define ${L(l.id)}_I2C_PEER_ADDRESS 0x${l.i2c.peerAddress.toString(16).padStart(2, "0")}`)
		}
		for (const m of l.messages ?? []) {
			lines.push(`#define ${M(m.name)}_HASH 0x${m.hash.slice(0, 8)}UL`)
			structs.set(m.name, m)
		}
	}
	for (const m of structs.values()) lines.push("", `struct __attribute__((packed)) ${m.name}_msg {`, ...m.fields.map((f) => `\t${C_TYPE[f.type]} ${f.name};`), "};")
	// The code main.cpp calls, compiled only into the firmware.
	const uart = links.find((l) => l.kind === "uart")
	const sends = links.flatMap((l) => (l.messages ?? []).filter((m) => m.dir === "send" && m.name === "reading").map((m) => ({ l, m })))
	const receives = links.flatMap((l) => (l.messages ?? []).filter((m) => m.dir === "receive").map((m) => ({ l, m })))
	const body: string[] = ["", "#ifdef ARDUINO", "#include <Wire.h>", "#include \"linkframe.h\""]
	if (receives.length) {
		body.push("static void linkReceived(const char *link, uint32_t hash, const uint8_t *p, uint8_t len) {")
		for (const { l, m } of receives) {
			const fmt = m.fields.map((f) => `${f.name}=${PRINTF[f.type][0]}`).join(" ")
			const args = m.fields.map((f) => `, ${PRINTF[f.type][1]}x.${f.name}`).join("")
			body.push(`\tif (hash == ${M(m.name)}_HASH && len == sizeof(${m.name}_msg)) {`, `\t\t${m.name}_msg x;`, `\t\tmemcpy(&x, p, sizeof x);`, `\t\tSerial.printf("LINK %s ${m.name} from ${l.peer}: ${fmt}\\n", link${args});`, `\t\treturn;`, "\t}")
		}
		body.push(`\tSerial.printf("LINK %s: a frame with an unknown definition (hash %08lx), dropped\\n", link, (unsigned long)hash);`, "}")
	}
	if (target) body.push(`static LinkFrameReader linkTargetReader;`, `static volatile bool linkTargetGot = false;`, `static uint8_t linkTargetFrame[LINK_MAX_PAYLOAD];`, `static uint8_t linkTargetLen = 0;`, `static uint32_t linkTargetHash = 0;`, `// Runs in the I2C driver's context: keep the frame for linkPoll().`, `static void linkOnReceive(int) {`, `\tconst uint8_t *p;`, `\tuint8_t len;`, `\tuint32_t hash;`, `\twhile (Wire.available()) if (linkTargetReader.feed((uint8_t)Wire.read(), hash, p, len) && !linkTargetGot) {`, `\t\tmemcpy(linkTargetFrame, p, len);`, `\t\tlinkTargetLen = len;`, `\t\tlinkTargetHash = hash;`, `\t\tlinkTargetGot = true;`, `\t}`, `}`)
	// An I2C target can't start a transfer: what it sends waits in one frame, which the controller reads (onRequest).
	// It is handed over once and then cleared, so the controller never hears the same reading twice; an empty answer is
	// one 0x00 byte, which the controller's reader skips.
	const targetSends = target && sends.some((x) => x.l.id === target.id)
	if (targetSends)
		body.push(
			`static uint8_t linkReplyFrame[8 + LINK_MAX_PAYLOAD];`,
			`static volatile uint8_t linkReplyLen = 0;`,
			`struct LinkBufferOut : public Print {`,
			`	uint8_t buf[8 + LINK_MAX_PAYLOAD];`,
			`	uint8_t n = 0;`,
			`	size_t write(uint8_t c) override { if (n < sizeof buf) buf[n++] = c; return 1; }`,
			`};`,
			`static void linkOnRequest() {`,
			`	if (linkReplyLen) {`,
			`		Wire.write(linkReplyFrame, linkReplyLen);`,
			`		linkReplyLen = 0;`,
			`	} else Wire.write((uint8_t)0);`,
			`}`,
		)
	// One read per target that sends (a target sends one message per link; the spec check says so).
	const i2cIns = receives.filter((r, i) => r.l.kind === "i2c" && r.l.i2c?.role === "controller" && receives.findIndex((x) => x.l.id === r.l.id) === i)
	for (const { l } of i2cIns) body.push(`static LinkFrameReader linkI2cReader_${l.id};`, `static uint32_t linkI2cLastRead_${l.id} = 0;`)
	if (uart) body.push(`static LinkFrameReader linkUartReader;`)
	body.push("static void linkBegin() {")
	if (uart) body.push(`\tSerial1.begin(${L(uart.id)}_BAUD, SERIAL_8N1, PIN_${uart.id}_RX, PIN_${uart.id}_TX);`)
	if (targetSends) body.push(`\tWire.onRequest(linkOnRequest);`)
	if (target) body.push(`\tWire.onReceive(linkOnReceive);`, `\tWire.begin((uint8_t)${L(target.id)}_I2C_ADDRESS, PIN_I2C_SDA, PIN_I2C_SCL, ${L(target.id)}_I2C_KHZ * 1000UL);`)
	body.push("}", "static void linkSendReading(bool ok, float t, float rh) {", "\t(void)ok;", "\t(void)t;", "\t(void)rh;")
	for (const { l, m } of sends) {
		// A failed reading goes out only in a message that can say so (an ok field); otherwise it isn't sent.
		body.push(m.fields.some((f) => f.name === "ok") ? `\t{` : `\tif (ok) {`, `\t\t${m.name}_msg m = {};`, ...m.fields.map((f) => `\t\tm.${f.name} = ${READING_FILL[f.name] ?? "0"};${READING_FILL[f.name] ? "" : " // not a reading field: sent as 0"}`))
		if (l.kind === "uart") body.push(`\t\tlinkFrameWrite(Serial1, ${M(m.name)}_HASH, &m, sizeof m);`, `\t\tSerial1.flush();`)
		else if (l.i2c?.role === "target") body.push(`\t\tLinkBufferOut out;`, `\t\tlinkFrameWrite(out, ${M(m.name)}_HASH, &m, sizeof m);`, `\t\tlinkReplyLen = 0;`, `\t\tmemcpy(linkReplyFrame, out.buf, out.n);`, `\t\tlinkReplyLen = out.n; // last: the request handler sees a whole frame or none`)
		else body.push(`\t\tWire.beginTransmission((uint8_t)${L(l.id)}_I2C_PEER_ADDRESS);`, `\t\tlinkFrameWrite(Wire, ${M(m.name)}_HASH, &m, sizeof m);`, `\t\tconst uint8_t err = Wire.endTransmission();`, `\t\tif (err) Serial.printf("LINK ${l.id}: ${l.peer} didn't answer at 0x%02x (%u)\\n", ${L(l.id)}_I2C_PEER_ADDRESS, err);`)
		body.push(`\t\tSerial.println("LINK ${l.id} sent ${m.name}");`, `\t}`)
	}
	body.push("}", "// Listens for ms milliseconds (a board that receives nothing just waits).", "static void linkPoll(uint32_t ms) {")
	if (!receives.length) body.push("\tdelay(ms);")
	else {
		body.push("\tconst uint32_t start = millis();", "\tdo {")
		const uartIn = receives.find((r) => r.l.kind === "uart")
		if (uartIn) body.push(`\t\tconst uint8_t *p;`, `\t\tuint8_t len;`, `\t\tuint32_t hash;`, `\t\twhile (Serial1.available()) if (linkUartReader.feed((uint8_t)Serial1.read(), hash, p, len)) linkReceived("${uartIn.l.id}", hash, p, len);`)
		// The controller reads the target's frame, at most every 200 ms: the target answers once per frame.
		for (const i2cIn of i2cIns)
			body.push(
				`\t\tif (millis() - linkI2cLastRead_${i2cIn.l.id} >= 200) {`,
				`\t\t\tlinkI2cLastRead_${i2cIn.l.id} = millis();`,
				`\t\t\tconst uint8_t *ip;`,
				`\t\t\tuint8_t ilen;`,
				`\t\t\tuint32_t ihash;`,
				`\t\t\tWire.requestFrom((uint8_t)${L(i2cIn.l.id)}_I2C_PEER_ADDRESS, (uint8_t)(8 + sizeof(${i2cIn.m.name}_msg)));`,
				`\t\t\twhile (Wire.available()) if (linkI2cReader_${i2cIn.l.id}.feed((uint8_t)Wire.read(), ihash, ip, ilen)) linkReceived("${i2cIn.l.id}", ihash, ip, ilen);`,
				`\t\t}`,
			)
		if (target) body.push(`\t\tif (linkTargetGot) {`, `\t\t\tlinkReceived("${target.id}", linkTargetHash, linkTargetFrame, linkTargetLen);`, `\t\t\tlinkTargetGot = false;`, `\t\t}`)
		body.push("\t\tdelay(5);", "\t} while (millis() - start < ms);")
	}
	body.push("}", "#endif")
	return [...lines, ...body, ""].join("\n")
}
