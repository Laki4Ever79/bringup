import type { ContractSnapshot } from "../contract/types.ts"
import { connectivityOf } from "../contract/connectivity.ts"
import { DEFAULT_PERIOD_S } from "./firmware.ts"

// The device's data format: one source for the firmware (include/dataformat.h, which main.cpp and record.h read) and
// for whatever reads the device (the generated Python reader, reader/bringup_reader.py). Before, the record layout
// and the GATT UUIDs lived only in main.cpp, so a reader had to copy them by hand and could drift.
export const DATA_FORMAT = {
	gatt: {
		service: "b7e10001-5c2e-4f1a-9d3b-6a8e2f40c0de",
		latest: "b7e10002-5c2e-4f1a-9d3b-6a8e2f40c0de",
		count: "b7e10003-5c2e-4f1a-9d3b-6a8e2f40c0de",
		offset: "b7e10004-5c2e-4f1a-9d3b-6a8e2f40c0de",
		history: "b7e10005-5c2e-4f1a-9d3b-6a8e2f40c0de",
		// Records per history read.
		chunk: 100,
	},
	// One reading in 4 bytes, little-endian: temperature in centi-degrees offset by +45 °C (the sensors' -45 °C floor)
	// in the high half, relative humidity in centi-percent in the low half.
	record: { bytes: 4, tempOffsetC: 45, tempScale: 100, rhScale: 100 },
	// The "latest" characteristic's two non-readings.
	latestSensorFailed: 0xffffffff,
	latestNoSensor: 0xfffffffe,
	mqtt: { prefix: "bringup", discovery: "homeassistant" },
} as const

const hex = (n: number) => `0x${n.toString(16).toUpperCase()}`

export function dataFormatHeader(): string {
	const g = DATA_FORMAT.gatt
	const r = DATA_FORMAT.record
	return [
		"// Generated by Bringup from src/codegen/data-format.ts, the one source of the device's data format; the",
		"// generated reader (reader/bringup_reader.py) is made from the same source. Do not edit.",
		"#pragma once",
		`#define DF_GATT_SERVICE "${g.service}"`,
		`#define DF_GATT_LATEST "${g.latest}"`,
		`#define DF_GATT_COUNT "${g.count}"`,
		`#define DF_GATT_OFFSET "${g.offset}"`,
		`#define DF_GATT_HISTORY "${g.history}"`,
		`#define DF_HISTORY_CHUNK ${g.chunk}`,
		`#define DF_RECORD_BYTES ${r.bytes}`,
		`#define DF_TEMP_OFFSET_C ${r.tempOffsetC}`,
		`#define DF_TEMP_SCALE ${r.tempScale}`,
		`#define DF_RH_SCALE ${r.rhScale}`,
		`#define DF_LATEST_SENSOR_FAILED ${hex(DATA_FORMAT.latestSensorFailed)}u`,
		`#define DF_LATEST_NO_SENSOR ${hex(DATA_FORMAT.latestNoSensor)}u`,
		`#define DF_MQTT_PREFIX "${DATA_FORMAT.mqtt.prefix}"`,
		`#define DF_MQTT_DISCOVERY "${DATA_FORMAT.mqtt.discovery}"`,
		"",
	].join("\n")
}

// A small Python reader for this design: decoding is plain Python; reading over Bluetooth needs bleak
// (pip install bleak); the MQTT batch is JSON any client hands it.
export function readerPython(s: ContractSnapshot): string {
	const g = DATA_FORMAT.gatt
	const r = DATA_FORMAT.record
	const c = connectivityOf(s)
	const periodS = s.values.requirements?.dutyCycle?.periodS ?? DEFAULT_PERIOD_S
	return `"""Reader for this Bringup design's data (revision ${s.revision}). Generated from the same source as the firmware's
include/dataformat.h (Bringup src/codegen/data-format.ts), so the two can't drift. Do not edit.

The device: radio ${c.radio}, reports ${c.report.join(", ")}${c.radio === "wifi" ? `, uploads every ${c.uploadPeriodS} s` : ""}; a reading every ${periodS} s.

    decode_record(record)            one 4-byte reading -> {"temperature_c", "humidity_pct"}
    decode_history(data)             a GATT history read (newest first) -> [reading, ...]
    decode_mqtt_batch(json_text)     an MQTT history batch (oldest first) -> [reading with "age_s", ...]
    await read_history(address)      every stored reading over Bluetooth LE (needs: pip install bleak)
"""

import json
import struct

GATT_SERVICE = "${g.service}"
GATT_LATEST = "${g.latest}"
GATT_COUNT = "${g.count}"
GATT_OFFSET = "${g.offset}"
GATT_HISTORY = "${g.history}"
HISTORY_CHUNK = ${g.chunk}
RECORD_BYTES = ${r.bytes}
TEMP_OFFSET_C = ${r.tempOffsetC}
TEMP_SCALE = ${r.tempScale}
RH_SCALE = ${r.rhScale}
LATEST_SENSOR_FAILED = ${hex(DATA_FORMAT.latestSensorFailed)}
LATEST_NO_SENSOR = ${hex(DATA_FORMAT.latestNoSensor)}
MQTT_PREFIX = "${DATA_FORMAT.mqtt.prefix}"
PERIOD_S = ${periodS}


def decode_record(record):
    """One packed reading; None for the latest characteristic's "sensor failed" and "no sensor"."""
    if record in (LATEST_SENSOR_FAILED, LATEST_NO_SENSOR):
        return None
    return {
        "temperature_c": round((record >> 16) / TEMP_SCALE - TEMP_OFFSET_C, 2),
        "humidity_pct": round((record & 0xFFFF) / RH_SCALE, 2),
    }


def decode_history(data):
    """A history characteristic read: little-endian records, newest first."""
    count = len(data) // RECORD_BYTES
    return [decode_record(r) for r in struct.unpack("<%dI" % count, data[: count * RECORD_BYTES])]


def decode_mqtt_batch(text):
    """The {"periodS", "records"} batch from MQTT_PREFIX/<id>/history: oldest first, each with its age in seconds."""
    batch = json.loads(text)
    period, records = batch["periodS"], batch["records"]
    out = []
    for i, record in enumerate(records):
        reading = decode_record(record)
        if reading is not None:
            reading["age_s"] = (len(records) - 1 - i) * period
        out.append(reading)
    return out


async def read_history(address):
    """Every stored reading, newest first, over Bluetooth LE (the device advertises for a moment after each reading)."""
    from bleak import BleakClient  # pip install bleak

    readings = []
    async with BleakClient(address) as client:
        count = struct.unpack("<I", await client.read_gatt_char(GATT_COUNT))[0]
        for offset in range(0, count, HISTORY_CHUNK):
            await client.write_gatt_char(GATT_OFFSET, struct.pack("<I", offset), response=True)
            readings += decode_history(await client.read_gatt_char(GATT_HISTORY))
    return readings
`
}
